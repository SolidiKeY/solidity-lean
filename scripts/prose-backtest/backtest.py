def git_blob_id(data):
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


# ---------------------------------------------------------------- git access
class Repo:
    def __init__(self, path):
        self.path = str(path)
        self._cat = None
        self._check = None
        self._exists = {}

    def run(self, *args):
        return subprocess.run(["git", "-C", self.path, *args], check=True,
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout

    def blob(self, sha):
        if self._cat is None:
            self._cat = subprocess.Popen(["git", "-C", self.path, "cat-file", "--batch"],
                                         stdin=subprocess.PIPE, stdout=subprocess.PIPE)
        self._cat.stdin.write(sha.encode() + b"\n")
        self._cat.stdin.flush()
        header = self._cat.stdout.readline().split()
        if len(header) < 3 or header[1] == b"missing":
            raise KeyError(sha)
        data = self._cat.stdout.read(int(header[2]))
        self._cat.stdout.read(1)
        return data

    def exists(self, commit, path):
        key = (commit, path)
        if key not in self._exists:
            if self._check is None:
                self._check = subprocess.Popen(
                    ["git", "-C", self.path, "cat-file", "--batch-check"],
                    stdin=subprocess.PIPE, stdout=subprocess.PIPE)
            self._check.stdin.write(f"{commit}:{path}\n".encode())
            self._check.stdin.flush()
            line = self._check.stdout.readline()
            self._exists[key] = b" blob " in line
        return self._exists[key]

    def tree(self, commit):
        """(mode, sha, path) for docs/, Solidity/, registry roots, checker and baseline."""
        out = self.run("ls-tree", "-r", "-z", "--full-tree", commit, "--", "docs", "Solidity",
                       *REGISTRY_ROOTS, CHECKER_PATH, BASELINE_PATH)
        entries = []
        for item in out.split(b"\0"):
            if item:
                meta, path = item.split(b"\t", 1)
                mode, kind, sha = meta.decode().split()
                entries.append((mode, kind, sha, path.decode("utf-8", "surrogateescape")))
        return entries

    def close(self):
        for proc in (self._cat, self._check):
            if proc:
                proc.stdin.close()
                proc.stdout.close()
                proc.wait()
        self._cat = self._check = None


def text_of(data):
    """Path.read_text(encoding='utf-8') semantics: strict UTF-8, universal newlines."""
    return data.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")


# ---------------------------------------------------------------- interval
def freeze_interval(repo, end, days):
    end = repo.run("rev-parse", "--verify", end + "^{commit}").decode().strip()
    shallow = repo.run("rev-parse", "--is-shallow-repository").decode().strip() == "true"
    rows = repo.run("rev-list", "--first-parent", "--format=%H %ct %P", end).decode().splitlines()
    chain = []
    for line in rows:
        if line.startswith("commit "):
            continue
        parts = line.split()
        chain.append((parts[0], int(parts[1]), parts[2:]))
    end_ts = chain[0][1]
    start_ts = end_ts - days * 86400
    selected, predecessor, out_of_order = [], None, []
    walking = True
    for sha, ts, parents in chain:
        if walking and ts >= start_ts:
            selected.append((sha, ts))
        elif walking:
            predecessor = (sha, ts)
            walking = False
        elif ts >= start_ts:
            out_of_order.append((sha, ts))
    # Exact filter: report (never silently drop) ancestors stamped after the end commit.
    outside = [s for s in selected if not start_ts <= s[1] <= end_ts]
    selected = [s for s in selected if start_ts <= s[1] <= end_ts]
    root_reached = predecessor is None
    return {
        "end": end, "end_committer_ts": end_ts, "days": days,
        "start_ts": start_ts, "interval": [start_ts, end_ts],
        "first_parent_commits": [s for s, _ in reversed(selected)],
        "commit_ts": {s: t for s, t in selected},
        "predecessor": predecessor[0] if predecessor else None,
        "predecessor_ts": predecessor[1] if predecessor else None,
        "first_parent_ancestors_total": len(chain),
        "shallow": shallow,
        "history_incomplete": shallow or root_reached,
        "out_of_order_after_boundary": [s for s, _ in out_of_order],
        "selected_outside_interval": [s for s, _ in outside],
    }


# ---------------------------------------------------------------- file analysis
def generated_claims(text, comment_spans, lean):
    """Return (header_generator_or_None, [(begin_line, end_line, generator)], problems)."""
    lines = text.split("\n")
    header = None
    limit = sum(len(x) + 1 for x in lines[:HEADER_LINES])
    for match in HEADER_MARK.finditer(text, 0, limit):
        line_no = text.count("\n", 0, match.start()) + 1
        if lean:
            ok = any(s <= match.start() < e and text.count("\n", 0, s) < HEADER_LINES
                     for s, e in comment_spans)
        else:
            ok = LINE_HEADER.match(lines[line_no - 1]) is not None
        if ok:
            path = GENERATOR.search(text, match.end(), match.end() + 300)
            header = path[1] if path else ""
            break
    blocks, problems, open_block = [], [], None
    for number, line in enumerate(lines, 1):
        if (begin := BLOCK_BEGIN.match(line)):
            if open_block:
                problems.append(f"nested BEGIN at line {number}")
            open_block = (number, begin[1])
        elif (end := BLOCK_END.match(line)):
            if open_block and open_block[1] == end[1]:
                blocks.append((open_block[0], number, open_block[1]))
            else:
                problems.append(f"unmatched END at line {number}")
            open_block = None
    if open_block:
        problems.append(f"unclosed BEGIN at line {open_block[0]}")
    return header, blocks, problems


def lean_lines(text):
    """Comment, docstring and code physical-line sets plus comment spans."""
    scanner = CHECK._Scanner(text)
    spans = []
    original = scanner.mark

    def mark(start, end, target):
        if target is scanner.comments and end > start:
            spans.append((start, end))
        original(start, end, target)

    scanner.mark = mark
    scanner.code()
    scanner.scanned = True
    del scanner.mark
    newlines = scanner.newlines
    code = set()
    pos = 0
    for start, end in sorted(spans) + [(len(text), len(text))]:
        if start > pos:
            # each physical line piece of the non-comment segment
            line = bisect_left(newlines, pos) + 1
            for piece in text[pos:start].split("\n"):
                if piece.strip():
                    code.add(line)
                line += 1
        pos = max(pos, end)
    return scanner, spans, code


class Analyzer:
    """Per-blob measurements, cached by blob identity (and registry slice for IDs)."""

    def __init__(self, repo):
        self.repo = repo
        self.cache = {}
        self.pid_cache = {}

    def file(self, sha, is_lean):
        key = (sha, is_lean)
        if key in self.cache:
            return self.cache[key]
        data = self.repo.blob(sha)
        try:
            text = text_of(data)
        except UnicodeDecodeError:
            info = {"error": "undecodable"}
            self.cache[key] = info
            return info
        info = {"physical": len(text.splitlines())}
        if is_lean:
            scanner, spans, code = lean_lines(text)
            info.update(comments=scanner.comments, docs=scanner.docs, code=code,
                        raw_pids=[bisect_left(scanner.newlines, m.start()) + 1
                                  for m in CHECK.PROCESS_ID.finditer(text)],
                        g_names=frozenset(n for n in _ID_DOTTED.findall(text) if _G_ID.search(n)))
            if info["raw_pids"]:
                info["text"] = text   # kept only where registry-dependent IDs need a rescan
        else:
            spans = []
        header, blocks, problems = generated_claims(text, spans, is_lean)
        info.update(header=header, blocks=blocks, block_problems=problems)
        if not is_lean:
            block_lines = set()
            for b, e, _ in blocks:
                block_lines.update(range(b, e + 1))
            info["block_line_count"] = len(block_lines & set(range(1, info["physical"] + 1)))
        self.cache[key] = info
        return info

    def process_ids(self, sha, info, modules):
        """Current (v3) semantics; result depends only on modules among G-bearing names."""
        if not info["raw_pids"]:
            return 0
        key = (sha, bool(modules), info["g_names"] & modules)
        if key not in self.pid_cache:
            scanner = CHECK._Scanner(info["text"])
            self.pid_cache[key] = CHECK.process_ids(info["text"], modules, scanner)
        return self.pid_cache[key]


def checker_version(blob_id, known):
    return known.get(blob_id)


def area_of(path):
    tree, _, rest = path.partition("/")
    parts = rest.split("/")
    return tree + "/" + (parts[0] if len(parts) > 1 else "_root")


def measure_commit(repo, analyzer, commit, estimate):
    """Legacy (historical semantics) and normalized counts for one commit."""
    entries = repo.tree(commit)
    byp = {p: (m, k, s) for m, k, s, p in entries}
    modules = set()
    for root in REGISTRY_ROOTS:
        if root in byp:
            try:
                for line in text_of(repo.blob(byp[root][2])).splitlines():
                    if token := CHECK._IMPORT.fullmatch(line):
                        modules.add(token[1])
            except UnicodeDecodeError:
                pass
    modules = frozenset(modules)
    legacy, legacy_v1_pids = {}, {}
    norm, code = {}, {}
    exclusions, unknown, unsupported = [], [], []
    has_docs = any(p.startswith("docs/") for p in byp)
    has_sol = any(p.startswith("Solidity/") for p in byp)
    legacy_error = None if has_docs and has_sol else "missing source directory"
    for mode, kind, sha, path in sorted(entries, key=lambda e: e[3]):
        tree = path.split("/", 1)[0]
        if tree not in ("docs", "Solidity") or "/" not in path:
            continue
        if kind != "blob" or mode not in ("100644", "100755"):
            unsupported.append({"path": path, "mode": mode, "kind": kind})
            continue
        is_lean = tree == "Solidity"
        if is_lean and not path.endswith(".lean"):
            continue
        area = area_of(path)
        lrow = legacy.setdefault(area, dict.fromkeys(METRICS, 0))
        nrow = norm.setdefault(area, dict.fromkeys(METRICS, 0))
        code.setdefault(area, 0)
        legacy_v1_pids.setdefault(area, 0)
        info = analyzer.file(sha, is_lean)
        if "error" in info:
            legacy_error = legacy_error or f"undecodable {path}"
            unknown.append({"path": path, "reason": "undecodable UTF-8; excluded from both sides"})
            continue
        # legacy: exactly the checker's per-file contributions
        if is_lean:
            lrow["comment_lines"] += len(info["comments"])
            lrow["docstring_lines"] += len(info["docs"])
            pids = analyzer.process_ids(sha, info, modules)
            lrow["process_ids"] += pids
            legacy_v1_pids[area] += len(info["raw_pids"])
        else:
            lrow["docs_lines"] += info["physical"]
        # normalized: generated exclusion on both prose and code
        header = info["header"]
        if header is not None:
            if header and repo.exists(commit, header):
                exclusions.append({"path": path, "rule": "header", "generator": header})
                continue
            unknown.append({"path": path, "reason": "generation claimed in header but no in-tree "
                            "generator path resolved; kept as handwritten",
                            "generator": header or None})
        good_blocks = []
        for b, e, gen in info["blocks"]:
            if repo.exists(commit, gen):
                good_blocks.append((b, e))
                exclusions.append({"path": path, "rule": "block", "lines": [b, e], "generator": gen})
            else:
                unknown.append({"path": path, "reason": "generated block without in-tree generator; kept",
                                "lines": [b, e], "generator": gen})
        for problem in info["block_problems"]:
            unknown.append({"path": path, "reason": "generated-block markers: " + problem})
        blocked = set()
        for b, e in good_blocks:
            blocked.update(range(b, e + 1))
        if is_lean:
            nrow["comment_lines"] += len(info["comments"] - blocked)
            nrow["docstring_lines"] += len(info["docs"] - blocked)
            nrow["process_ids"] += pids - sum(1 for line in info["raw_pids"] if line in blocked)
            code[area] += len(info["code"] - blocked)
        else:
            inside = len(blocked & set(range(1, info["physical"] + 1)))
            nrow["docs_lines"] += info["physical"] - inside
    return {
        "legacy": legacy, "legacy_v1_process_ids": legacy_v1_pids, "legacy_error": legacy_error,
        "normalized": norm, "code": code,
        "exclusions": exclusions, "unknown": unknown, "unsupported_entries": unsupported,
        "checker_blob": byp.get(CHECKER_PATH, (None, None, None))[2],
        "baseline_blob": byp.get(BASELINE_PATH, (None, None, None))[2],
        "registered_modules": len(modules),
    }


def denominator(area, codes, mapping):
    target = mapping.get(area)
    if target is None:
        target = "self" if area.startswith("Solidity/") else "repository-solidity"
    if target == "self":
        return codes.get(area, 0), "self"
    if target == "repository-solidity":
        return sum(v for a, v in codes.items() if a.startswith("Solidity/")), target
    return sum(codes.get(a, 0) for a in target), "+".join(target)


# ---------------------------------------------------------------- rules
def ratio_limit_ok(n, d, cal, margin):
    """Exact test n/d <= (1+margin) * cal_n/cal_d as n*cal_d*q <= cal_n*(p+q)*d."""
    p, q = margin.numerator, margin.denominator
    cn, cd = cal["numerator"], cal["denominator"]
    if cn == 0:
        return n == 0, "frozen zero numerator: only zero allowed"
    if cd == 0:
        return (n == 0), "calibration has prose but zero code: inapplicable, only zero allowed"
    if d == 0:
        return n == 0, "zero code denominator"
    return n * cd * q <= cn * (p + q) * d, None


def limit_value(d, cal, margin):
    """Largest integer numerator permitted at denominator d (floor), or None."""
    cn, cd = cal["numerator"], cal["denominator"]
    if cn == 0 or cd == 0 or d == 0:
        return 0
    return (cn * (margin.numerator + margin.denominator) * d) // (cd * margin.denominator)


def classify(n, d, pn, pd, rule, ratio_ok, reason=None):
    causes = []
    if reason and reason.startswith("unseen area"):
        causes.append("unseen_area")
    if reason in ("zero code denominator", "calibration has prose but zero code: inapplicable, only zero allowed"):
        causes.append("zero_code")
    if reason == "frozen zero numerator: only zero allowed":
        causes.append("prose_where_calibration_had_none")
    dn = None if pn is None else n - pn
    dd = None if pd is None else d - pd
    if dn is not None and dn > 0 and (dd is None or dd <= 0):
        causes.append("prose_rose_without_code")
    if dd is not None and dd < 0:
        causes.append("denominator_shrank")
    if dn is not None and dd is not None and dn > 0 and dd > 0:
        causes.append("code_rose_with_normal_prose" if ratio_ok else "code_and_prose_rose")
    if rule == "ratio" and not reason:
        causes.append("ratio_exceeded_frozen_allowance")
    if rule != "ratio" and not reason:
        causes.append("absolute_limit_exceeded")
    if rule == "legacy" and reason and reason.startswith("area absent"):
        causes.append("area_absent_from_baseline")
    if dn == 0 and dd == 0:
        causes.append("unchanged_counts")
    if dn is not None and dn < 0:
        causes.append("prose_fell_still_over")
    return causes or ["other_no_prior"]


def replay(args):
    repo = Repo(args.repo)
    estimate = json.loads(Path(args.estimate).read_text(encoding="utf-8"))
    frozen = freeze_interval(repo, args.end, args.days)
    end_checker = repo.tree(frozen["end"])
    end_checker = {p: s for _, _, s, p in end_checker}.get(CHECKER_PATH)
    local = git_blob_id(CHECKER_FILE.read_bytes())
    if local != end_checker or local != estimate["classifier"]["checker_blob"]:
        raise SystemExit(f"checker blob {local} differs from end commit {end_checker} "
                         f"or estimate {estimate['classifier']['checker_blob']}")
    margin = Fraction(estimate["margin"]["value"])
    sensitivity = [Fraction(x) for x in estimate["margin"]["sensitivity"]]
    cal = estimate["calibration"]
    mapping = estimate["denominator_mapping"]
    excluded = set(estimate["enforcement_exclusions"])
    known_versions = estimate["legacy_semantics"]["checker_versions"]
    analyzer = Analyzer(repo)
    commits = ([frozen["predecessor"]] if frozen["predecessor"] else []) + frozen["first_parent_commits"]
    rows, commit_rows, failures = [], [], []
    prev = None
    prev_codes = None
    prev_status = {}
    for index, commit in enumerate(commits):
        in_window = commit != frozen["predecessor"]
        m = measure_commit(repo, analyzer, commit, estimate)
        version = known_versions.get(m["checker_blob"]) if m["checker_blob"] else None
        baseline = None
        legacy_state = "evaluated"
        if m["checker_blob"] is None or m["baseline_blob"] is None:
            legacy_state = "checker_or_baseline_absent"
        elif version is None:
            legacy_state = "unsupported_checker_version"
        elif m["legacy_error"]:
            legacy_state = "checker_error:" + m["legacy_error"]
        else:
            baseline = json.loads(text_of(repo.blob(m["baseline_blob"])))
        codes = m["code"]
        areas = sorted(set(m["legacy"]) | set(cal) | set(baseline or {}))
        position = ("calibration" if commit == estimate["calibration_commit"] else
                    "before_calibration" if index < commits.index(estimate["calibration_commit"])
                    else "after_calibration") if estimate["calibration_commit"] in commits else "unknown"
        summary = {"commit": commit, "committer_ts": frozen["commit_ts"].get(commit, frozen["predecessor_ts"]),
                   "in_window": in_window, "position": position,
                   "legacy_state": legacy_state, "legacy_checker_version": version,
                   "baseline_blob": m["baseline_blob"], "checker_blob": m["checker_blob"],
                   "registered_modules": m["registered_modules"],
                   "excluded_generated": len(m["exclusions"]),
                   "excluded_generated_files": sum(1 for e in m["exclusions"] if e["rule"] == "header"),
                   "unknown_classifications": len(m["unknown"]),
                   "unsupported_entries": m["unsupported_entries"],
                   "fail": {"legacy": 0, "normalized_absolute": 0, "ratio": 0, "ratio_enforced": 0},
                   "unavailable": {"legacy": 0}}
        if index == 0 or args.full_details:
            summary["exclusions"] = m["exclusions"]
            summary["unknown"] = m["unknown"]
        else:
            summary["exclusions_digest"] = hashlib.sha256(json.dumps(m["exclusions"], sort_keys=True).encode()).hexdigest()
            summary["unknown"] = m["unknown"]
        current = {}
        for area in areas:
            lrow = m["legacy"].get(area, dict.fromkeys(METRICS, 0))
            nrow = m["normalized"].get(area, dict.fromkeys(METRICS, 0))
            d, dname = denominator(area, codes, mapping)
            for metric in METRICS:
                n = nrow[metric]
                lv = lrow[metric]
                c = cal.get(area, {}).get(metric)
                row = {"commit": commit, "area": area, "metric": metric,
                       "in_window": in_window, "position": position,
                       "legacy_numerator": lv, "numerator": n, "denominator": d,
                       "denominator_source": dname}
                p = prev.get((area, metric)) if prev else None
                if p is None and prev is not None:
                    # area absent at the prior commit: its prior counts are zero
                    p = {"numerator": 0, "legacy_numerator": 0,
                         "denominator": denominator(area, prev_codes, mapping)[0]}
                row["prior_numerator"] = p["numerator"] if p else None
                row["prior_denominator"] = p["denominator"] if p else None
                row["prior_legacy_numerator"] = p["legacy_numerator"] if p else None
                row["delta_numerator"] = None if p is None else n - p["numerator"]
                row["delta_denominator"] = None if p is None else d - p["denominator"]
                row["delta_legacy_numerator"] = None if p is None else lv - p["legacy_numerator"]
                results = {}
                # (a) faithful legacy
                if legacy_state != "evaluated":
                    results["legacy"] = ("unavailable", None, legacy_state)
                elif version == "v2" and metric == "process_ids":
                    results["legacy"] = ("unavailable", None, "unsupported semantic version v2 process_ids")
                else:
                    value = m["legacy_v1_process_ids"].get(area, 0) if (version == "v1" and metric == "process_ids") else lv
                    row["legacy_numerator"] = value
                    limit = baseline.get(area, {}).get(metric, 0)
                    results["legacy"] = ("pass" if value <= limit else "fail", limit,
                                         None if area in baseline else "area absent from baseline: zero allowance")
                # (b) normalized absolute vs frozen ratio, same classifier
                if c is None:
                    results["normalized_absolute"] = ("pass" if n == 0 else "fail", 0, "unseen area: zero allowance")
                    results["ratio"] = ("pass" if n == 0 else "fail", 0, "unseen area: cannot train own allowance")
                else:
                    results["normalized_absolute"] = ("pass" if n <= c["numerator"] else "fail", c["numerator"], None)
                    ok, why = ratio_limit_ok(n, d, c, margin)
                    results["ratio"] = ("pass" if ok else "fail", limit_value(d, c, margin), why)
                    row["sensitivity"] = {str(s): ratio_limit_ok(n, d, c, s)[0] for s in sensitivity}
                row["enforced_in_proposal"] = area not in excluded
                for rule, (status, limit, reason) in results.items():
                    row[rule] = {"status": status, "limit": limit, "reason": reason}
                rows.append(row)
                current[(area, metric)] = row
                if not in_window:
                    continue
                for rule, (status, limit, reason) in results.items():
                    if status == "unavailable":
                        summary["unavailable"]["legacy"] += 1
                        continue
                    if status != "fail":
                        continue
                    summary["fail"][rule] += 1
                    if rule == "ratio" and row["enforced_in_proposal"]:
                        summary["fail"]["ratio_enforced"] += 1
                    numerator = row["legacy_numerator"] if rule == "legacy" else n
                    prior_n = row["prior_legacy_numerator"] if rule == "legacy" else row["prior_numerator"]
                    prior_status = prev_status.get((rule, area, metric))
                    ratio_ok = results.get("ratio", ("pass",))[0] == "pass"
                    failures.append({
                        "rule": rule, "commit": commit, "area": area, "metric": metric,
                        "numerator": numerator, "denominator": d, "limit": limit,
                        "prior_numerator": prior_n, "prior_denominator": row["prior_denominator"],
                        "introduced": prior_status != "fail", "prior_status": prior_status,
                        "position": position,
                        "enforced_in_proposal": row["enforced_in_proposal"] if rule == "ratio" else None,
                        "reason": reason,
                        "causes": classify(numerator, d, prior_n, row["prior_denominator"], rule,
                                           ratio_ok, reason)})
        for (area, metric), row in current.items():
            for rule in ("legacy", "normalized_absolute", "ratio"):
                prev_status[(rule, area, metric)] = row[rule]["status"]
        prev = current
        prev_codes = codes
        commit_rows.append(summary)
        if args.progress:
            print(f"{index + 1}/{len(commits)} {commit[:12]}", file=sys.stderr)
    repo.close()
    window_commits = [c for c in commit_rows if c["in_window"]]

    def totals(rule, position=None):
        scope = [c for c in window_commits if position is None or c["position"] == position]
        names = {c["commit"] for c in scope}
        base = rule.replace("_enforced", "")
        picked = [f for f in failures if f["rule"] == base and f["commit"] in names
                  and (rule != "ratio_enforced" or f["enforced_in_proposal"])]
        return {"commits": len(scope),
                "failing_commits": len({f["commit"] for f in picked}),
                "failing_cells": len(picked),
                "introduced_cells": sum(1 for f in picked if f["introduced"]),
                "introduced_after_evaluable_prior": sum(1 for f in picked if f["prior_status"] == "pass")}
    positions = ("before_calibration", "calibration", "after_calibration")
    sens = {}
    for s in sensitivity:
        sens[str(s)] = {}
        for position in positions:
            bad = {r["commit"] for r in rows if r["in_window"] and r["position"] == position
                   and r["enforced_in_proposal"]
                   and (r.get("sensitivity", {}).get(str(s)) is False
                        or ("sensitivity" not in r and r["ratio"]["status"] == "fail"))}
            sens[str(s)][position] = len(bad)
    output = {
        "schema": SCHEMA, "frozen_inputs": frozen, "estimate": estimate,
        "totals": {"commits_in_window": len(window_commits),
                   "rows": len(rows),
                   "legacy_states": _count(c["legacy_state"] for c in window_commits),
                   "by_rule": {r: totals(r) for r in ("legacy", "normalized_absolute", "ratio", "ratio_enforced")},
                   "by_rule_and_position": {r: {p: totals(r, p) for p in positions}
                                            for r in ("legacy", "normalized_absolute", "ratio", "ratio_enforced")},
                   "margin_sensitivity_failing_commits_enforced": sens},
        "commits": commit_rows, "rows": rows, "failure_index": failures,
    }
    Path(args.output).write_text(json.dumps(output, sort_keys=True, separators=(",", ":")) + "\n",
                                 encoding="utf-8")
    t = output["totals"]
    print(json.dumps({"commits_in_window": t["commits_in_window"], "by_rule": t["by_rule_and_position"]},
                     sort_keys=True))
    return 0


def _count(items):
    out = {}
    for item in items:
        out[item] = out.get(item, 0) + 1
    return dict(sorted(out.items()))


