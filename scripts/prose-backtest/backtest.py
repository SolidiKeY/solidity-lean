REGISTRY_ROOTS = ("Solidity.lean", "SolidityExamples.lean", "SoliditySlowExamples.lean",
                  "Bridge/SolidityBridge.lean")
CHECKER_PATH = "scripts/check-prose-budget"
BASELINE_PATH = "scripts/prose-baseline.json"
SCHEMA = "pb1-prose-backtest/1"
CLASSIFIER_RULES = "generated-rule/1"
HEADER_LINES = 15
GENERATOR = re.compile(r"((?:scripts|tests)/[A-Za-z0-9_./-]+\.(?:py|mjs|js|sh|lean))")
HEADER_MARK = re.compile(r"Generated by|Auto-generated by")
LINE_HEADER = re.compile(r"[ \t]*(?:<!--|#+|//)?[ \t]*(?:Generated by|Auto-generated by)\b")
BLOCK_BEGIN = re.compile(r"[ \t]*(?:--|<!--)[ \t]*BEGIN generated by[ \t]+`?([^\s`]+)")
BLOCK_END = re.compile(r"[ \t]*(?:--|<!--)[ \t]*END generated by[ \t]+`?([^\s`]+)")
_ID_DOTTED = re.compile(r"[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)+")
_G_ID = re.compile(r"\bG[0-9]+\b")


def load_checker(path):
    loader = importlib.machinery.SourceFileLoader("prose_budget_checker", str(path))
    spec = importlib.util.spec_from_loader(loader.name, loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


