def calibrate(args):
    repo = Repo(args.repo)
    commit = repo.run("rev-parse", "--verify", args.calibration + "^{commit}").decode().strip()
    margin = Fraction(args.margin)
    m = measure_commit(repo, Analyzer(repo), commit, None)
    mapping = json.loads(args.mapping) if args.mapping else {}
    cal = {}
    for area in sorted(m["normalized"]):
        d, dname = denominator(area, m["code"], mapping)
        cal[area] = {metric: {"numerator": m["normalized"][area][metric], "denominator": d,
                              "denominator_source": dname,
                              "ratio": None if d == 0 or m["normalized"][area][metric] == 0 else
                              str(Fraction(m["normalized"][area][metric], d)),
                              "null_reason": ("zero numerator" if m["normalized"][area][metric] == 0 else
                                              "zero denominator" if d == 0 else None)}
                     for metric in METRICS}
    baseline_blob = args.baseline_blob
    if baseline_blob:
        baseline = json.loads(text_of(repo.blob(baseline_blob)))
        absent = sorted(set(baseline) - set(cal))
        new = sorted(set(cal) - set(baseline))
    else:
        absent, new = [], []
    repo.close()
    estimate = {
        "schema": SCHEMA, "status": "PROPOSAL ONLY - not an active budget",
        "calibration_commit": commit, "calibration_tree": repo.run("rev-parse", commit + "^{tree}").decode().strip(),
        "reviewed_baseline": {"commit": args.baseline_commit, "blob": baseline_blob,
                              "review_provenance": args.review,
                              "calibration_label": "provisional" if args.review.startswith("UNVERIFIABLE") else "reviewed"},
        "classifier": {"checker_path": CHECKER_PATH, "checker_blob": git_blob_id(CHECKER_FILE.read_bytes()),
                       "generated_rules": CLASSIFIER_RULES},
        "margin": {"value": str(margin), "sensitivity": args.sensitivity.split(","),
                   "formula": "pass iff n * cal_d * q <= cal_n * (p + q) * d, margin = p/q; "
                              "cal_n == 0 or cal_d == 0 or d == 0 permits only n == 0"},
        "denominator_mapping": mapping,
        "enforcement_exclusions": args.exclude.split(",") if args.exclude else [],
        "legacy_semantics": {"checker_versions": json.loads(args.versions) if args.versions else {}},
        "calibration_generated_exclusions": len(m["exclusions"]),
        "calibration_unknown": len(m["unknown"]),
        "areas_absent_from_calibration": absent, "areas_new_in_calibration": new,
        "calibration": {a: v for a, v in cal.items()},
    }
    Path(args.output).write_text(json.dumps(estimate, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return 0


# ---------------------------------------------------------------- docs/audits inventory
SCRIPT_EXT = {".py", ".sh", ".mjs", ".js", ".lean", ".patch", ".ts"}
PROSE_EXT = {".md"}  # .txt is unknown: listings and samples are not prose by default
DATA_EXT = {".json", ".tsv", ".csv", ".jsonl"}
WRITE_HINT = re.compile(r"write_text|json\.dump|open\([^)]*['\"]w|>\s*\S|writer|to_csv|\.write\(")


def audits_inventory(args):
    repo = Repo(args.repo)
    commit = repo.run("rev-parse", "--verify", args.commit + "^{commit}").decode().strip()
    out = repo.run("ls-tree", "-r", "-z", "--full-tree", commit, "--", args.area)
    files = []
    for item in out.split(b"\0"):
        if item:
            meta, path = item.split(b"\t", 1)
            files.append((meta.decode().split()[2], path.decode()))
    texts = {}
    for sha, path in files:
        try:
            texts[path] = text_of(repo.blob(sha))
        except UnicodeDecodeError:
            texts[path] = None
    scripts = {p: t for p, t in texts.items() if Path(p).suffix in SCRIPT_EXT and t}
    rows = []
    for sha, path in files:
        suffix = Path(path).suffix
        text = texts[path]
        lines = len(text.splitlines()) if text is not None else None
        name = Path(path).name
        writers = sorted(p for p, t in scripts.items() if p != path and name in t and WRITE_HINT.search(t))
        if text is None:
            kind = "unknown_binary"
        elif suffix in SCRIPT_EXT:
            kind = "script_or_source"
        elif suffix in PROSE_EXT:
            kind = "handwritten_prose"
        elif suffix in DATA_EXT:
            kind = "data_generator_reference_unverified" if writers else "data_no_generator_evidence"
        else:
            kind = "unknown"
        rows.append({"path": path, "lines": lines, "kind": kind, "referencing_writers": writers})
    repo.close()
    summary = {}
    for r in rows:
        s = summary.setdefault(r["kind"], {"files": 0, "lines": 0})
        s["files"] += 1
        s["lines"] += r["lines"] or 0
    result = {"schema": SCHEMA, "commit": commit, "area": args.area,
              "note": "regenerability is NOT verified: generators were not executed (read-only study); "
                      "data_generator_reference_unverified only means a script names the file and writes output",
              "summary": dict(sorted(summary.items())), "files": rows}
    Path(args.output).write_text(json.dumps(result, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(result["summary"], sort_keys=True))
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--mode", choices=("replay", "calibrate", "audits-inventory"), default="replay")
    parser.add_argument("--repo", default=".", help="repository to read (Git objects only)")
    parser.add_argument("--output", required=False, help="output JSON path (written only here)")
    parser.add_argument("--end", help="replay: full end commit SHA (launch commit)")
    parser.add_argument("--days", type=int, default=21, help="replay: window length in days")
    parser.add_argument("--estimate", help="replay: frozen estimate JSON (read only)")
    parser.add_argument("--progress", action="store_true", help="replay: progress on stderr")
    parser.add_argument("--full-details", action="store_true",
                        help="replay: list generated exclusions for every commit, not only the first")
    parser.add_argument("--calibration", help="calibrate: calibration commit")
    parser.add_argument("--margin", default="1/20", help="calibrate: fixed rational margin p/q")
    parser.add_argument("--sensitivity", default="0,1/20,1/10", help="calibrate: predeclared margins to report")
    parser.add_argument("--mapping", help="calibrate: JSON area -> 'self' | 'repository-solidity' | [areas]")
    parser.add_argument("--exclude", default="", help="calibrate: comma list of areas outside proposed enforcement")
    parser.add_argument("--baseline-commit", help="calibrate: commit that introduced the reviewed baseline")
    parser.add_argument("--baseline-blob", help="calibrate: reviewed baseline blob")
    parser.add_argument("--review", default="UNVERIFIABLE", help="calibrate: review provenance record")
    parser.add_argument("--versions", help="calibrate: JSON checker blob -> semantic version label")
    parser.add_argument("--commit", help="audits-inventory: commit to inspect")
    parser.add_argument("--area", default="docs/audits", help="audits-inventory: directory")
    args = parser.parse_args(argv)
    if not args.output:
        parser.error("--output is required")
    if args.mode == "replay":
        if not (args.end and args.estimate):
            parser.error("replay needs --end and --estimate")
        return replay(args)
    if args.mode == "calibrate":
        if not args.calibration:
            parser.error("calibrate needs --calibration")
        return calibrate(args)
    if not args.commit:
        parser.error("audits-inventory needs --commit")
    return audits_inventory(args)


if __name__ == "__main__":
    sys.exit(main())
