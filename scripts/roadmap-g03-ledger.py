WAVE_HEADINGS = [
    (r"^### Wave 0 ", 0), (r"^### Independent source definitions", 0.5),
    (r"^### Wave 1 ", 1), (r"^### Wave 2 ", 2), (r"^### Wave 3 ", 3),
    (r"^### Wave 4 ", 4), (r"^### Wave 5 ", 5), (r"^### Wave 6 ", 6),
]


def load_plan(root):
    """Work packages, waves and the VM table of docs/coverage-plan.md."""
    text = (root / "docs/coverage-plan.md").read_text()
    lines = text.splitlines()
    groups, wave_of, wave = [], {}, None
    section = None
    for line in lines:
        for pat, w in WAVE_HEADINGS:
            if re.match(pat, line):
                wave = w
        if line.startswith("## "):
            section = line
            if not line.startswith("## Groups and dependencies"):
                wave = None if "manifest" not in line else wave
        m = re.match(r"^\| ([SG]\d\d) \|", line)
        if m and wave is not None and section and section.startswith("## Groups"):
            groups.append(m.group(1))
            wave_of[m.group(1)] = wave
    children = re.findall(r"^\| ([SG]\d\d\.\d\d) —", text, re.M)
    parents = {c.split(".")[0] for c in children}
    for c in children:
        wave_of[c] = wave_of.get(c.split(".")[0])
    packages = [g for g in groups if g not in parents] + children
    m = re.search(r"There are \*\*(\d+) proof work packages\*\*", text)
    stated = int(m.group(1)) if m else None
    vms = []
    for line in lines:
        m = re.match(r"^\| (V\d\d) \| ([^|]+) \| ([^|]+) \|", line)
        if m:
            vms.append((m.group(1), m.group(2).strip(), m.group(3).strip()))
    return dict(groups=groups, children=children, parents=parents, packages=packages,
                stated=stated, wave_of=wave_of, vms=vms)


def expand_ids(cell, plan):
    """`G03, G05`, `S04.01–S04.03`, a parent (all its children) -> package IDs."""
    out = []
    for part in [p.strip() for p in cell.split(",") if p.strip() and p.strip() != "—"]:
        m = re.match(r"^([SG]\d\d)\.(\d\d)–\1\.(\d\d)$", part)
        if m:
            out += [f"{m.group(1)}.{i:02d}" for i in range(int(m.group(2)), int(m.group(3)) + 1)]
        elif part in plan["parents"]:
            out += [c for c in plan["children"] if c.startswith(part + ".")]
        else:
            out.append(part)
    return out


def load_decisions(root):
    """First cells of the binding decision table and the follow-up labels."""
    text = (root / "docs/solidity-scope.md").read_text()
    start = text.index("## User decisions (2026-10-29)")
    end = text.index("\n## ", start + 5)
    block = text[start:end]
    rows = [m.group(1).strip() for m in re.finditer(r"^\| ([^|]+) \| [^|]+ \|$", block, re.M)
            if m.group(1).strip() not in ("Question", "---")]
    follow = re.findall(r"^- \*\*([^*]+?)\.?\*\*", block, re.M)
    return rows, follow


def load_restrictions(root):
    text = (root / "docs/feature-work/roadmap-g04-restrictions.md").read_text()
    out = {}
    for m in re.finditer(r"^\| (R\d\d) \|.*\| ([^|]+) \|$", text, re.M):
        out[m.group(1)] = m.group(2).strip()
    return out


DECL = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable|partial|unsafe|nonrec)\s+)*"
                  r"(theorem|lemma|def|abbrev|structure|inductive|class|instance|opaque|axiom)\s+([^\s:(\[{]+)")


def decl_index(root, files):
    """Qualified declaration names -> line, for the files the ledger cites."""
    out = {}
    for rel in sorted(files):
        p = root / rel
        if not p.is_file():
            continue
        ns = []
        for i, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            m = re.match(r"^namespace\s+(\S+)", line)
            if m:
                ns.append(m.group(1))
                continue
            m = re.match(r"^end\s+(\S+)\s*$", line)
            if m and ns and ns[-1] == m.group(1):
                ns.pop()
                continue
            m = DECL.match(line)
            if m:
                n = m.group(2)
                q = n[len("_root_."):] if n.startswith("_root_.") else ".".join(ns + [n])
                out.setdefault((rel, q), i)
    return out


def lean_imports(root):
    """Module -> directly imported modules, over the core and the Bridge."""
    graph = {}
    for base in ("Solidity", "Bridge"):
        for p in (root / base).rglob("*.lean"):
            if ".lake" in p.parts:
                continue
            rel = p.relative_to(root)
            parts = list(rel.with_suffix("").parts)
            if parts[0] == "Bridge":
                parts = parts[1:]
            mod = ".".join(parts)
            imps = re.findall(r"^import\s+(\S+)", p.read_text(errors="replace"), re.M)
            graph[mod] = (str(rel), imps)
    return graph


def module_of(path):
    parts = list(Path(path).with_suffix("").parts)
    if parts[0] == "Bridge":
        parts = parts[1:]
    return ".".join(parts)


