def build(root):
    errors = []
    g00 = load_g00(root)
    features = json.loads((root / "docs/solidity-features.json").read_text())["features"]
    byid = {f["id"]: f for f in features}
    plan = load_plan(root)
    if plan["stated"] != len(plan["packages"]):
        errors.append(f"coverage-plan.md states {plan['stated']} work packages; parsed {len(plan['packages'])}")
    pk = set(plan["packages"])
    imports = load_imports_cached(root)

    # anchors: every cited file must exist and hold the declaration
    cited = set()
    for rows in (D.COVER, D.COMBO_COVER, D.DECISION_COVER):
        for anchors in rows.values():
            for a in anchors:
                cited.add(a[2])
    cited.add("Solidity/Roadmap/Contracts.lean")
    idx = decl_index(root, cited)

    def anchor(where, a):
        stage, name, path, note = a
        if stage not in STAGES:
            errors.append(f"{where}: unknown stage {stage}")
        line = idx.get((path, name))
        if line is None:
            errors.append(f"{where}: {name} is not declared in {path}")
            line = 0
        return {"stage": stage, "decl": name, "module": module_of(path), "file": path,
                "line": line, "note": note}

    for c in CONTRACTS:
        if ("Solidity/Roadmap/Contracts.lean", "Solidity.Roadmap." + c) not in idx:
            errors.append(f"contract Solidity.Roadmap.{c} not found")

    # feature rows
    ledger_rows = []
    in_profile = [f for f in features if f["scope"] in ("model", "abstract")]
    extra_rows = [byid[k] for k in D.FEATURE_EXTRA if k in byid and byid[k] not in in_profile]
    for k in D.FEATURE_EXTRA:
        if k not in byid:
            errors.append(f"FEATURE_EXTRA: unknown feature {k}")
    for f in in_profile + extra_rows:
        fid = f["id"]
        cols = feature_owners(f, g00, plan, errors)
        if cols is None:
            continue
        reasons = D.DASH.get(fid, {})
        for st in STAGES:
            check_owner_list(f"{fid} {st}", cols[st], plan, errors, reasons.get(st))
        for st in reasons:
            if cols[st]:
                errors.append(f"{fid} {st}: reason recorded but owners present")
        # G00's owners must survive refinement
        if f["scope"] in ("model", "abstract"):
            o = g00.owners(f)
            for si, st in enumerate(("source", "admission", "lowering", "backend")):
                want = []
                for t in tokens(o[si]):
                    want += D.REFINE.get((fid, t), t).split() if t in plan["parents"] else [t]
                have = cols[st] + (cols["evm"] if st == "backend" else [])
                for t in want:
                    if t not in have:
                        errors.append(f"{fid} {st}: G00 owner {t} dropped")
        for t in cols["theorem"]:
            if not (t.startswith(("G48", "G49", "G50", "G51"))):
                errors.append(f"{fid} theorem: {t} is not a composition package (G48-G51)")
        contracts = D.STAGE_ADD.get(fid, {}).get("contracts") or D.CONTRACT_BY_CATEGORY[f["category"]]
        contracts = contracts.split()
        for c in contracts:
            if c not in CONTRACTS:
                errors.append(f"{fid}: unknown contract {c}")
        anchors = [anchor(fid, a) for a in D.COVER.get(fid, [])]
        missing = D.MISSING.get(fid, [])
        if f["scope"] in ("model", "abstract") and not missing:
            errors.append(f"{fid}: no missing cases recorded (current {f['current']})")
        covered = sorted({a["stage"] for a in anchors}, key=STAGES.index)
        ledger_rows.append({
            "id": fid, "category": f["category"], "scope": f["scope"], "current": f["current"],
            "owners": cols, "contracts": contracts, "reasons": reasons, "cover": anchors,
            "uncovered": [s for s in STAGES if s not in covered and s not in reasons],
            "missing": missing, "restrictions": D.FEATURE_RESTRICTIONS.get(fid, []),
            "decision": D.FEATURE_EXTRA.get(fid, {}).get("note"),
        })
    for fid in list(D.COVER) + list(D.MISSING) + list(D.STAGE_ADD) + list(D.DASH):
        if fid not in byid:
            errors.append(f"data names unknown feature {fid}")
    for (fid, parent), r in D.REFINE.items():
        if fid not in byid:
            errors.append(f"REFINE: unknown feature {fid}")
        for t in r.split():
            if not t.startswith(parent + "."):
                errors.append(f"REFINE {fid} {parent}: {t} is not a child of {parent}")

    # combinations
    combos = []
    g00_keys = set()
    for name, ins, outs, own in g00.COMBINATIONS:
        g00_keys.add((tuple(sorted(ins)), tuple(sorted(outs))))
    seen_g00 = set()
    for c in D.COMBINATIONS:
        key, ins, outs, owners, restr, missing = c
        for t in ins + outs:
            if t not in byid:
                errors.append(f"combination {key}: unknown feature {t}")
        for t in ins:
            if t in byid and byid[t]["scope"] not in ("model", "abstract") and t not in D.FEATURE_EXTRA:
                errors.append(f"combination {key}: {t} is not in profile")
        for t in outs:
            if t in byid and byid[t]["scope"] != "exclude":
                errors.append(f"combination {key}: {t} is not excluded")
        if not owners:
            errors.append(f"combination {key}: no owner")
        for st, cell in owners.items():
            if st not in STAGES:
                errors.append(f"combination {key}: unknown stage {st}")
            check_owner_list(f"combination {key} {st}", cell.split(), plan, errors)
        if not missing:
            errors.append(f"combination {key}: no missing cases recorded")
        k2 = (tuple(sorted(ins)), tuple(sorted(outs)))
        if outs:
            seen_g00.add(k2)
            if k2 not in g00_keys:
                errors.append(f"combination {key}: not one of G00's named combinations")
        anchors = [anchor(f"combination {key}", a) for a in D.COMBO_COVER.get(key, [])]
        combos.append({"key": key, "in": ins, "out": outs, "owners": {s: owners[s].split() for s in owners},
                       "restrictions": restr, "cover": anchors, "missing": missing,
                       "source": "G00" if outs else "G03"})
    for k in g00_keys - seen_g00:
        errors.append(f"G00 combination {k} has no G03 row (combination without an owner)")
    for key in D.COMBO_COVER:
        if key not in {c[0] for c in D.COMBINATIONS}:
            errors.append(f"COMBO_COVER: unknown combination {key}")

    # ledger symbol combinations (shared punctuation): owned through G15 and
    # the owners of their in-profile rows
    ledger = json.loads((root / "docs/solidity-upstream-inventory.json").read_text())
    scope = {f["id"]: f["scope"] for f in features}
    owned = {r["id"] for r in ledger_rows}
    symbol_combos = []
    for kind, table in ledger["symbols"].items():
        for name, targets in sorted(table.items()):
            targets = g00.targets_of(kind, name, targets)
            st = g00.symbol_status(targets, scope)
            if st.startswith("combination"):
                ins = [t for t in targets if scope[t] in ("model", "abstract")]
                for t in ins:
                    if t not in owned:
                        errors.append(f"symbol combination {kind}.{name}: in-profile {t} unowned")
                symbol_combos.append({"kind": kind, "symbol": name, "status": st, "in": ins,
                                      "other": [t for t in targets if t not in ins],
                                      "owners": ["G15"] + sorted({o for r in ledger_rows if r["id"] in ins
                                                                  for o in r["owners"]["admission"]} - {"G15"})})

    # G04 restrictions: each referenced by a G03 row whose owners include
    # one of the restriction's discharging packages
    restrictions = load_restrictions(root)
    referenced = collections.defaultdict(list)
    for r in ledger_rows:
        for x in r["restrictions"]:
            referenced[x].append(("feature", r["id"], {o for s in STAGES for o in r["owners"][s]}))
    for c in combos:
        for x in c["restrictions"]:
            referenced[x].append(("combination", c["key"], {o for s in c["owners"].values() for o in s}))
    for rid, disc in restrictions.items():
        if rid not in referenced:
            errors.append(f"G04 restriction {rid} has no G03 row")
            continue
        want = set()
        for t in re.findall(r"\b([SG]\d\d(?:\.\d\d)?)\b", disc):
            want |= set(expand_ids(t, plan)) if t in plan["parents"] else {t}
        want &= pk
        if want and not any(want & ow for _, _, ow in referenced[rid]):
            errors.append(f"G04 restriction {rid}: no G03 row owns any discharging package of {sorted(want)}")
    for rid in referenced:
        if rid not in restrictions:
            errors.append(f"unknown G04 restriction {rid}")

    # decisions
    dec_rows, follow = load_decisions(root)
    decisions = []
    seen_dec = collections.Counter()
    for d in D.DECISIONS:
        did, title, keys, owners, missing, lanes = d
        for k in keys:
            if k not in dec_rows and k not in follow:
                errors.append(f"decision {did}: unknown decision key {k!r}")
            seen_dec[k] += 1
        for st, cell in owners.items():
            if st not in STAGES:
                errors.append(f"decision {did}: unknown stage {st}")
            check_owner_list(f"decision {did} {st}", cell.split(), plan, errors)
        if not owners:
            errors.append(f"decision {did}: no owner")
        if not missing:
            errors.append(f"decision {did}: no missing cases recorded")
        anchors = [anchor(f"decision {did}", a) for a in D.DECISION_COVER.get(did, [])]
        decisions.append({"id": did, "title": title, "decisions": keys,
                          "owners": {s: owners[s].split() for s in owners}, "cover": anchors,
                          "missing": missing, "lanes": lanes})
    for k in dec_rows + follow:
        if not seen_dec[k]:
            errors.append(f"binding decision {k!r} has no G03 obligation row")
    for did in D.DECISION_COVER:
        if did not in {d[0] for d in D.DECISIONS}:
            errors.append(f"DECISION_COVER: unknown decision row {did}")
    for title, did in D.REQUIRED_DECISION_ROWS.items():
        if did not in {d[0] for d in D.DECISIONS}:
            errors.append(f"assignment-required decision row missing: {title} ({did})")

    # dependencies
    dep = dependency_ledger(plan, imports, root, errors)

    # oversized checkpoints
    cells = collections.Counter()
    for r in ledger_rows:
        for st in STAGES:
            for o in r["owners"][st]:
                cells[o] += 1
    for c in combos + decisions:
        for v in c["owners"].values():
            for o in v:
                cells[o] += 1
    sizes = {}
    for wp in plan["packages"]:
        mods = [m for m in D.MODULES.get(wp, "").split() if m != "new"]
        lines = sum(dep["lines_of"].get(m, 0) for m in mods)
        big = [m for m in mods if dep["lines_of"].get(m, 0) > D.MODULE_LINES_LIMIT]
        over = []
        if cells[wp] > D.CELLS_LIMIT:
            over.append(f"{cells[wp]} owned cells > {D.CELLS_LIMIT}")
        if lines > D.EDIT_LINES_LIMIT:
            over.append(f"{lines} edited lines > {D.EDIT_LINES_LIMIT}")
        if big:
            over.append("modules over " + str(D.MODULE_LINES_LIMIT) + " lines: " + ", ".join(big))
        sizes[wp] = {"cells": cells[wp], "modules": mods, "lines": lines, "oversized": over,
                     "split": D.SPLITS.get(wp)}
        if over and wp not in D.SPLITS:
            errors.append(f"oversized checkpoint {wp} ({'; '.join(over)}) has no lemma split")
    for wp in D.SPLITS:
        if wp not in sizes or not sizes[wp]["oversized"]:
            errors.append(f"SPLITS: {wp} is not flagged oversized")
    unowned = [wp for wp in plan["packages"] if cells[wp] == 0 and wp not in D.NO_FEATURE_CELLS]
    for wp in unowned:
        errors.append(f"work package {wp} owns no ledger cell and has no recorded reason")
    for wp in D.NO_FEATURE_CELLS:
        if cells[wp]:
            errors.append(f"NO_FEATURE_CELLS: {wp} does own cells")

    return dict(errors=errors, plan=plan, rows=ledger_rows, combos=combos, symbol_combos=symbol_combos,
                decisions=decisions, dep=dep, sizes=sizes, restrictions=restrictions)


