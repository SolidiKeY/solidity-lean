def dump_json(obj):
    """One list element or map entry per line: reviewable diffs, compact file."""
    def one(x):
        return json.dumps(x, ensure_ascii=False, sort_keys=True)

    def block(v, ind):
        pad = " " * ind
        if isinstance(v, list) and v and isinstance(v[0], (dict, list)):
            return "[\n" + ",\n".join(pad + " " + one(x) for x in v) + "\n" + pad + "]"
        if isinstance(v, dict) and any(isinstance(x, (dict, list)) for x in v.values()):
            return "{\n" + ",\n".join(f"{pad} {json.dumps(k)}: {block(x, ind + 1)}" for k, x in v.items()) \
                + "\n" + pad + "}"
        return one(v)
    return block(obj, 0) + "\n"


