def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    args = ap.parse_args()
    root = Path(args.root)
    L = build(root)
    if L["errors"]:
        print("\n".join(L["errors"]), file=sys.stderr)
        print(f"roadmap-g03: {len(L['errors'])} error(s)", file=sys.stderr)
        return 1
    js = dump_json(to_json(L))
    doc = root / DOC
    text = doc.read_text()
    start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
    block = "\n" + report(L) + "\n"
    if args.write:
        doc.write_text(text[:start] + block + text[end:])
        (root / JSON_OUT).write_text(js)
        return 0
    if args.check:
        stale = []
        if text[start:end] != block:
            stale.append(DOC)
        if not (root / JSON_OUT).is_file() or (root / JSON_OUT).read_text() != js:
            stale.append(JSON_OUT)
        if stale:
            print(f"stale generated output: {', '.join(stale)} (run --write)", file=sys.stderr)
            return 1
        rows = L["rows"]
        print(f"roadmap-g03: {len(rows)} feature rows, {len(L['combos'])} combinations, "
              f"{len(L['symbol_combos'])} symbol combinations, {len(L['decisions'])} decision rows, "
              f"{len(L['plan']['packages'])} work packages, "
              f"{sum(len(r['cover']) for r in rows)} anchors, {len(L['dep']['findings'])} acknowledged findings, "
              f"{len(L['dep']['cycles'])} acknowledged cycles; 0 errors")
        return 0
    print(report(L))
    return 0


