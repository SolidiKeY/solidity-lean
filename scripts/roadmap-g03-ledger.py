#!/usr/bin/env python3
"""Roadmap G03: source-constructor/feature -> theorem ledger, and the
module/lemma dependency ledger.

For every in-profile manifest row (docs/solidity-features.json), every named
feature combination and every decision-driven obligation
(docs/solidity-scope.md#user-decisions-2026-10-29) this records the work
packages of docs/coverage-plan.md that own six stages -- source definition,
admission, lowering, backend, EVM bridge, final theorem -- the existing
declarations that already cover part of it, and the cases still missing.
It extends G00's owner table (scripts/roadmap-g00-scope.py, imported
read-only, never edited): G00's source/syntax/lowering/backend owners must
reappear here, refined from split parents to their child work packages.

`--check` fails on: an owner that is not one of the roadmap's work packages
(the 115 rows of its manifest: unsplit S/G rows plus child rows), a stage
with no owner and no recorded reason, a G00 owner dropped, a split parent
left unrefined, a G00 combination or a G04 restriction with no G03 row, a
decision of the binding record with no obligation row, an anchor that is not
a declaration in the cited file, a dependency on an unknown package, an
unacknowledged dependency cycle, schedule inversion or oversized checkpoint,
and stale generated output.

Usage: python3 -I scripts/roadmap-g03-ledger.py [--check | --write] [--root DIR]
`--write` regenerates docs/feature-work/roadmap-g03-ledger.json and the
generated block of docs/feature-work/roadmap-g03-ledger.md; with neither
flag the ledger is printed. Standard library only.
"""

