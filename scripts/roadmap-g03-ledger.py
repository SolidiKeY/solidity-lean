def closure(edges, start):
    seen, todo = set(), [start]
    while todo:
        n = todo.pop()
        for m in edges.get(n, ()):
            if m not in seen:
                seen.add(m)
                todo.append(m)
    return seen


def find_cycles(nodes, edges):
    """Strongly connected components with more than one node (Tarjan)."""
    index, low, stack, on, out, counter = {}, {}, [], set(), [], [0]

    def visit(v):
        index[v] = low[v] = counter[0]
        counter[0] += 1
        stack.append(v)
        on.add(v)
        for w in edges.get(v, ()):
            if w not in index:
                visit(w)
                low[v] = min(low[v], low[w])
            elif w in on:
                low[v] = min(low[v], index[w])
        if low[v] == index[v]:
            comp = []
            while True:
                w = stack.pop()
                on.discard(w)
                comp.append(w)
                if w == v:
                    break
            if len(comp) > 1:
                out.append(sorted(comp))

    sys.setrecursionlimit(10000)
    for v in nodes:
        if v not in index:
            visit(v)
    return out


def dependency_ledger(plan, imports, root, errors):
    pk = plan["packages"]
    wave = plan["wave_of"]
    # VM schedule
    vm_of, vm_pre, vm_order = {}, {}, {}
    for vm, cps, pre in plan["vms"]:
        ids = expand_ids(cps, plan)
        for pos, i in enumerate(ids):
            if i in vm_of:
                errors.append(f"VM table: {i} in {vm_of[i]} and {vm}")
            vm_of[i] = vm
            vm_order[i] = pos
        vm_pre[vm] = [v.strip() for v in pre.split(",") if v.strip() not in ("—", "")]
    for i in pk:
        if i not in vm_of:
            errors.append(f"VM table: work package {i} has no VM")
    vm_closure = {vm: closure(vm_pre, vm) for vm in vm_pre}
    # declared and G03 dependencies
    edges = collections.defaultdict(set)
    origin = {}
    for a, bs, why, kind in D.DEPENDENCIES:
        for x in [a] + bs.split():
            if x not in pk:
                errors.append(f"dependency {a} <- {bs}: unknown work package {x}")
        for b in bs.split():
            edges[a].add(b)
            origin[(a, b)] = (kind, why)
    # module ledger: edited modules per package
    graph = imports
    mod_edit = collections.defaultdict(list)
    for wp, mods in D.MODULES.items():
        if wp not in pk:
            errors.append(f"module ledger: unknown work package {wp}")
        for m in mods.split():
            if m == "new":
                continue
            if m not in graph:
                errors.append(f"module ledger {wp}: unknown module {m}")
                continue
            mod_edit[m].append(wp)
    for wp in pk:
        if wp not in D.MODULES:
            errors.append(f"module ledger: no entry for {wp}")
    imp = {m: set(i for i in graph[m][1] if i in graph) for m in graph}
    mod_closure = {}

    def mclos(m):
        if m not in mod_closure:
            mod_closure[m] = closure(imp, m)
        return mod_closure[m]

    induced = collections.defaultdict(set)
    induced_why = {}
    for wp, mods in D.MODULES.items():
        for m in mods.split():
            if m not in graph:
                continue
            for y in sorted(mclos(m) | {m}):
                for other in mod_edit.get(y, ()):
                    if other != wp:
                        induced[wp].add(other)
                        induced_why.setdefault((wp, other), set()).add((m, y))

    def before(b, a):
        """b is scheduled to complete before a starts (wave, then VM order)."""
        wa, wb = wave.get(a), wave.get(b)
        if wa is None or wb is None:
            return False
        if wb < wa:
            return True
        if wb > wa:
            return False
        va, vb = vm_of.get(a), vm_of.get(b)
        if va == vb:
            return vm_order[b] < vm_order[a]
        return vb in vm_closure.get(va, set())

    findings = []
    acked = {(a, b): why for a, b, why in D.ACKNOWLEDGED}
    # 1. declared/G03 dependency against the schedule
    for a in sorted(edges):
        for b in sorted(edges[a]):
            kind, why = origin[(a, b)]
            if kind == "deferred":
                continue
            if not before(b, a):
                findings.append(("schedule", a, b, why, None))
    # 2. induced module dependencies against the schedule (import inversion)
    for a in sorted(induced):
        if a in D.INTEGRATED:
            continue
        for b in sorted(induced[a]):
            if b in edges.get(a, ()) or before(b, a):
                continue
            if before(a, b):
                for m, y in sorted(induced_why[(a, b)]):
                    via = "is" if m == y else f"imports {y}, which is"
                    findings.append(("inversion", a, b, f"{m} {via} edited later by {b}", y))
    # 3. shared writes between unordered packages
    for m, wps in sorted(mod_edit.items()):
        for i, a in enumerate(wps):
            for b in wps[i + 1:]:
                if not before(a, b) and not before(b, a):
                    findings.append(("shared-write", a, b, f"both edit {m}, unordered", m))
    # cycles over declared + induced edges + the schedule's own order
    # cycles: declared (non-deferred) edges plus the implicit wave order;
    # module-induced edges are reported as inversions, not cycles
    all_edges = collections.defaultdict(set)
    for a in edges:
        all_edges[a] |= {b for b in edges[a] if origin[(a, b)][0] != "deferred"}
    for a in pk:
        for b in pk:
            if wave.get(b) is not None and wave.get(a) is not None and wave[b] < wave[a]:
                all_edges[a].add(b)
    cycles = find_cycles(sorted(pk), all_edges)
    acked_cycles = {tuple(sorted(c.split())) for c, _ in D.ACKNOWLEDGED_CYCLES}
    for c in cycles:
        if tuple(c) not in acked_cycles:
            errors.append(f"unacknowledged dependency cycle: {' '.join(c)}")
    used_mod = set()
    for kind, a, b, why, mod in findings:
        if (a, b) in acked or (b, a) in acked:
            continue
        if mod in D.ACK_MODULES:
            used_mod.add(mod)
            continue
        errors.append(f"unacknowledged {kind} {a} <- {b}: {why}")
    for m in D.ACK_MODULES:
        if m not in used_mod:
            errors.append(f"stale module acknowledgement {m}")
    for (a, b) in acked:
        if not any((x, y) in ((a, b), (b, a)) for _, x, y, _, _ in findings):
            errors.append(f"stale acknowledgement {a} <- {b}: no such finding")
    for c, _ in D.ACKNOWLEDGED_CYCLES:
        if tuple(sorted(c.split())) not in {tuple(x) for x in cycles}:
            errors.append(f"stale cycle acknowledgement: {c}")
    # sizes
    lines_of = {}
    for m, (rel, _) in graph.items():
        lines_of[m] = sum(1 for _ in (root / rel).open(errors="replace"))
    return dict(vm_of=vm_of, vm_pre=vm_pre, edges=edges, origin=origin, induced=induced,
                induced_why=induced_why, findings=findings, cycles=cycles, mod_edit=mod_edit,
                lines_of=lines_of)


