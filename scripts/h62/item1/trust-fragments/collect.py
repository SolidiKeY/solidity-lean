#!/usr/bin/env python3
"""Collect ordered raw TrustAudit fragments without interpreting Lean syntax."""
import argparse
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
FRAGMENTS = ROOT / 'tests/h62/item1/trust-fragments/fragments'
AUDIT = ROOT / 'TrustAudit.lean'
LANES = ROOT / 'tests/h62/item1/trust-fragments/lanes'
BASELINE_SHA256 = 'ece2e6cebbee95d82fec246892993662e81dcfd895831981583d2b0867a37482'
MARKER = b'-- Generated by scripts/h62/item1/trust-fragments/collect.py --migration --stdout; edit fragments instead.\n'
PATTERN = re.compile(r'\d{3}-[a-z0-9-]+\.leanfrag')


def collect(directory):
    if directory.is_symlink():
        raise ValueError('fragment root must not be a symlink')
    entries = sorted(directory.iterdir(), key=lambda p: p.name)
    if not entries or any(p.is_symlink() or not p.is_file() or not PATTERN.fullmatch(p.name) for p in entries):
        raise ValueError('unexpected or missing fragment entry')
    for index, path in enumerate(entries):
        if not path.name.startswith(f'{index:03d}-'):
            raise ValueError('fragment numbering must be contiguous from 000')
    return b''.join(p.read_bytes() for p in entries)


# Lane files are data, not executable Python or unrestricted Lean commands.
# Each owner has a separate directory and each addition a separate JSON file.
# Legacy bytes and the original check loop remain intact except for insertion
# into the first headline list and imports at the beginning.
def read_lane_files(directory):
    if directory.is_symlink():
        raise ValueError('lane root must not be a symlink')
    if not directory.exists():
        return {}
    result = {}
    for lane in sorted(directory.iterdir(), key=lambda p: p.name):
        if lane.is_symlink() or not lane.is_dir() or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', lane.name):
            raise ValueError(f'invalid lane directory: {lane.name}')
        files = sorted(lane.iterdir(), key=lambda p: p.name)
        if not files:
            raise ValueError(f'empty lane directory: {lane.name}')
        for path in files:
            if path.is_symlink() or not path.is_file() or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*\.json', path.name):
                raise ValueError(f'invalid lane fragment: {path.name}')
            result[f'{lane.name}/{path.name}'] = path.read_bytes()
    return result


def collect_lanes(baseline, directory):
    return collect_lane_snapshot(baseline, read_lane_files(directory))


def collect_lane_snapshot(baseline, files):
    if hashlib.sha256(baseline).hexdigest() != BASELINE_SHA256:
        raise ValueError('lane collection requires the exact frozen baseline')
    atom = r"[A-Za-z_][A-Za-z0-9_']*[?!]?"
    module = re.compile(r'Solidity(?:\.' + atom + r')+')
    known_imports = set(re.findall(rb'(?m)^import (\S+)', baseline))
    known_names = set(re.findall(rb'``(Solidity[^,\s\]]+)', baseline))
    imports = set()
    names = []
    for path, data in sorted(files.items(), key=lambda row: tuple(row[0].split('/', 1))):
        def unique_object(pairs):
            data = {}
            for key, value in pairs:
                if key in data:
                    raise ValueError(f'duplicate JSON key: {key}')
                data[key] = value
            return data
        payload = json.loads(data.decode('utf-8'), object_pairs_hook=unique_object)
        if not isinstance(payload, dict) or set(payload) != {'imports', 'headlines'}:
            raise ValueError(f'invalid lane fragment schema: {path}')
        lane_imports, lane_names = payload['imports'], payload['headlines']
        if not isinstance(lane_imports, list) or not isinstance(lane_names, list) or not lane_names:
            raise ValueError(f'fragment must contain headline additions: {path}')
        for name in lane_imports:
            if not isinstance(name, str) or not module.fullmatch(name):
                raise ValueError(f'invalid import: {name!r}')
            encoded = name.encode()
            if encoded not in known_imports:
                imports.add(encoded)
        for name in lane_names:
            if not isinstance(name, str) or not module.fullmatch(name):
                raise ValueError(f'invalid headline: {name!r}')
            encoded = name.encode()
            if encoded in known_names:
                raise ValueError(f'duplicate headline: {name}')
            known_names.add(encoded)
            names.append(encoded)
    if not names:
        return baseline
    first = baseline.index(b'  let headlines : List Name := [')
    end = baseline.index(b']', first)
    additions = b''.join(b',\n    ``' + name for name in names)
    result = baseline[:end] + additions + baseline[end:]
    return b''.join(b'import ' + name + b'\n' for name in sorted(imports)) + result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--fragments', type=pathlib.Path, default=FRAGMENTS)
    parser.add_argument('--lanes', type=pathlib.Path, default=LANES)
    parser.add_argument('--check', type=pathlib.Path, default=AUDIT)
    parser.add_argument('--stdout', action='store_true')
    parser.add_argument('--migration', action='store_true', help='include generated-file marker for the proposed migration')
    args = parser.parse_args()
    try:
        data = collect_lanes(collect(args.fragments), args.lanes)
        if args.migration:
            data = MARKER + data
        if args.stdout:
            sys.stdout.buffer.write(data)
        elif data != args.check.read_bytes():
            print('fragment reproduction differs from audit', file=sys.stderr)
            return 1
        else:
            print(f'reproduced {len(data)} bytes sha256={hashlib.sha256(data).hexdigest()}')
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f'fragment collection failed: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
