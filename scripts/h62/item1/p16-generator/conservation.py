#!/usr/bin/env python3
"""Account for a supplied owner interface delta against registrations."""
import argparse
from collections import Counter
import hashlib
import json
import re
from pathlib import Path
import subprocess
import sys

import census
import generate

BASE = "c6f550e281a7e5affa9a99bc2cdaed556dec00e4"
MARKER = "-- Generated by scripts/h62/item1/p16-generator/generate.py; edit fragments, not this file.\n"


def digest(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def summarize(counter, hashed=False):
    return [{"node": digest(value) if hashed else value, "count": count}
            for value, count in sorted(counter.items())]


def verify_revision_sources(root, rev, nodes):
    for node in nodes:
        path = node.replace(".", "/") + ".lean"
        result = subprocess.run(["git", "ls-tree", "-z", rev, "--", path], cwd=root,
                                capture_output=True, check=True).stdout
        records = [record for record in result.split(b"\0") if record]
        if len(records) != 1 or b"\t" not in records[0]:
            raise ValueError("missing source file at revision: " + path)
        metadata, found = records[0].split(b"\t", 1)
        fields = metadata.split()
        if len(fields) != 3 or fields[0] not in (b"100644", b"100755") or fields[1] != b"blob" or found != path.encode("utf-8"):
            raise ValueError("not a regular source file at revision: " + path)


def main():
    ap = argparse.ArgumentParser()
    source = ap.add_mutually_exclusive_group(required=True)
    source.add_argument("--after", type=Path, help="P16 snapshot to reconcile")
    source.add_argument("--after-rev", help="full owner commit SHA containing P16")
    ap.add_argument("--owner", choices=("VY1", "VY3", "integrated"), default="integrated",
                    help="select one owner registrations or their integrated union")
    args = ap.parse_args()
    generate.render(require_sources=False)
    baseline = subprocess.run(["git", "show", BASE + ":" + generate.NAME], cwd=generate.ROOT,
                              capture_output=True, check=True).stdout.decode("utf-8")
    if args.after_rev:
        if not re.fullmatch(r"[0-9a-f]{40}", args.after_rev):
            raise ValueError("after revision must be a full lowercase commit SHA")
        subprocess.run(["git", "merge-base", "--is-ancestor", BASE, args.after_rev], cwd=generate.ROOT,
                       capture_output=True, check=True)
        after_bytes = subprocess.run(["git", "show", args.after_rev + ":" + generate.NAME], cwd=generate.ROOT,
                                     capture_output=True, check=True).stdout
        source_label = "git:" + args.after_rev
    else:
        after_bytes = args.after.read_bytes()
        source_label = "file:" + str(args.after.resolve())
    after = after_bytes.decode("utf-8")
    after_body = after[len(MARKER):] if after.startswith(MARKER) else after
    base_imports, base_docs = census.parse(baseline)
    after_imports, after_docs = census.parse(after_body)
    if args.after_rev:
        verify_revision_sources(generate.ROOT, args.after_rev, after_imports)
    inventory = json.loads((generate.HERE / "baseline-inventory.json").read_bytes())
    baseline_fragments = "\n".join("import " + (generate.HERE / "imports" / name).read_bytes().decode("utf-8")[:-1]
                                   for name in sorted(inventory["imports"])) + "\n\n" + "\n".join(
                                       (generate.HERE / "body" / name).read_bytes().decode("utf-8")
                                       for name in sorted(inventory["body"]))
    registrations = []
    registered_imports, registered_docs = Counter(), Counter()
    for path in sorted((generate.HERE / "registrations").glob("*.json")):
        entry = json.loads(path.read_bytes())
        if args.owner != "integrated" and not path.stem.startswith(args.owner + "-"):
            continue
        module = entry["module"]
        doc_hash = None
        if module is not None:
            registered_imports[module] += 1
        if entry["documentation"]:
            contents = (generate.HERE / "body" / ("ext-" + path.stem + ".txt")).read_bytes().decode("utf-8")[:-1]
            registered_docs[contents] += 1
            doc_hash = digest(contents)
        registrations.append({"id": path.stem, "module": module, "documentation_sha256": doc_hash})
    import_names = sorted(inventory["imports"]) + sorted("ext-" + r["id"] + ".txt" for r in registrations if r["module"] is not None)
    doc_names = sorted(inventory["body"]) + sorted("ext-" + r["id"] + ".txt" for r in registrations if r["documentation_sha256"] is not None)
    generated = "\n".join("import " + (generate.HERE / "imports" / n).read_bytes().decode("utf-8")[:-1] for n in import_names) + "\n\n" + "\n".join((generate.HERE / "body" / n).read_bytes().decode("utf-8") for n in doc_names)
    added_imports = Counter(after_imports) - Counter(base_imports)
    removed_imports = Counter(base_imports) - Counter(after_imports)
    added_docs = Counter(after_docs) - Counter(base_docs)
    removed_docs = Counter(base_docs) - Counter(after_docs)
    ok = (baseline_fragments == baseline and not removed_imports and not removed_docs
          and added_imports == registered_imports and added_docs == registered_docs
          and after_body == generated)
    result = {
        "comparison_scope": args.owner,
        "source": source_label,
        "source_identity_note": "A path or Git SHA alone does not authenticate owner membership or certify producer completeness.",
        "source_module_check": "git_tree_verified" if args.after_rev else "not_verified_for_file_snapshot",
        "owner_completeness": "unverified",
        "base_commit": BASE,
        "base_sha256": digest(baseline),
        "after_sha256": hashlib.sha256(after_bytes).hexdigest(),
        "base": {"imports": len(base_imports), "documentation_blocks": len(base_docs)},
        "after": {"imports": len(after_imports), "documentation_blocks": len(after_docs)},
        "registered_extensions": registrations,
        "added_imports": summarize(added_imports),
        "removed_imports": summarize(removed_imports),
        "unregistered_imports": summarize(added_imports - registered_imports),
        "unrepresented_import_registrations": summarize(registered_imports - added_imports),
        "added_documentation_sha256": summarize(added_docs, True),
        "removed_documentation_sha256": summarize(removed_docs, True),
        "unregistered_documentation_sha256": summarize(added_docs - registered_docs, True),
        "unrepresented_documentation_registrations_sha256": summarize(registered_docs - added_docs, True),
        "baseline_matches_pinned_bytes": baseline_fragments == baseline,
        "output_matches_registered_bytes_and_order": after_body == generated,
        "status": "interface_delta_match" if ok else "interface_delta_mismatch",
    }
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if ok else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, TypeError, KeyError, subprocess.CalledProcessError) as exc:
        print("P16 conservation: " + str(exc), file=sys.stderr)
        sys.exit(2)
