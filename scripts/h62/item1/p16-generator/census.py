#!/usr/bin/env python3
"""Reconcile a supplied P16 interface against registered import and doc nodes."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import sys
import subprocess

import generate


def parse(text):
    marker = "-- Generated by scripts/h62/item1/p16-generator/generate.py; edit fragments, not this file.\n"
    if text.startswith(marker):
        text = text[len(marker):]
    head, body = text.split("\n\n", 1)
    lines = head.splitlines()
    if any(not re.fullmatch(r"import " + generate.MODULE.pattern, line) for line in lines):
        raise ValueError("unsupported import header")
    blocks = []
    index = 0
    while index < len(body):
        if not body.startswith("/-!", index):
            raise ValueError("unsupported documentation block layout")
        start = index
        index += 3
        depth = 1
        while index < len(body) and depth:
            pair = body[index:index + 2]
            if pair == "/-":
                depth += 1
                index += 2
            elif pair == "-/":
                depth -= 1
                index += 2
            else:
                index += 1
        if depth:
            raise ValueError("unbalanced documentation block")
        blocks.append(body[start:index])
        if index == len(body) or body[index] != "\n":
            raise ValueError("missing documentation separator")
        while index < len(body) and body[index] == "\n":
            index += 1
    if not blocks:
        raise ValueError("empty documentation blocks")
    return [line[len("import "):] for line in lines], blocks


def delta(label, desired, observed):
    missing = Counter(desired) - Counter(observed)
    extra = Counter(observed) - Counter(desired)
    for kind, data in (("missing", missing), ("extra", extra)):
        for value, count in sorted(data.items()):
            desc = value if label == "import" else "sha256:" + hashlib.sha256(value.encode()).hexdigest()
            print(f"{kind} {label} {desc} count={count}")
    if not missing and not extra and desired != observed:
        print(f"{label} order differs")
    return desired == observed


def main():
    ap = argparse.ArgumentParser()
    source = ap.add_mutually_exclusive_group()
    source.add_argument("--target", type=Path, default=generate.TARGET)
    source.add_argument("--baseline", action="store_true", help="compare baseline fragments to the pinned Git commit")
    args = ap.parse_args()
    _, expected = generate.render()
    if args.baseline:
        inventory = json.loads((generate.HERE / "baseline-inventory.json").read_bytes().decode("utf-8"))
        import_lines = ["import " + (generate.HERE / "imports" / n).read_bytes().decode("utf-8").strip() for n in sorted(inventory["imports"])]
        body_parts = [(generate.HERE / "body" / n).read_bytes().decode("utf-8") for n in sorted(inventory["body"])]
        expected = "\n".join(import_lines) + "\n\n" + "\n".join(body_parts)
        observed = subprocess.run(["git", "show", "c6f550e281a7e5affa9a99bc2cdaed556dec00e4:" + generate.NAME], cwd=generate.ROOT, capture_output=True, check=True).stdout.decode("utf-8")
    else:
        observed = args.target.read_bytes().decode("utf-8")
    imports, docs = parse(expected)
    got_imports, got_docs = parse(observed)
    imports_ok = delta("import", imports, got_imports)
    docs_ok = delta("documentation", docs, got_docs)
    marker = "-- Generated by scripts/h62/item1/p16-generator/generate.py; edit fragments, not this file.\n"
    normalized = observed[len(marker):] if observed.startswith(marker) else observed
    bytes_ok = expected == normalized
    if not bytes_ok and imports_ok and docs_ok:
        print("byte-level text differs")
    print(f"registered imports={len(imports)} documentation_blocks={len(docs)}; observed imports={len(got_imports)} documentation_blocks={len(got_docs)}")
    return 0 if imports_ok and docs_ok and bytes_ok else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, TypeError, subprocess.CalledProcessError) as exc:
        print("P16 census: " + str(exc), file=sys.stderr)
        sys.exit(2)
