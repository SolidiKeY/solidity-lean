#!/usr/bin/env python3
"""Generate additive typed fixture table + exact-file owner migration proposal.

Never edits originals. Reuses original fixtures by name and preserves their
exact source statement prefix. Finite certificates keep original +kernel
checking; the generic semantic proof is structural in Core.lean.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
from census import BASE, declarations, encode

REPO = Path(__file__).resolve().parents[4]
TARGET = Path('tests/h62/item4/generic-source-frontend')
ORIGINAL = Path('Solidity/Frontend/StatementGrammarH28/FixtureControls')

def generated(repo):
    originals = sorted((repo / ORIGINAL).glob('Case*.lean'))
    if [p.name for p in originals] != [f'Case{i:02}.lean' for i in range(45)]:
        raise ValueError('original 45-case inventory changed')
    rows = []
    for i, path in enumerate(originals):
        source = path.read_text()
        ds = declarations(source)
        if len(ds) != 1 or ds[0]['name'] != f'statementFixture{i}_checked':
            raise ValueError(f'unexpected original declaration: {path}')
        expected = f'theorem statementFixture{i}_checked : statementFixtureCheck statementFixture{i} = true'
        if ds[0]['source_header'] != expected or source.count('by decide +kernel') != 1:
            raise ValueError('frozen original statement/proof changed: ' + str(path))
        rows.append(dict(case=i, path=path.relative_to(repo).as_posix(),
                         original_file_sha256=hashlib.sha256(source.encode()).hexdigest(),
                         source_header=expected, source_header_sha256=ds[0]['source_header_sha256']))
    table = "import tests.h62.item4.«generic-source-frontend».Core\nimport Solidity.Frontend.StatementGrammarH28.FixtureData\n\n/-! Generated by scripts/h62/item4/generic-source-frontend/generate.py.\nExactly the original 45 finite certificates. The universal semantic theorem\nis proved in Core, not by deciding this table. This file awaits the owned\nFrontend/Checked/Token migration; no passing check is claimed until then. -/\nnamespace Solidity.Frontend.GenericSourceControls\nopen Solidity.Source Solidity.Frontend.Checked\nopen Solidity.Frontend.StatementGrammarH28\n\n/-- No copied fixture schema: rows retain the owner's exact fixture type. -/\ndef statementRows : List (Row StatementFixture statementFixtureCheck) := [\n"
    certs = '\n'.join(f'private theorem certificate{i} : statementFixtureCheck statementFixture{i} = true := by decide +kernel' for i in range(45)) + '\n\n'
    marker = '/-- No copied fixture schema:'
    table = table.replace(marker, certs + marker)
    table += ',\n'.join(f'  ⟨statementFixture{i}, certificate{i}⟩' for i in range(45))
    table += "]\n\n/-- Exact original data, order, positives, negatives, and profile controls. -/\ntheorem statementRows_exact : statementRows.map Row.fixture = statementFixtures := rfl\n\ntheorem statementRows_length : statementRows.length = 45 := rfl\n\n/-- Definitionally the same Boolean proposition as the owner's checker. -/\ntheorem checker_exact (c : StatementFixture) :\n    statementFixtureCheck c = check (parse (ascii c.source)) c.accepts c.profile\n      c.required (fun u => u.rejections.isEmpty) fixtureBodyCtors := rfl\n\ntheorem fixture_correspondence (c : StatementFixture) :\n    statementFixtureCheck c = true ↔\n      Specification (parse (ascii c.source)) c.accepts c.profile\n        c.required (fun u => u.rejections.isEmpty) fixtureBodyCtors := by\n  rw [checker_exact]\n  exact check_iff _ _ _ _ _ _\n\n/-- A failed-acceptance row still requires a real parse refusal. -/\ntheorem fixture_negative_refuses (c : StatementFixture)\n    (ha : c.accepts = false) (hc : statementFixtureCheck c = true) :\n    ∃ e : Error, parse (ascii c.source) = .error e := by\n  rw [checker_exact, ha] at hc\n  exact negative_requires_refusal _ _ _ _ _ hc\n"
    for i in range(45):
        table += f'\ntheorem instance{i} : statementFixtureCheck statementFixture{i} = true :=\n  (statementRows[{i}]).checked\n'
    table += '\n#print axioms fixture_correspondence\n#print axioms fixture_negative_refuses\n#print axioms statementRows_exact\nend Solidity.Frontend.GenericSourceControls\n'
    proposal = dict(base=BASE, status='OWNER_AGREEMENT_REQUIRED_NOT_APPLIED',
                    owner='H28-STATEMENT-GRAMMAR',
                    module_registration='coordinator must approve area/module registration; generated roots untouched',
                    files=[])
    for row, path in zip(rows, originals):
        i = row['case']
        source = path.read_text()
        changed = source.replace('import Solidity.Frontend.StatementGrammarH28.FixtureData',
                                 'import tests.h62.item4.«generic-source-frontend».FixtureTable')
        changed = changed.replace('by decide +kernel',
                                  f'Solidity.Frontend.GenericSourceControls.instance{i}')
        proposal['files'].append(dict(**row, proposed_content=changed))
    return {TARGET / 'FixtureTable.lean': table,
            TARGET / 'owner-migration-proposal.json': encode(proposal)}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--baseline-output', type=Path)
    args = ap.parse_args()
    for path, content in generated(REPO).items():
        path = REPO / path
        if args.check:
            if path.read_text() != content:
                raise SystemExit('GENERATED_DRIFT: ' + str(path))
        else:
            path.write_text(content)
    if args.baseline_output:
        baseline = 'import Solidity.Frontend.StatementGrammarH28.FixtureData\n\n'
        for path in sorted((REPO/ORIGINAL).glob('Case*.lean')):
            baseline += path.read_text().split('\n', 1)[1] + '\n'
        args.baseline_output.write_text(baseline)
    print('GENERATION_MATCH 45 original statements; no originals modified')

if __name__ == '__main__':
    main()
