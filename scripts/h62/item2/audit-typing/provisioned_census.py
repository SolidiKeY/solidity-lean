#!/usr/bin/env python3
"""Generate a census module for frozen assigned modules with checked artifacts.
No module or generated theorem is excluded from its selected module census.
Unprovisioned assigned modules and unconfirmed owners stay visibly pending.
"""
import fcntl
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[4]
EVIDENCE = Path("/workspace/h62-audit-typing-evidence/v4.24.0")
BASE = "c6f550e281a7e5affa9a99bc2cdaed556dec00e4"

def generate():
    scope_file = EVIDENCE/"frozen-scope.json"
    subprocess.run([sys.executable, str(Path(__file__).with_name("source_census.py")),
        "--output", str(scope_file)], cwd=ROOT, check=True)
    scope = json.loads(scope_file.read_text())
    assert scope["base"] == BASE
    modules = {m["path"]: m for m in scope["modules"]}
    records = []
    for manifest in ["typing-values-build-results.json", "frontend-units-build-results.json"]:
        records += json.loads((EVIDENCE/manifest).read_text())
    assert all(r["exit"] == 0 and r["stopped"] is None for r in records)
    built = {r["command"][-1] for r in records}
    selected = sorted(set(modules) & built)
    inventory = []
    for path in selected:
        module = path.removesuffix(".lean").replace("/", ".")
        history = subprocess.check_output(["git", "log", "-1", "--format=%H%n%an", BASE, "--", path], cwd=ROOT, text=True).splitlines()
        inventory.append(dict(path=path, module=module, areas=modules[path]["areas"],
            frozen_source_sha256=modules[path]["sha256"],
            owner=None, owner_status="live-producer-identity-unconfirmed",
            historical_last_change=dict(commit=history[0], author=history[1])))
    target = ROOT/"tests/h62/item2/audit-typing/ProvisionedCensus.lean"
    source = "-- Generated by scripts/h62/item2/audit-typing/provisioned_census.py\n"
    source += "import tests.h62.item2.«audit-typing».DeclarationCensus\n"
    source += "".join("import "+row["module"]+"\n" for row in inventory)
    source += "\n"+"".join("#audit_module "+row["module"]+"\n" for row in inventory)
    target.write_text(source)
    result = dict(base=BASE, selected=inventory,
        unprovisioned=sorted(set(modules)-built),
        limitations=["Historical authorship is not live ownership.",
            "Generated constants remain included with unresolved interface status.",
            "Selected-module census is not complete area coverage."])
    (EVIDENCE/"provisioned-module-inventory.json").write_text(json.dumps(result, sort_keys=True, indent=2)+"\n")
    print(json.dumps(dict(selected=len(selected), unprovisioned=len(result["unprovisioned"]))))

def main():
    lockpath = Path("/tmp/solidity-lean-feature-groups-20261025/writer.lock")
    lockpath.parent.mkdir(exist_ok=True)
    with lockpath.open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        generate()

if __name__ == "__main__":
    main()
