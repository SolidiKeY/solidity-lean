#!/usr/bin/env python3
"""Reproduce exact-type packages for all frozen module-map control declarations."""
from pathlib import Path
import sys
sys.dont_write_bytecode = True
import census

root = Path(__file__).resolve().parents[4]
rows = [r for p in census.module_paths(census.frozen(census.MAP)) if p.endswith("Controls.lean")
        for r in census.declarations(p,census.frozen(p))]
assert len(rows) == 93
terms = {
"ErrorReadWindowControls.populated": "⟨[0],by decide,True.intro⟩",
"ErrorReadWindowControls.older_byte": "⟨[0,255],True.intro⟩",
"ErrorOffsetWindowControls.populated": "⟨[165],[0],by decide,by decide,True.intro⟩",
"ErrorOffsetWindowControls.older_byte": "⟨[165],[0,255],True.intro⟩",
"PanicCallFrameControls.application": "⟨300,by decide,[17],True.intro⟩",
"PanicCallFrameControls.zero_receiver": "⟨300,[17],True.intro⟩",
"PanicCallFrameControls.emitted_member": "⟨300,by decide,True.intro⟩",
"PacketPrefixControls.boundary_applied": "⟨1,by rw [PacketPrefixControls.payload_length]; decide,True.intro⟩",
"PacketPrefixControls.byte_applied": "⟨1,by rw [PacketPrefixControls.payload_length]; decide,True.intro⟩",
"PacketPrefixControls.address_applied": "⟨1,by rw [PacketPrefixControls.payload_length]; decide,True.intro⟩",
"CallerWordBytesControls.wrong_symbolic": "⟨Evm.Slot.root 0,(fun _ => 0),True.intro⟩",
"CheckedAddArtifactControls.populated_artifact": "by\n  obtain ⟨out,assembled⟩ := CheckedAddArtifactControls.witnessed\n  exact ⟨out,assembled,True.intro⟩",
"CheckedAddArtifactControls.wrong_label": "⟨8,0,True.intro⟩",
"NativeParentWordControls.applied": "⟨1,by decide,[17],True.intro⟩",
"NativeParentWordControls.slot_is_not_value": "⟨Evm.Slot.root 0,True.intro⟩",
"MutatingEntryWordsControls.applied": "⟨[17],True.intro⟩",
}
for name in ["represented","numeric_load","loaded_repr","image","typed_application","loaded_then_restored","old_byte"]:
    terms["CallerWordBytesControls."+name] = "⟨⟨300,by decide⟩,True.intro⟩"
imports = list(dict.fromkeys(r["path"][:-5].replace("/", ".") for r in rows))
lines = ["import H62AbiWorld.WitnessSchema"]+["import "+m for m in imports]
lines += ["", "/-! Generated by generate_controls.py. Every frozen control declaration has one", "exact-type binder package, including those with no input binders. -/", "namespace H62.AbiWorld.ControlWitnesses", "open Solidity Solidity.Backend.AbiWorld", ""]
for row in rows:
    short = row["name"].removeprefix("Solidity.Backend.AbiWorld.")
    # Reviewed frozen controls not listed above have no binders in their type.
    term = terms.pop(short, "True.intro")
    label = short.replace(".", "_")+"_hypotheses"
    lines += [f"theorem {label} : hypotheses% {row['name']} :=", "  "+term,
              f"#print axioms {label}", ""]
assert not terms,terms
lines += ["end H62.AbiWorld.ControlWitnesses", ""]
(root/"tests/h62/item2/audit-abi-world/H62AbiWorld/ControlWitnesses.lean").write_text("\n".join(lines))
print("Generated 93 control packages")
