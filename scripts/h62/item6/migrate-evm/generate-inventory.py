"""Generate a test-only elaborated constant/type inventory (including constructors)."""
from pathlib import Path
import importlib.util
ROOT=Path(__file__).resolve().parents[4]
spec=importlib.util.spec_from_file_location("census",Path(__file__).with_name("census.py"))
c=importlib.util.module_from_spec(spec); spec.loader.exec_module(c)
imports="\n".join("import "+m for m,v in c.census(ROOT)["modules"].items() if v["assigned"])
body='''
open Lean

-- Raw expression representations retain exact elaborated types and levels.
-- Toolchain-generated auxiliaries are included; compare with source ownership.
#eval show CoreM Unit from do
  let env ← getEnv
  let entries := env.constants.toList.mergeSort (fun a b => decide (a.1.toString ≤ b.1.toString))
  for (name, info) in entries do
    let some idx := env.getModuleIdxFor? name | continue
    let moduleName := env.header.moduleNames[idx]!.toString
    unless moduleName.startsWith "Solidity.Evm." do continue
    let kind : String := match info with
      | .axiomInfo _ => "axiom"
      | .defnInfo _ => "definition"
      | .thmInfo _ => "theorem"
      | .opaqueInfo _ => "opaque"
      | .quotInfo _ => "quotient"
      | .inductInfo _ => "inductive"
      | .ctorInfo _ => "constructor"
      | .recInfo _ => "recursor"
    let row := Json.mkObj [
      ("module", toJson moduleName), ("name", toJson name.toString),
      ("kind", toJson kind), ("type_repr", toJson (reprStr info.type)),
      ("level_params", toJson (info.levelParams.map Name.toString))]
    IO.println row.compress
'''
output=ROOT/"tests/h62/item6/migrate-evm/Inventory.lean"
output.write_text("-- Generated by scripts/h62/item6/migrate-evm/generate-inventory.py\nimport Lean\n"+imports+"\n"+body)
print(output)

smoke=ROOT/"tests/h62/item6/migrate-evm/InventorySmoke.lean"
smoke.write_text("-- Generated inventory-helper acceptance fixture\nimport Lean\nimport Solidity.Evm.Machine\n"+body)
