#!/usr/bin/env python3
"""Generate the lane's H26 kernel-return signature freeze (no producer instance)."""
import json,pathlib,sys
root=pathlib.Path(__file__).resolve().parents[2]
fields=json.loads((root/'scripts/v14/creation-return-interface-v1.json').read_text())
text='''import Solidity.Backend.Creation.Immutables

/-! Generated by scripts/v14/generate-creation-return-interface.py.
H26 V1: kernel constructor-return observations only. Pending laws are fields,
not axioms or a concrete producer. No Source/profile/account/fetched-CREATE
correspondence is supplied. Existing concrete declarations remain unchanged. -/
namespace Solidity.Backend.Executable.CreationReturnInterfaceV1
open Solidity.Backend Solidity.Backend.Creation

/-- A genuine nonempty input and actual finite constructor execution. -/
structure Witness where
  artifact : Artifact Bool
  links : LinkTable artifact
  table : ImmutableTable artifact.runtime.length Bool
  addresses : Bool → Vector UInt8 20
  compatible : Creation.compatible table links.sites = true
  site : LinkSite artifact.runtime.length Bool
  present : site ∈ links.sites
  runtime_nonempty : artifact.runtime ≠ []
  args_nonempty : artifact.args ≠ []
  immutable_nonempty : table.patches ≠ []
  executed : let b := combinedArtifact artifact links table addresses compatible
    Exec b.payload b.payload [] [] (.returned b.runtime)

/-- Both obligations preserve the existing concrete theorem signatures.
An inhabitant is not supplied; consumers must retain this parameter explicitly.
The required witness rules out empty-only admission of the interface. -/
structure Producer where
  witness : Witness
'''
for n,ty in fields.items():text+='  '+n+' : '+ty.replace('\n','\n  ')+'\n'
text+='\nend Solidity.Backend.Executable.CreationReturnInterfaceV1\n'
p=root/'Solidity/Backend/Executable/CreationReturnInterfaceV1.lean'
if sys.argv[1:]==['--check']:
 if not p.exists() or p.read_text()!=text:raise SystemExit('stale V14 return interface')
else:p.write_text(text)
