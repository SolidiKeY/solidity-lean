#!/usr/bin/env python3
"""Heartbeat ratchet for the library modules (H1076): a checking-speed guard.

  ratchet.py build DIR TARGET...   lake build TARGET... and record heartbeats in DIR
  ratchet.py check DIR             compare what `build DIR` built with the baselines
  ratchet.py write DIR             update the baselines of the modules `build DIR` built
  ratchet.py write                 regenerate every baseline (library must be built)

`gate.sh touched` runs build and check when GATE_HEARTBEATS=1. After a merge, the
baselines are regenerated from the merged head and checked in:

  GATE_HEARTBEATS=1 GATE_LOGS=LOGS bash scripts/coord-tools/gate.sh touched
  python3 -B scripts/heartbeats/library/ratchet.py write LOGS/heartbeats

Baselines: Solidity.tsv and SolidityExamples.tsv beside this file, one line
`module<TAB>units` per module of that library root (units as in `maxHeartbeats`:
raw / 1000, rounded). Generated; never edit them by hand.

`build` is the gate's own `lake build` with two more weak arguments
(`-DElab.async=false`, so kernel checking counts, and `--plugin` HeartbeatLinter),
given through a copy of lakefile.toml; they change neither a build hash nor the
`.olean` that the same arguments without the plugin produce. Each module Lean
compiles writes DIR/records/<Module>.tsv: `first line, last line, raw heartbeats,
kind and name` per command. Records are also kept by Lake input hash, so a module
that a later build takes from Lake's cache still has its count. A target with no
record at all (built earlier without this step) is compiled once more, without
outputs; that is the only cost over the build.

`check` fails when a module exceeds its baseline by more than the tolerance
(GATE_HEARTBEATS_TOLERANCE percent, default TOLERANCE) and by more than FLOOR
units. In a module whose source the branch changed, new and edited commands are
set aside (they only print) and the others together are held to the baseline.
A decrease, a new module and a module without a record only print.
"""
import concurrent.futures, hashlib, json, os, pathlib, re, shutil, subprocess, sys, tempfile

TOLERANCE = 2.0  # percent; from the import-drift samples in the hb3 result
FLOOR = 50  # units; below this absolute growth a small module's drift is noise
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
ROOTS = ("Solidity", "SolidityExamples")
HEADER = "# generated by scripts/heartbeats/library/ratchet.py write; never edit by hand\n"


def lake_env():
    out = subprocess.check_output(["lake", "env"], cwd=ROOT, text=True)
    return dict(line.split("=", 1) for line in out.splitlines() if "=" in line)


class Tools:
    """The toolchain, the compiled plugin and the record store."""

    def __init__(self):
        self.env = lake_env()
        self.lean = self.env["LEAN"]
        source = (HERE / "HeartbeatLinter.lean").read_bytes()
        key = hashlib.sha256(source + self.env.get("LEAN_GITHASH", "").encode()).hexdigest()[:16]
        cache = os.environ.get("HEARTBEATS_STORE") or (
            os.path.join(self.env["LAKE_CACHE_DIR"], "heartbeats") if self.env.get("LAKE_CACHE_DIR")
            else str(ROOT / ".lake/build/heartbeats"))
        self.store = pathlib.Path(cache) / key
        self.plugin = self.store / "HeartbeatLinter.so"
        if not self.plugin.exists():
            self.store.mkdir(parents=True, exist_ok=True)
            with tempfile.TemporaryDirectory(dir=self.store) as tmp:
                c, so = os.path.join(tmp, "HeartbeatLinter.c"), os.path.join(tmp, "HeartbeatLinter.so")
                subprocess.check_call([self.lean, f"--root={HERE}", "-c", c, str(HERE / "HeartbeatLinter.lean")])
                leanc = os.path.join(os.path.dirname(self.lean), "leanc")
                subprocess.check_call([leanc, "-shared", "-DLEAN_EXPORTING", "-o", so, c])
                os.replace(so, self.plugin)
        self.args = ["-DElab.async=false", f"--plugin={self.plugin}"]

    def stored(self, module):
        """Where the record for the module's current Lake input hash is kept."""
        try:
            trace = json.loads((ROOT / ".lake/build/lib/lean" / (module.replace(".", "/") + ".trace")).read_text())
            return self.store / f"{trace['depHash']}.tsv"
        except (OSError, ValueError, KeyError):
            return None


def source(module):
    return module.replace(".", "/") + ".lean"


def read_record(path):
    rows = []
    for line in pathlib.Path(path).read_text().splitlines():
        first, last, raw, label = line.split("\t", 3)
        rows.append((int(first), int(last), int(raw), label))
    return rows


def build(directory, targets):
    directory = pathlib.Path(directory).resolve()
    records = directory / "records"
    records.mkdir(parents=True, exist_ok=True)
    (directory / "targets").write_text("".join(t + "\n" for t in targets))
    try:
        tools = Tools()
    except (OSError, subprocess.CalledProcessError, KeyError) as error:
        print(f"heartbeats: no plugin ({error}); plain build", file=sys.stderr)
        return subprocess.call(["lake", "build", *targets], cwd=ROOT)
    extra = "".join(json.dumps(a) + ", " for a in tools.args)
    lakefile, count = re.subn(r"(?m)^weakLeanArgs = \[", lambda m: m.group(0) + extra, (ROOT / "lakefile.toml").read_text())
    if not count:
        sys.exit("heartbeats: lakefile.toml has no weakLeanArgs to extend")
    (directory / "lakefile.toml").write_text(lakefile)
    status = subprocess.call(["lake", "-f", str(directory / "lakefile.toml"), "build", *targets], cwd=ROOT,
                             env={**os.environ, "HEARTBEATS_DIR": str(records)})
    if status == 0:
        for record in records.glob("*.tsv"):
            kept = tools.stored(record.stem)
            if kept:
                shutil.copyfile(record, kept)
    return status


def measure(tools, module, records):
    """Compile one built module again, without outputs, for its record."""
    setup = ROOT / ".lake/build/ir" / (module.replace(".", "/") + ".setup.json")
    weak = json.loads(re.search(r"(?m)^weakLeanArgs = (\[.*\])$", (ROOT / "lakefile.toml").read_text()).group(1))
    cmd = [tools.lean, *weak, *tools.args, source(module)] + (["--setup", str(setup)] if setup.exists() else [])
    env = {**os.environ, **tools.env, "HEARTBEATS_DIR": str(records), "LEAN_NUM_THREADS": "1"}
    done = subprocess.run(cmd, cwd=ROOT, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return done.returncode == 0


def collect(directory, modules, fresh_only=False):
    """module -> rows, from this build's records, else the store, else a compile."""
    records = pathlib.Path(directory) / "records"
    records.mkdir(parents=True, exist_ok=True)
    out, missing = {}, []
    tools = None
    for module in modules:
        record = records / f"{module}.tsv"
        if not record.exists() and not fresh_only:
            tools = tools or Tools()
            kept = tools.stored(module)
            if kept and kept.exists():
                shutil.copyfile(kept, record)
            elif kept and (ROOT / source(module)).is_file():
                missing.append(module)
        if record.exists():
            out[module] = read_record(record)
    if missing:
        print(f"heartbeats: compiling {len(missing)} module(s) that have no record", file=sys.stderr)
        with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 1) as pool:
            for module, ok in zip(missing, pool.map(lambda m: measure(tools, m, records), missing)):
                record = records / f"{module}.tsv"
                if ok and record.exists():
                    shutil.copyfile(record, tools.stored(module))
                    out[module] = read_record(record)
    return out


def library_modules():
    """root -> the modules its (generated) root file imports."""
    return {root: [line.split()[1] for line in (ROOT / f"{root}.lean").read_text().splitlines()
                   if line.startswith("import ") and len(line.split()) > 1] for root in ROOTS}


def read_baselines():
    base = {}
    for root in ROOTS:
        path = HERE / f"{root}.tsv"
        if path.exists():
            for line in path.read_text().splitlines():
                if line and not line.startswith("#"):
                    module, units = line.split("\t")
                    base[module] = int(units)
    return base


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True)


def added_lines(merge, path):
    """Line ranges the branch added or changed in path; None when it is unchanged."""
    diff = git("diff", "-U0", "--no-renames", merge, "--", path)
    if not diff:
        return None
    ranges = []
    for start, count in re.findall(r"(?m)^@@ -\S+ \+(\d+)(?:,(\d+))? @@", diff):
        if count != "0":
            ranges.append((int(start), int(start) + int(count or 1) - 1))
    return ranges


def check(directory):
    tolerance = float(os.environ.get("GATE_HEARTBEATS_TOLERANCE") or TOLERANCE)
    targets_file = pathlib.Path(directory) / "targets"
    targets = targets_file.read_text().split() if targets_file.exists() else []
    rows = collect(directory, targets)
    base = read_baselines()
    merge = git("merge-base", os.environ.get("GATE_BASE", "origin/master"), "HEAD").strip()
    fails = 0
    for module in targets:
        if module not in rows:
            print(f"no record {module}")
            continue
        total = sum(r[2] for r in rows[module]) / 1000
        if module not in base:
            if total > FLOOR:
                print(f"new module {module}: {total:.0f}")
            continue
        old, value, label = base[module], total, module
        added = added_lines(merge, source(module))
        if added is not None:
            edited = [r for r in rows[module] if any(r[0] <= b and a <= r[1] for a, b in added)]
            value = total - sum(r[2] for r in edited) / 1000
            label = f"{module} (commands the branch left unchanged)"
            print(f"changed {module}: {total:.0f} (baseline {old}); {len(edited)} new or edited command(s), {total - value:.0f}")
        if value > old * (1 + tolerance / 100) and value - old > FLOOR:
            fails += 1
            print(f"FAIL {label}: {value:.0f} > {old} (+{100 * (value - old) / max(old, 1):.1f}%, tolerance {tolerance:g}%)")
        elif added is None and value < old * (1 - tolerance / 100) and old - value > FLOOR:
            print(f"decrease {module}: {value:.0f} < {old}")
    print(f"heartbeats: {len(rows)} of {len(targets)} target(s) compared, {fails} over baseline")
    return 1 if fails else 0


def write(directory):
    libraries = library_modules()
    base = read_baselines()
    if directory is None:
        with tempfile.TemporaryDirectory() as tmp:
            rows = collect(tmp, [m for modules in libraries.values() for m in modules])
        lacking = [m for modules in libraries.values() for m in modules if m not in rows]
        if lacking:
            sys.exit(f"heartbeats: no record for {len(lacking)} module(s), e.g. {lacking[0]}; "
                     "run `lake build Solidity SolidityExamples` first")
        base = {}
    else:
        rows = collect(directory, [p.stem for p in (pathlib.Path(directory) / "records").glob("*.tsv")], fresh_only=True)
    for module, record in rows.items():
        base[module] = round(sum(r[2] for r in record) / 1000)
    seen = set()
    for root in ROOTS:
        modules = sorted(m for m in set(libraries[root]) - seen if m in base)
        seen.update(libraries[root])
        (HERE / f"{root}.tsv").write_text(HEADER + "".join(f"{m}\t{base[m]}\n" for m in modules))
    print(f"heartbeats: wrote {len(rows)} module(s)", file=sys.stderr)
    return 0


def main(argv):
    if len(argv) >= 3 and argv[0] == "build":
        return build(argv[1], argv[2:])
    if len(argv) == 2 and argv[0] == "check":
        return check(argv[1])
    if argv and argv[0] == "write" and len(argv) <= 2:
        return write(argv[1] if len(argv) == 2 else None)
    sys.exit(__doc__.split("\n\n")[1])


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
