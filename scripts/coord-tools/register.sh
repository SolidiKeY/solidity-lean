#!/usr/bin/env bash
# register.sh [--check] [MODULE...]: the generated library roots.
#
# Each root below imports every module under its source prefix, sorted, minus
# the excluded subtrees (other libraries' modules and Solidity/Scratch/). The
# roots are a function of the file tree, so a lane never edits them by hand:
# it runs this script after adding, moving or deleting a module, and the
# integrator regenerates them after a merge instead of resolving their hunks
# (`docs/parallelism.md`, "Shared registries").
#
#   register.sh            rewrite every root that differs from the tree
#   register.sh MODULE...  the same, after checking that each MODULE exists
#   register.sh --check    write nothing; exit 1 and list the differences
#                          when a root is out of date
#
# Exit 0 = roots up to date (or rewritten), 1 = --check found a stale root,
# 2 = invalid input or another error.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
exec python3 - "$@" <<'PY'
import pathlib,re,subprocess,sys

# H109: the three slow examples and DecisionGaps reverse-import closure.
SLOW_EXAMPLES = ['Solidity.Examples.DecisionGaps', 'Solidity.Examples.DecisionAPF', 'Solidity.Examples.DecisionBlocks', 'Solidity.Examples.DecisionGapCore', 'Solidity.Examples.DecisionGapHashes', 'Solidity.Examples.DecisionGapKInt', 'Solidity.Examples.DecisionLedger', 'Solidity.Examples.DecisionOperators', 'Solidity.Examples.DecisionRefutations', 'Solidity.Examples.DecisionResidue', 'Solidity.Examples.DecisionStorageArrays', 'Solidity.Examples.DecisionThreeKindCoverage', 'Solidity.Examples.Tactics.OpenLoops', 'Solidity.Examples.Tactics.RevertData', 'Solidity.Examples.Tactics.OpenLoops.RowsNine']

# (root file, source directory, module prefix, excluded module prefixes, header)
ROOTS=[
    ("Solidity.lean",".","Solidity",
     ["Solidity.Scratch","Solidity.Corpus","Solidity.TestSuite","Solidity.Solkey.TestSuite","Solidity.Examples"],
     ["-- The root of the `Solidity` library: every module of the default build but the examples.",
      "-- Generated by `scripts/coord-tools/register.sh` from the file tree; do not",
      "-- edit. `Solidity/Examples/`, `Solidity/Corpus/` and `Solidity/TestSuite/`",
      "-- (with `Solidity/Solkey/TestSuite.lean`) belong to their own libraries, and",
      "-- `Solidity/Scratch/` to none."]),
    ("SolidityExamples.lean",".","Solidity.Examples",SLOW_EXAMPLES,
     ["-- The root of the `SolidityExamples` library: the worked examples, a default target.",
      "-- Generated by `scripts/coord-tools/register.sh` from the file tree; do not edit."]),
    ("Solidity/Goals.lean",".","Solidity.Goals",[],
     ["-- Every goal module under `Solidity/Goals/`, for the roadmap (`Solidity/Examples/Goals.lean`).",
      "-- Generated by `scripts/coord-tools/register.sh` from the file tree; do not edit: a new goal",
      "-- goes in its own module, so goal steps never share a file."]),
    ("Bridge/SolidityBridge.lean","Bridge","SolidityBridge",[],
     ["-- The root of the bridge: the core's notions as Mathlib's and CSLib's.",
      "-- Generated by `scripts/coord-tools/register.sh` from the file tree; do not edit."]),
]

def under(m,prefix): return m==prefix or m.startswith(prefix+".")

def modules(src,prefix,excluded,exact=False):
    # Tracked files and untracked ones git does not ignore: a new module counts
    # before its first commit, an ignored scratch file never does.
    d=prefix.replace(".","/")
    files=subprocess.run(["git","-C",src,"ls-files","-co","--exclude-standard","--",d],
                         capture_output=True,text=True,check=True).stdout.split("\n")
    out=[]
    for f in files:
        if not f.endswith(".lean") or not (pathlib.Path(src)/f).is_file(): continue
        m=f[:-len(".lean")].replace("/",".")
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)+",m):
            raise ValueError(f"not a module name: {f} (rename or delete it)")
        if not any(m == x if exact else under(m,x) for x in excluded): out.append(m)
    return sorted(set(out))

def render(header,mods): return "\n".join(header+["import "+m for m in mods])+"\n"

def main():
    args=sys.argv[1:]; check=bool(args and args[0]=="--check")
    if check: args=args[1:]
    if check and args: raise ValueError("--check takes no modules")
    # A root whose source directory is absent (a sparse checkout) is left alone.
    gen=[(r,modules(src,prefix,excluded,exact=(r == "SolidityExamples.lean")),header) for r,src,prefix,excluded,header in ROOTS
         if (pathlib.Path(src)/prefix.replace(".","/")).is_dir()]
    if pathlib.Path("Solidity/Examples").is_dir():
        available = set(modules(".", "Solidity.Examples", []))
        missing = sorted(set(SLOW_EXAMPLES) - available)
        sparse = subprocess.run(["git", "config", "--bool", "core.sparseCheckout"],
                                capture_output=True, text=True).stdout.strip() == "true"
        if missing and not sparse: raise ValueError("missing H109 slow examples: " + ", ".join(missing))
        gen.append(("SoliditySlowExamples.lean", sorted(set(SLOW_EXAMPLES) & available),
                    ["-- The non-default slow examples library (H109).",
                     "-- Generated by `scripts/coord-tools/register.sh`; do not edit."]))
    known={m for _,mods,_ in gen for m in mods}
    for m in args:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)+",m) or m not in known:
            raise ValueError("unknown or excluded module: "+m)
    stale=0
    for root,mods,header in gen:
        path=pathlib.Path(root); want=render(header,mods)
        have=path.read_text() if path.is_file() else ""
        if have==want: continue
        if check:
            stale=1
            got={l.split()[1] for l in have.splitlines() if l.startswith("import ") and len(l.split())>1}
            for m in sorted(set(mods)-got): print(f"{root}: missing import {m}")
            for m in sorted(got-set(mods)): print(f"{root}: extra import {m}")
            if set(mods)==got: print(f"{root}: not in generated form (order or comments)")
        else: path.write_text(want)
    if stale: print("register: stale roots; run scripts/coord-tools/register.sh",file=sys.stderr)
    return stale
try: sys.exit(main())
except Exception as e: print("register: "+str(e),file=sys.stderr); sys.exit(2)
PY
