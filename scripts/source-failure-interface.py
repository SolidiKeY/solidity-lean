#!/usr/bin/env python3
"""Generate H16 cursor declaration/signature probes from the actual module."""
import argparse,re,json,hashlib
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('output',type=Path);args=p.parse_args()
module='Solidity.Source.FailureCursor';source=root/'Solidity/Source/FailureCursor.lean';text=source.read_text()
names=re.findall(r'^(?:abbrev|structure|inductive|def)\s+([A-Za-z_][A-Za-z0-9_.]*[?]?)',text,re.M)
assert names and len(names)==len(set(names))
assert 'Cursor.stop?' in names, 'question-mark declaration omitted'
prefix='Solidity.Source.FailureExecution.'
args.output.write_text('/- Generated by scripts/source-failure-interface.py; no proof placeholders. -/\nimport '+module+'\n'+'\n'.join('#print '+prefix+n for n in names)+'\n'+'\n'.join('#print axioms '+prefix+n for n in names if n.startswith(('Cursor.','Stop.','FrameBudget.','RuntimePlan.')))+'\n')
print(json.dumps({'module':module,'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'declarations':names,'signature_file':str(args.output)}))
