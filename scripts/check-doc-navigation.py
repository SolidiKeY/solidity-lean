#!/usr/bin/env python3
"""Keep tracked Markdown discoverable from AGENTS.md and CLAUDE.md.

--write regenerates the catalog. Add new documents to Git before running it.
Fragment inputs are represented by their generated documents, not catalog rows.
This checks discovery, not semantic freshness or every legacy URL/anchor.
"""
import argparse
from collections import defaultdict, deque
from pathlib import Path
import posixpath
import re
import subprocess
import sys
from urllib.parse import quote, unquote

ROOT = Path(__file__).resolve().parent.parent
CATALOG = 'docs/document-index.md'


def documents():
    output = subprocess.check_output(
        ['git', 'ls-files', '-z', '--', '*.md'], cwd=ROOT
    ).decode()
    return {p for p in output.split('\0') if p and (ROOT / p).is_file()} | {CATALOG}


def fragment(path):
    return (path.startswith(('docs/README.d/', 'docs/module-map.d/', 'TERRA-TODO.d/'))
            or (path.startswith('docs/module-map/')
                and len(Path(path).parts) > 3 and Path(path).parts[2].endswith('.d')))


def group(path):
    if 'vendor/' in path or 'THIRD_PARTY_NOTICES' in path:
        return 'Vendored packages and attribution'
    if path.startswith('docs/module-map/'):
        return 'Module reference'
    if path.startswith('docs/feature-work/'):
        name = Path(path).name
        if name.startswith(('integration-', 'cloud-integration-')):
            return 'Integration records'
        if name.startswith(('h28-', 'h55-', 'h62-')):
            return 'Audit and maintenance lanes'
        return 'Feature support and interfaces'
    if path.startswith('docs/'):
        return 'Guides, audits and performance'
    if path.startswith(('tests/', 'Bridge/tests/')):
        return 'Tests, fixtures and retained proposals'
    if path.startswith(('scripts/', 'vscode/', 'web/')):
        return 'Tools and editors'
    if path.startswith('Solidity/'):
        return 'Library conventions'
    return 'Project and agent guidance'


def render(paths):
    groups = defaultdict(list)
    for path in sorted(paths - {CATALOG}):
        if not fragment(path):
            groups[group(path)].append(path)
    lines = [
        '<!-- Generated by scripts/check-doc-navigation.py --write; do not edit. -->',
        '# Documentation catalog', '',
        'Start with the [topic guide](README.md) and follow the documents relevant',
        'to the task. This catalog makes every retained Markdown document discoverable;',
        'it does not require reading every document for every task. Generator input',
        'fragments are represented by their combined documents.', '',
        'Integration and lane records describe their recorded snapshots. Consult the',
        '[coverage plan](coverage-plan.md) and current feature document for support',
        'and open obligations. Test proposals remain proposals until applied.', '',
    ]
    for label in sorted(groups):
        lines += ['## ' + label, '']
        for path in groups[label]:
            target = quote(posixpath.relpath(path, 'docs'), safe='/')
            link_label = path.replace("\\", "\\\\").replace("[", r"\[").replace("]", r"\]")
            lines.append(f'- [{link_label}]({target})')
        lines.append('')
    return '\n'.join(lines)


def visible_markdown(text):
    """Ignore examples/comments that do not provide clickable navigation."""
    text = re.sub(r'<!--.*?-->|<!--.*\Z', '', text, flags=re.DOTALL)
    lines = []
    fence = None
    for line in text.splitlines(keepends=True):
        if fence is not None:
            if re.fullmatch(r' {0,3}' + re.escape(fence[0])
                            + '{' + str(len(fence)) + r',}\s*', line):
                fence = None
            continue
        match = re.match(r' {0,3}(`{3,}|~{3,})', line)
        if match:
            fence = match.group(1)
            continue
        if line.startswith(('    ', '\t')):
            continue
        lines.append(line)
    # Delimiter runs must match exactly; a longer run is not a closing span.
    return re.sub(r'(?<!`)(`+)(?!`)(.*?)\1(?!`)', '', ''.join(lines),
                  flags=re.DOTALL)


def links(path, text, paths):
    text = visible_markdown(text)
    refs = re.findall(r'\]\(<?([^\s)>]+)', text)
    # Claude Code imports the shared instructions through its existing @ directive.
    if path == 'CLAUDE.md':
        refs += re.findall(r'^@([^\s]+\.md)\s*$', text, re.MULTILINE)
    for ref in refs:
        if '://' in ref:
            continue
        target = unquote(ref.split('#', 1)[0])
        if not target:
            continue
        dest = posixpath.normpath(posixpath.join(posixpath.dirname(path), target))
        if dest in paths:
            yield dest
        elif dest.rstrip('/') + '/README.md' in paths:
            yield dest.rstrip('/') + '/README.md'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    paths = documents()
    catalog = ROOT / CATALOG
    expected = render(paths)
    if args.write:
        catalog.parent.mkdir(parents=True, exist_ok=True)
        catalog.write_text(expected)
    if not catalog.is_file() or catalog.read_text() != expected:
        print('doc-navigation: stale catalog; run python3 scripts/check-doc-navigation.py --write', file=sys.stderr)
        return 1
    graph = {p: set(links(p, (ROOT / p).read_text(), paths)) for p in paths}
    required = {p for p in paths if not fragment(p)}
    for entry in ('AGENTS.md', 'CLAUDE.md'):
        if entry not in paths:
            print(f'doc-navigation: missing entry point {entry}', file=sys.stderr)
            return 1
        seen, queue = {entry}, deque([entry])
        while queue:
            for dest in graph[queue.popleft()] - seen:
                seen.add(dest)
                queue.append(dest)
        missing = sorted(required - seen)
        if missing:
            print(f'doc-navigation: unreachable from {entry}:', file=sys.stderr)
            print('\n'.join(missing), file=sys.stderr)
            return 1
    print(f'doc-navigation: {len(required)} documents reachable from both agent entry points')
    return 0


if __name__ == '__main__':
    sys.exit(main())
