#!/usr/bin/env python3
"""Generate the H14 P8a-SPEC root imports and exact interface probe."""
import argparse,re,json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
p=argparse.ArgumentParser();p.add_argument('--write',action='store_true');p.add_argument('--signatures',type=Path);a=p.parse_args()
modules=['Solidity.Lowering.P8.FrozenInterface','Solidity.Source.FailureResources','Solidity.Lowering.P8.FailureProjection','Solidity.Lowering.P8.SourceRealization']
path=root/'Solidity.lean';text=path.read_text();lines=text.splitlines()
code=[];i=0;depth=0
while i<len(text):
    if text.startswith('/-',i):depth+=1;code.extend('  ');i+=2
    elif depth and text.startswith('-/',i):depth-=1;code.extend('  ');i+=2
    elif depth:code.append('\n' if text[i]=='\n' else ' ');i+=1
    elif text.startswith('--',i):
        end=text.find('\n',i);end=len(text) if end<0 else end
        code.extend(' '*(end-i));i=end
    else:code.append(text[i]);i+=1
assert depth==0,'unterminated Lean comment'
imports=[]
for line in ''.join(code).splitlines():
    if not line.strip():continue
    match=re.fullmatch(r'\s*import\s+([A-Za-z_][A-Za-z0-9_.]*)\s*',line)
    assert match,'unsupported root declaration: '+line
    imports.append(match.group(1))
for module in modules:
    assert (root/(module.replace('.','/')+'.lean')).is_file(),module
    assert imports.count(module)<=1,'duplicate module registration: '+module
    if module not in imports:lines.append('import '+module)
result='\n'.join(lines)+'\n'
if a.write:path.write_text(result)
else:assert result==text,'missing generated P8 imports'
if a.signatures:
    names=['Solidity.Source.FailureResources.Bound','Solidity.Source.FailureResources.NoFail','Solidity.Source.FailureResources.Bound.failures_with','Solidity.Source.FailureResources.no_horizon_retraction','Solidity.Lowering.P8.SpecFailures.points','Solidity.Lowering.P8.SpecFailures.withPoints','Solidity.Lowering.P8.SpecFailures.failureFree','Solidity.Lowering.P8.SpecExecution.run','Solidity.Lowering.P8.SpecExecution.MachineAgreement','Solidity.Lowering.P8.P8a.FailureProjection','Solidity.Lowering.P8.P8a.SourceRealization']
    a.signatures.write_text('/- Generated by scripts/p8-spec-interface.py; no proof placeholders. -/\n'+'\n'.join('import '+m for m in modules)+'\n'+'\n'.join('#print '+n for n in names)+'\n#print axioms Solidity.Source.FailureResources.no_horizon_retraction\n')
print(json.dumps({'modules':modules,'rootChanged':text!=result,'interface':str(a.signatures) if a.signatures else None}))
