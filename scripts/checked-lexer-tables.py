#!/usr/bin/env python3
"""Generate the byte-pattern tables of the checked lexer (G08).

Writes `Solidity/Frontend/Checked/Tables.lean`: the keyword, word and
punctuation tables as `match`es on byte literals, which the kernel evaluates
as a decision tree (a lookup through `String` spellings costs a conversion
per entry).  `Solidity/Frontend/Checked/LexExamples.lean` checks the tables
against the spellings in `Token.lean` (`Kw.bytes_spell`, …).

Usage: python3 scripts/checked-lexer-tables.py [--check]
"""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
tok = (root / "Solidity/Frontend/Checked/Token.lean").read_text()

def spells(fn):
    body = tok.split(f"def {fn} :")[1].split("\n\n")[0]
    return re.findall(r"\| \.(\w+) => \"([^\"]*)\"", body)

kws = spells("Kw.spell")
yks = spells("YulKw.spell")
puncts = spells("Punct.spell")
reserved = re.findall(r'"(\w+)"', tok.split("def reservedKeywords")[1].split("\n\n")[0])
denoms = ["wei", "gwei", "ether", "seconds", "minutes", "hours", "days", "weeks", "years"]

def pat(s, tail=None):
    bs = [str(ord(c)) for c in s]
    return " :: ".join(bs + [tail]) if tail else "[" + ", ".join(bs) + "]"

out = []
w = out.append
w("import Solidity.Frontend.Checked.Token\n")
w("/-!\n# Byte tables of the checked lexer (G08)\n")
w("Generated by `scripts/checked-lexer-tables.py` from the spellings in")
w("`Solidity/Frontend/Checked/Token.lean`; do not edit.  Matches on byte")
w("literals, so the kernel evaluates a lookup as a decision tree.  The tables")
w("agree with the spellings (`Kw.bytes_spell`, `Punct.bytes_spell`,")
w("`YulKw.bytes_spell`, in `Solidity/Frontend/Checked/LexExamples.lean`).\n-/\n")
w("namespace Solidity.Frontend.Checked\n\nopen Solidity.Source\n")
for name, items in [("Kw", kws), ("YulKw", yks), ("Punct", puncts)]:
    w(f"/-- The bytes of a `{name}` spelling. -/")
    w(f"def {name}.bytes : {name} → Bytes")
    for c, s in items:
        w(f"  | .{c} => {pat(s)}")
    w("")
w("/-- What an exact word of Solidity mode is, before the numbered type")
w("names: a token, a reserved keyword, or another word. -/")
w("inductive WordClass where\n  | tok (t : Tok)\n  | reserved\n  | other\n")
w("/-- The fixed words of Solidity mode. -/")
w("def solWordTable : Bytes → WordClass")
for c, s in kws:
    w(f"  | {pat(s)} => .tok (.kw .{c})")
for s in ["address", "bool", "string"]:
    w(f"  | {pat(s)} => .tok (.elem .{s})")
for d in denoms:
    w(f"  | {pat(d)} => .tok (.denom .{d})")
w(f"  | {pat('true')} => .tok (.bool true)")
w(f"  | {pat('false')} => .tok (.bool false)")
for s in reserved:
    w(f"  | {pat(s)} => .reserved")
w("  | _ => .other\n")
w("/-- The fixed words of Yul mode. -/")
w("def yulWordTable : Bytes → Option Tok")
for c, s in yks:
    w(f"  | {pat(s)} => some (.yulKw .{c})")
w(f"  | {pat('true')} => some (.bool true)")
w(f"  | {pat('false')} => some (.bool false)")
w("  | _ => none\n")
w("/-- The punctuation spelled exactly by a lexeme. -/")
w("def punctExact : Bytes → Option Punct")
for c, s in puncts:
    w(f"  | {pat(s)} => some .{c}")
w("  | _ => none\n")
w("end Solidity.Frontend.Checked")
text = "\n".join(out) + "\n"
dst = root / "Solidity/Frontend/Checked/Tables.lean"
if "--check" in sys.argv:
    if dst.read_text() != text:
        print("Tables.lean is stale; run scripts/checked-lexer-tables.py"); sys.exit(1)
    print("Tables.lean up to date")
else:
    dst.write_text(text)
