def cache_dir(repo, rev):
    return Path(repo) / CACHE_ROOT / rev


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------- extraction ----

def elan_env(**extra):
    env = dict(os.environ, **extra)
    env['PATH'] = str(Path.home() / '.elan/bin') + os.pathsep + env.get('PATH', '')
    return env


def restore_artifacts(repo):
    subprocess.run([sys.executable, 'scripts/ci/restore-lake-artifacts.py'], cwd=repo,
                   env=elan_env(), check=True)


def run_gate(repo, lean_file, env_extra, logs):
    env = elan_env(**env_extra, GATE_LOGS=str(logs))
    shutil.rmtree(logs, ignore_errors=True)
    r = subprocess.run(['bash', 'scripts/coord-tools/gate.sh', 'per-file', str(lean_file)],
                       cwd=repo, env=env)
    return r.returncode, (Path(logs) / '1.log')


def extract(repo, rev):
    repo = Path(repo).resolve()
    if subprocess.run(['git', '-C', str(repo), 'diff', '--quiet', rev, '--', '*.lean', ':(exclude)scripts/lean-inventory/**']).returncode:
        sys.exit('extract: tracked Lean sources differ from ' + rev)
    untracked = S.git(repo, 'ls-files', '--others', '--exclude-standard', '--', '*.lean').decode()
    if untracked.strip():
        sys.exit('extract: untracked Lean files present:\n' + untracked)
    out = cache_dir(repo, rev)
    out.mkdir(parents=True, exist_ok=True)
    work = repo / CACHE_ROOT / 'work'
    work.mkdir(parents=True, exist_ok=True)
    groups = [('lib', list(S.LIB_ROOTS))] + [('exe:' + e, [m]) for m, e in S.EXE_ROOTS.items()]
    build_logs = {}
    for g, mods in groups:
        if g == 'lib':
            f = (work / 'Build-lib.lean')
            f.write_text(''.join(f'import {m}\n' for m in mods))
            f = f.relative_to(repo)
        else:
            # An executable root is no importable module; checking its own file builds
            # its imports, and Extract.lean elaborates it again over them.
            f = mods[0] + '.lean'
            # Lake leaves cache-fetched imports out of .lake/build until restored.
            restore_artifacts(repo)
        code, log = run_gate(repo, f, {}, work / ('gl-' + g.replace(':', '-')))
        if code:
            sys.exit(f'extract: build of {g} failed; see {log}')
        build_logs[g] = log.read_text()
    # Earlier runs of the same build (an interrupted build resumed by this one) keep the
    # times of the modules they compiled; .lake/lean-inventory/timing/*.log holds them.
    earlier = sorted((repo / CACHE_ROOT / 'timing').glob('*.log'))
    (out / 'build.log').write_text(''.join(p.read_text() for p in earlier) + build_logs['lib'])
    restore_artifacts(repo)
    listing = work / 'modules.tsv'
    listing.write_text(''.join(f'{g}\t{m}\n' if g == 'lib' else f'{g}\t{m}\t{m}.lean\n'
                               for g, mods in groups for m in mods))
    graph = work / 'graph.jsonl'
    code, log = run_gate(repo, 'scripts/lean-inventory/Extract.lean',
                         {'LEAN_INVENTORY_OUT': str(graph), 'LEAN_INVENTORY_MODULES': str(listing)},
                         work / 'gl-extract')
    if code:
        sys.exit(f'extract: Extract.lean failed; see {log}')
    records = [json.loads(line) for line in graph.read_text().splitlines()]
    if records[-1].get('r') != 'end':
        sys.exit('extract: truncated graph')
    with gzip.open(out / 'graph.jsonl.gz', 'wt', compresslevel=6) as f:
        for r in records:
            f.write(json.dumps(r, sort_keys=True) + '\n')
    # Anonymous uses: .ilean usages outside every declaration range of their module.
    ranges, modules = {}, set()
    for r in records:
        if r.get('g') != 'lib':
            continue
        if r['r'] == 'module':
            modules.add(r['m'])
        elif r['r'] == 'const' and 'range' in r:
            ranges.setdefault(r['m'], []).append(r['range'])
    paths = {S.module_name(p): p for p, _ in S.tracked(repo, rev) if p.endswith('.lean')}
    anon, ilean_digest, missing = {}, hashlib.sha256(), []
    lib_dir = repo / '.lake/build/lib/lean'
    olean_digest = hashlib.sha256()
    for m in sorted(modules):
        rel = m.replace('.', '/')
        il, ol = lib_dir / (rel + '.ilean'), lib_dir / (rel + '.olean')
        if not il.exists() or not ol.exists():
            missing.append(m)
            continue
        olean_digest.update(f'{m} {sha256_file(ol)}\n'.encode())
        ilean_digest.update(f'{m} {sha256_file(il)}\n'.encode())
        data = json.loads(il.read_text())
        if data.get('module') != m:
            sys.exit(f'extract: {il} names module {data.get("module")}')
        spans = sorted(ranges.get(m, []))
        uses = []
        for key, entry in data['references'].items():
            ident = json.loads(key)
            if 'c' not in ident:
                continue
            name = ident['c']['n']
            for u in entry.get('usages', []):
                line = u[0] + 1
                if not any(a <= line <= b for a, b in spans):
                    uses.append([line, name])
        if uses:
            anon[m] = sorted(set(map(tuple, uses)))
    identity = {
        'revision': rev,
        'lean_tree_id': S.lean_tree_id(S.tracked(repo, rev)),
        'toolchain': S.blobs(repo, [dict(S.tracked(repo, rev))['lean-toolchain']]).popitem()[1].strip(),
        'lean_version': records[0]['lean'], 'lean_githash': records[0]['githash'],
        'extractor_blob': dict(S.tracked(repo, rev)).get('scripts/lean-inventory/Extract.lean')
        or S.git(repo, 'hash-object', 'scripts/lean-inventory/Extract.lean').decode().strip(),
        'groups': {g: mods for g, mods in groups},
        'olean_digest': olean_digest.hexdigest(), 'ilean_digest': ilean_digest.hexdigest(),
        'missing_compiled': missing,
        'build_command': 'bash scripts/coord-tools/gate.sh per-file '
                         + str((work / 'Build-lib.lean').relative_to(repo)),
        'extract_command': 'LEAN_INVENTORY_OUT=... LEAN_INVENTORY_MODULES=... bash '
                           'scripts/coord-tools/gate.sh per-file scripts/lean-inventory/Extract.lean',
    }
    (out / 'anon.json').write_text(json.dumps({m: [list(u) for u in v] for m, v in anon.items()},
                                              sort_keys=True))
    identity['graph_sha256'] = sha256_file(out / 'graph.jsonl.gz')
    identity['anon_sha256'] = sha256_file(out / 'anon.json')
    identity['build_log_sha256'] = sha256_file(out / 'build.log')
    (out / 'identity.json').write_text(json.dumps(identity, indent=1, sort_keys=True) + '\n')
    print('extract: wrote', out)


