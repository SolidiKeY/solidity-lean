"""Declaration-reachability inventory of the seven Lean areas (plan step k1-lean-inventory).

    python3 -B scripts/lean-inventory/inventory.py --repo . --revision REV --output scripts/lean-inventory.json [--check]
    python3 -B scripts/lean-inventory/inventory.py --repo . --revision REV --extract

`--extract` (run once per revision, on a checkout whose Lean sources equal REV) builds the
libraries through `scripts/coord-tools/gate.sh per-file`, restores Lake artifacts, runs
`Extract.lean` on the built `.olean` files and stores the elaborated graph, the anonymous
uses read from the `.ilean` files, the build log and the input identities under
`.lake/lean-inventory/REV/` (ordinary ignored build storage, never committed).

Generation reads only Git objects at REV and that cache, so it does not depend on the
working tree. `--check` regenerates in memory, fails on any byte difference from the
output file, and runs the independent checker (`checker.py`), which recomputes coverage,
grouping, roots, closed sets, witnesses, gap effects, aggregation and metadata.

The kernel theorem `Solidity.LeanInventory.inventory_sound` (InventorySound.lean)
certifies the abstract certificate reasoning only: not this extraction's completeness,
any elapsed time, Git recovery or deletion safety.
"""
