def digest(items):
    h = hashlib.sha256()
    for x in sorted(items):
        h.update((x + '\n').encode())
    return h.hexdigest()


def render(state):
    inp = state['inp']
    mi = state['module_info']
    facts = state['facts']
    rows = state['rows']
    measured, fetched = timings(inp)
    prov = {
        'source': 'Lake job time of one build of this revision (lake lean on the library roots '
                  'through gate.sh per-file)',
        'toolchain': inp.toolchain,
        'command': inp.identity['build_command'],
        'context': 'Lake artifact cache seeded by scripts/ci/fetch-lake-cache.sh; 4-core VM, '
                   'parallel Lake jobs; Lean sources identical to the analyzed revision '
                   f'(lean_tree_id {inp.lean_tree_id[:16]})',
        'outcome': 'build succeeded; build.log sha256 ' + inp.identity['build_log_sha256'],
    }
    fam_members = {}
    for m, info in mi.items():
        fam_members.setdefault(info['family'], []).append(m)
    decls_of = {}
    for d in facts.decls:
        decls_of.setdefault(facts.family(d), []).append(d)
    gap_list = facts.gaps
    families = []
    totals = {'modules': 0, 'lines': 0, 'decls': 0, 'pseudo': 0, 'families': 0,
              'verdicts': {v: 0 for v in CL.VERDICTS}, 'decl_verdicts': {v: 0 for v in CL.VERDICTS},
              'measured_modules': 0, 'unavailable_modules': 0, 'measured_ms': 0}
    areas = {}
    for fam in sorted(fam_members):
        members = sorted(fam_members[fam], key=lambda m: mi[m]['path'])
        ds = sorted(decls_of.get(fam, []))
        verdicts = [rows[d]['verdict'] for d in ds]
        verdict = CL.family_verdict(verdicts)
        counts = {v: verdicts.count(v) for v in CL.VERDICTS}
        mem_rows = []
        t_meas = t_un = t_ms = 0
        for m in members:
            n_decl = sum(1 for d in ds if facts.decl_module[d] == m and '@' not in d)
            n_pseudo = sum(1 for d in ds if facts.decl_module[d] == m and '@' in d)
            if m in measured:
                timing = measured[m]
                t_meas += 1
                t_ms += timing
            else:
                timing = None
                t_un += 1
            mem_rows.append([mi[m]['path'], mi[m]['role'], mi[m]['lines'], n_decl, n_pseudo, timing])
        witness = None
        if verdict == 'keep':
            d = next(x for x in ds if rows[x]['verdict'] == 'keep')
            r = rows[d]
            witness = {'decl': d, 'consumer': r['consumer'],
                       'kind': state['consumers'][r['consumer']]['kind'],
                       'entry': state['consumers'][r['consumer']]['entry'].get(r['root']),
                       'root': r['root'], 'path': r['path']}
        elif verdict == 'ownerNeeded':
            d = next(x for x in ds if rows[x]['verdict'] == 'ownerNeeded')
            r = rows[d]
            witness = {'decl': d, 'owner': r['owner'], 'cross_family': r['owner'] != fam,
                       'seed': r['seed'], 'path': r['path'], 'indep': 'S_primary'}
        elif verdict == 'orphan':
            witness = {'live': 'S_demand', 'decls': len(ds)}
        else:
            blockers = {}
            for d in ds:
                r = rows[d]
                if r['verdict'] == 'unresolved':
                    cls = gap_list[r['gap']]['class']
                    blockers[cls] = blockers.get(cls, 0) + 1
            if ds:
                d = next(x for x in ds if rows[x]['verdict'] == 'unresolved')
                r = rows[d]
                witness = {'decl': d, 'gap_class': gap_list[r['gap']]['class'],
                           'target': r['target'], 'path': r['path'], 'recorded': 'S_keep',
                           'blockers': dict(sorted(blockers.items()))}
            else:
                witness = {'empty': 'no declarations in any member module'}
        lines = sum(mi[m]['lines'] for m in members)
        area = mi[members[0]]['area']
        families.append({'family': fam, 'area': area, 'verdict': verdict, 'lines': lines,
                         'decls': sum(1 for d in ds if '@' not in d),
                         'pseudo': sum(1 for d in ds if '@' in d),
                         'counts': counts, 'members': mem_rows,
                         'timing': {'measured_modules': t_meas, 'unavailable_modules': t_un,
                                    'measured_ms': t_ms},
                         'witness': witness})
        a = areas.setdefault(area, {'modules': 0, 'families': 0, 'lines': 0, 'decls': 0,
                                    'verdicts': {v: 0 for v in CL.VERDICTS},
                                    'lines_by_verdict': {v: 0 for v in CL.VERDICTS}})
        a['modules'] += len(members)
        a['families'] += 1
        a['lines'] += lines
        a['decls'] += families[-1]['decls']
        a['verdicts'][verdict] += 1
        a['lines_by_verdict'][verdict] += lines
        totals['modules'] += len(members)
        totals['lines'] += lines
        totals['decls'] += families[-1]['decls']
        totals['pseudo'] += families[-1]['pseudo']
        totals['families'] += 1
        totals['verdicts'][verdict] += 1
        for v in CL.VERDICTS:
            totals['decl_verdicts'][v] += counts[v]
        totals['measured_modules'] += t_meas
        totals['unavailable_modules'] += t_un
        totals['measured_ms'] += t_ms
    consumers = []
    for cid in sorted(state['consumers']):
        c = state['consumers'][cid]
        in_scope = sorted(r for r in c['roots'] if r in facts.decl_module)
        consumers.append({'id': cid, 'kind': c['kind'], 'roots': len(c['roots']),
                          'in_scope_roots': len(in_scope)})
    gaps = []
    for cls, g in sorted(state['gap_classes'].items()):
        gaps.append({'class': cls, 'source': g['source'] + ':unknown', 'targets': g['targets'],
                     'reason': g['reason']})
    for g in gap_list:
        if g['targets'] is None:
            gaps.append({'class': g['class'], 'source': g['source'][0] + ':unknown',
                         'targets': None, 'reason': g['reason']})
    sets = {k: ({'size': len(v), 'sha256': digest(v)} if v is not None else None)
            for k, v in sorted(state['sets'].items())}
    unresolved_fams = [f['family'] for f in families if f['verdict'] == 'unresolved']
    orphans = [f['family'] for f in families if f['verdict'] == 'orphan']
    out = {
        'schema': SCHEMA, 'version': VERSION,
        'revision': inp.rev, 'lean_tree_id': inp.lean_tree_id, 'toolchain': inp.toolchain,
        'goal': {'goal_decl': 'Solidity.Goals.leanInventorySound',
                 'proof': 'Solidity.LeanInventory.inventory_sound',
                 'file': 'scripts/lean-inventory/InventorySound.lean'},
        'extraction': {k: inp.identity[k] for k in (
            'lean_version', 'lean_githash', 'extractor_blob', 'olean_digest', 'ilean_digest',
            'graph_sha256', 'anon_sha256', 'build_log_sha256', 'build_command', 'extract_command',
            'missing_compiled', 'groups')},
        'regenerate': [
            'export LEAN_NUM_THREADS=1',
            f'python3 -B scripts/lean-inventory/inventory.py --repo . --revision {inp.rev} --extract',
            f'python3 -B scripts/lean-inventory/inventory.py --repo . --revision {inp.rev} '
            '--output scripts/lean-inventory.json --check'],
        'limitations': LIMITATIONS,
        'scope': {'areas': list(S.AREAS), 'rule': 'tracked .lean files under Solidity/<Area>/',
                  'grouping_rule': S.GROUPING_RULE,
                  'identity': 'a declaration is a kernel constant with a declaration range; '
                              'auxiliary constants fold into their nearest ranged name prefix '
                              '(uses folded alike); module@line is an anonymous check inside '
                              'the areas (a Controls/Pins one is a demand seed)'},
        'line_basis': 'physical lines of the Git blob at the revision (newline-terminated lines '
                      'plus a final unterminated one)',
        'recovery': {'revision': inp.rev,
                     'command': f'git show {inp.rev}:PATH  (PATH: any member path below)'},
        'timing': {'provenance': prov,
                   'unavailable_reason': 'fetched from the Lake artifact cache in the recorded '
                                         'build (no elaboration measured) or not built there',
                   'member_field': 'members rows: [path, role, lines, declarations, '
                                   'anonymous checks, check ms or null when unavailable]'},
        'roots': {
            'consumers': consumers,
            'blanket': [{'path': p, 'reason': r} for p, r in sorted(state['blanket'].items())]
            + [{'path': p, 'reason': 'generated library root: imports only'}
               for p in S.GENERATED_ROOTS],
            'rules': [
                'goal:D: a registered @[goal] whose expected proof exists; root = that proof.',
                'test:P: a module built only by a test library (SolidityExamples, '
                'SoliditySlowExamples, SolkeyTestSuite, SolidityCorpus); roots = its theorems '
                'and the references of its anonymous commands.',
                'check:P: anonymous commands of a library module outside the areas; roots = '
                'their references.',
                'exe:E: a lean_exe main; roots = project constants its root module reaches.',
                'An anonymous check inside an area is a declaration of its module '
                '(module@line), not a consumer: in Controls/Pins it is a demand seed; in a '
                'member module it is deleted with its family and demands nothing.']},
        'gaps': gaps,
        'sets': sets,
        'totals': totals,
        'areas': dict(sorted(areas.items())),
        'unresolved_families': len(unresolved_fams),
        'certified_orphan_families': orphans,
        'families': families,
    }
    return json.dumps(out, indent=None, separators=(',', ':'), sort_keys=False) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--repo', default='.')
    ap.add_argument('--revision', required=True)
    ap.add_argument('--output')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--extract', action='store_true')
    a = ap.parse_args(argv)
    rev = S.resolve(a.repo, a.revision)
    if a.extract:
        extract(a.repo, rev)
        return 0
    if not a.output:
        ap.error('--output is required')
    inp = Inputs(a.repo, rev)
    text = render(build(inp))
    if a.check:
        import checker
        old = Path(a.output).read_text() if Path(a.output).exists() else None
        if old != text:
            print('inventory: drift: regenerated output differs from ' + a.output)
            return 1
        problems = checker.check(Path(a.repo), json.loads(old))
        if problems:
            for p in problems[:50]:
                print('inventory: check:', p)
            return 1
        print('inventory: check passed for', rev)
        return 0
    Path(a.output).write_text(text)
    print('inventory: wrote', a.output)
    return 0


if __name__ == '__main__':
    sys.exit(main())
