class Inputs:
    """Git objects at REV plus the extraction cache, with identities checked."""

    def __init__(self, repo, rev):
        self.repo = Path(repo).resolve()
        self.rev = S.resolve(self.repo, rev)
        self.files = S.tracked(self.repo, self.rev)
        self.blob_of = dict(self.files)
        lean_blobs = [b for p, b in self.files if p.endswith('.lean')]
        self.text = S.blobs(self.repo, lean_blobs + [self.blob_of['lean-toolchain']])
        self.lean_paths = [p for p, _ in self.files if p.endswith('.lean')]
        self.toolchain = self.text[self.blob_of['lean-toolchain']].strip()
        self.lean_tree_id = S.lean_tree_id(self.files)
        cdir = cache_dir(self.repo, self.rev)
        idp = cdir / 'identity.json'
        if not idp.exists():
            raise SystemExit(f'no extraction for {self.rev}: run with --extract first ({idp})')
        self.identity = json.loads(idp.read_text())
        problems = []
        if self.identity['revision'] != self.rev:
            problems.append('revision')
        if self.identity['lean_tree_id'] != self.lean_tree_id:
            problems.append('Lean source tree')
        if self.identity['toolchain'] != self.toolchain or \
                not self.toolchain.endswith('v' + self.identity['lean_version']):
            problems.append('toolchain')
        for name, key in (('graph.jsonl.gz', 'graph_sha256'), ('anon.json', 'anon_sha256'),
                          ('build.log', 'build_log_sha256')):
            if sha256_file(cdir / name) != self.identity[key]:
                problems.append(name)
        if problems:
            raise SystemExit('stale or altered extraction: ' + ', '.join(problems))
        with gzip.open(cdir / 'graph.jsonl.gz', 'rt') as f:
            self.records = [json.loads(line) for line in f]
        self.anon = json.loads((cdir / 'anon.json').read_text())
        self.build_log = (cdir / 'build.log').read_text()

    def lean_text(self, path):
        return self.text[self.blob_of[path]]


# ------------------------------------------------------------------- facts ----

def fold_map(consts):
    """Auxiliary constants (no declaration range) fold into their nearest ranged prefix."""
    ranged = {n for n, c in consts.items() if c.get('range')}
    fold = {}
    for n in consts:
        if n in ranged:
            fold[n] = n
            continue
        p = n
        target = n
        while '.' in p:
            p = p.rsplit('.', 1)[0]
            if p in ranged:
                target = p
                break
        fold[n] = target
    return fold


def build(inp):
    """All facts, the certificate, and the summary JSON."""
    module_paths = {S.module_name(p): p for p in inp.lean_paths}
    in_scope = sorted(p for p in inp.lean_paths if S.area_of(p))
    siblings = set(in_scope)
    module_info = {}
    for p in in_scope:
        fam, role = S.family_of(p, siblings)
        module_info[S.module_name(p)] = {'path': p, 'area': S.area_of(p), 'family': fam,
                                         'role': role, 'lines': S.line_count(inp.lean_text(p))}
    imports = {S.module_name(p): S.header_imports(inp.lean_text(p)) for p in inp.lean_paths}

    # Constants of the library group, and the executable roots' own modules.
    consts, loaded, goals, exe_consts = {}, set(), [], {}
    exe_root_of = {'exe:' + e: m for m, e in S.EXE_ROOTS.items()}
    for r in inp.records:
        g = r.get('g')
        if r['r'] == 'module' and g == 'lib':
            loaded.add(r['m'])
        elif r['r'] == 'const':
            if g == 'lib':
                c = consts.setdefault(r['n'], {'m': r['m'], 'refs': set(), 'k': r['k']})
                c['refs'].update(r['refs'])
                c['refs'].update(r.get('lits', ()))
                if 'impl' in r:
                    c['refs'].add(r['impl'])
                for flag in ('inst', 'simp', 'meta'):
                    if r.get(flag):
                        c[flag] = True
                if 'range' in r:
                    c['range'] = r['range']
                    c['m'] = r['m']
            elif r['m'] == exe_root_of.get(g):
                exe_consts.setdefault(g, {})[r['n']] = r
        elif r['r'] == 'goal' and g == 'lib':
            goals.append(r)
    fold = fold_map(consts)
    node_module = {}
    for n, c in sorted(consts.items()):
        f = fold[n]
        if f == n or f not in node_module:
            node_module.setdefault(f, consts[f]['m'] if f in consts else c['m'])
    edges = {}
    for n, c in consts.items():
        src = fold[n]
        for t in c['refs']:
            if t in fold and fold[t] != src:
                edges.setdefault(src, set()).add(fold[t])
    decl_module = {n: m for n, m in node_module.items() if m in module_info}

    # Pseudo-declarations: anonymous checks inside in-scope modules.
    starts_cache = {}

    def command_of(m, line):
        if m not in starts_cache:
            starts_cache[m] = S.command_starts(inp.lean_text(module_paths[m]))
        starts = starts_cache[m]
        best = max((s for s in starts if s <= line), default=None)
        return best, (starts[best] if best else '')

    lib_closure = S.closure(imports, ['Solidity'])
    test_closure = S.closure(imports, list(S.TEST_ROOTS)) - lib_closure
    consumers, unclassified, inline_counts = {}, {}, {}
    for m in sorted(inp.anon):
        if m not in module_paths:
            continue
        for line, name in inp.anon[m]:
            if name not in fold:
                continue
            target = fold[name]
            start, head = command_of(m, line)
            cls = S.classify_command(head) if start else 'unclassified'
            if cls == 'declaration-or-scope':
                continue
            if cls == 'unclassified':
                unclassified.setdefault(target, []).append(f'{module_paths[m]}:{line}')
                continue
            if m in module_info:
                pseudo = f'{m}@{start}'
                decl_module[pseudo] = m
                if target != pseudo:
                    edges.setdefault(pseudo, set()).add(target)
                inline_counts[m] = inline_counts.get(m, 0) + 1
            else:
                cid = ('test:' if m in test_closure else 'check:') + module_paths[m]
                c = consumers.setdefault(cid, {'kind': 'test', 'roots': set(), 'entry': {}})
                c['roots'].add(target)
                c['entry'].setdefault(target, f'{module_paths[m]}:{line}')
    # Test modules' theorems.
    for n, c in sorted(consts.items()):
        if fold[n] == n and c['m'] in test_closure and c['k'] == 'theorem' and c.get('range'):
            cid = 'test:' + module_paths[c['m']]
            e = consumers.setdefault(cid, {'kind': 'test', 'roots': set(), 'entry': {}})
            e['roots'].add(n)
            e['entry'].setdefault(n, f"{module_paths[c['m']]}:{c['range'][0]}")
    # Registered goals whose expected proof exists.
    for g in sorted(goals, key=lambda r: r['decl']):
        if g['proof'] in fold:
            gd = consts.get(g['decl'], {})
            entry = f"{module_paths.get(gd.get('m'), '?')}:{(gd.get('range') or ['?'])[0]}"
            consumers['goal:' + g['decl']] = {'kind': 'goalProof', 'roots': {fold[g['proof']]},
                                              'entry': {fold[g['proof']]: entry}}
    # Executables: project constants reached from `main` within the root module.
    for g, cs in sorted(exe_consts.items()):
        mod = exe_root_of[g]
        local = {n: set(r['refs']) | set(r.get('lits', ())) for n, r in cs.items()}
        reach = S.closure({n: [t for t in v if t in local] for n, v in local.items()}, ['main'])
        roots = {fold[t] for n in reach for t in local.get(n, ()) if t in fold}
        kind = 'cli' if g == 'exe:solkeycheck' or g == 'exe:solidity-lean' else 'runner'
        entry = f"{module_paths[mod]}:{(cs.get('main', {}).get('range') or ['?'])[0]}"
        consumers[g] = {'kind': kind, 'roots': roots, 'entry': {t: entry for t in roots}}

    decls = set(decl_module)
    by_module = {}
    for d, m in decl_module.items():
        by_module.setdefault(m, set()).add(d)

    # Gaps (sources are unknown, so each is live for every closed set).
    gaps, gap_classes = [], {}

    def add_gap(cls, source, targets, reason):
        targets = sorted(t for t in targets if t in node_module)
        if not targets:
            return
        gaps.append({'source': (source, None), 'targets': targets, 'reason': reason, 'class': cls})
        gap_classes.setdefault(cls, {'reason': reason, 'source': source, 'targets': 0})
        gap_classes[cls]['targets'] += len(targets)

    attributed = set()
    attr_cmd_tokens = set()
    for p in inp.lean_paths:
        attr_cmd_tokens |= S.attribute_commands(inp.lean_text(p))
    heads_cache = {}
    for d in node_module:
        c = consts.get(d)
        if not c or not c.get('range') or node_module[d] not in module_paths:
            continue
        m = node_module[d]
        if m not in heads_cache:
            heads_cache[m] = S.attributed_heads(inp.lean_text(module_paths[m]))
        a, b = c['range']
        if any(a <= h <= b for h in heads_cache[m]):
            attributed.add(d)
    by_last = {}
    for d in node_module:
        by_last.setdefault(d.rsplit('.', 1)[-1], []).append(d)
    for tok in attr_cmd_tokens:
        attributed.update(d for d in by_last.get(tok.rsplit('.', 1)[-1], ())
                          if d == tok or d.endswith('.' + tok))
    meta = {fold[n] for n, c in consts.items() if c.get('meta')}
    implicit = {fold[n] for n, c in consts.items() if c.get('inst') or c.get('simp')}
    add_gap('elaborator-time', 'use', meta,
            'metaprogram (type mentions the Lean namespace): run by the elaborator while '
            'checking other declarations, which leaves no kernel-term constant')
    add_gap('elaborator-time-anonymous', 'root', meta,
            'metaprogram possibly run by an anonymous command (no recorded constant)')
    implicit_targets = (implicit | attributed) - meta
    add_gap('implicit-use', 'use', implicit_targets,
            'instance, simp lemma or attribute-registered declaration: an anonymous check '
            'inside the areas may use it implicitly (instance or simp-set lookup), which its '
            '.ilean references do not record')
    add_gap('implicit-use-anonymous', 'root', implicit_targets,
            'instance, simp lemma or attribute-registered declaration possibly used implicitly '
            'by an anonymous command outside the areas')
    add_gap('unclassified-command', 'root', set(unclassified),
            'referenced from a command outside every declaration that the lexical command '
            'classifier cannot place (consumer or not)')
    # Unextracted Lean consumers: exact header import closures.
    built = S.closure(imports, list(S.LIB_ROOTS) + list(S.EXE_ROOTS))
    unextracted, blanket, reach_modules_all = {}, {}, set()
    for p in inp.lean_paths:
        m = S.module_name(p)
        if m in built or S.area_of(p):
            continue
        if p in BLANKET_RUNNERS:
            blanket[p] = BLANKET_RUNNERS[p]
            continue
        reach = S.closure(imports, imports.get(m, []))
        if reach & set(module_info):
            unextracted[p] = reach & set(module_info)
            reach_modules_all.update(reach)
    reach_modules = {}
    for p, ms in unextracted.items():
        for m in ms:
            reach_modules.setdefault(m, []).append(p)
    add_gap('unextracted-lean-file', 'root',
            {d for d, m in node_module.items() if m in reach_modules_all},
            'Lean file outside the built libraries (not elaborated here) whose header import '
            'closure reaches this module')
    # Runner scripts that write Lean text.
    runner_modules = {}
    all_modules = set(module_paths)
    script_blobs = [(p, b) for p, b in inp.files
                    if not p.endswith('.lean') and not p.startswith('docs/')
                    and p.endswith(('.py', '.mjs', '.js', '.cjs', '.sh', '.ts'))]
    texts = S.blobs(inp.repo, [b for _, b in script_blobs])
    for p, b in script_blobs:
        t = texts[b]
        if not S.LEAN_INVOCATION.search(t):
            continue
        names = set()
        for name in S.template_imports(t):
            if name.endswith('*'):
                names |= {m for m in all_modules if m.startswith(name[:-1] + '.')}
            elif name in all_modules:
                names.add(name)
        reach = S.closure(imports, sorted(names))
        for m in reach:
            runner_modules.setdefault(m, []).append(p)
    add_gap('runner-template', 'root',
            {d for d, m in node_module.items() if m in runner_modules},
            'Lean text written by a runner script whose import lines reach this module')
    missing = set(inp.identity['missing_compiled']) | (set(module_info) - loaded)
    for m in sorted(missing & set(module_info)):
        gaps.append({'source': ('use', None), 'targets': None, 'class': 'missing-compiled',
                     'reason': f'module {m} has no compiled metadata: its declarations are unknown'})

    facts = CL.Facts(decls, decl_module, module_info, edges,
                     {c: {'kind': v['kind'], 'roots': v['roots']} for c, v in consumers.items()},
                     gaps)
    rows, fam_verdicts, sets = CL.classify(facts)
    return {
        'inp': inp, 'module_info': module_info, 'module_paths': module_paths, 'facts': facts,
        'rows': rows, 'sets': sets, 'consumers': consumers, 'gap_classes': gap_classes,
        'blanket': blanket, 'unextracted': unextracted, 'reach_modules': reach_modules,
        'runner_modules': runner_modules, 'inline_counts': inline_counts,
        'unclassified': unclassified, 'consts': consts, 'loaded': loaded,
    }


# ------------------------------------------------------------------ timing ----

BUILT = re.compile(r'Built (\S+) \((\d+(?:\.\d+)?)(ms|s)\)')
FETCHED = re.compile(r'(?:Fetched|Replayed) (\S+)')


def timings(inp):
    measured, fetched = {}, set()
    for line in inp.build_log.splitlines():
        m = BUILT.search(line)
        if m:
            v = float(m.group(2))
            measured[m.group(1)] = int(round(v if m.group(3) == 'ms' else v * 1000))
        else:
            f = FETCHED.search(line)
            if f:
                fetched.add(f.group(1))
    return measured, fetched


