#!/usr/bin/env python3
"""Roadmap S00: the constructor-level definitions over `Syn`.

`Solidity/Source/Syntax.lean` declares `inductive Syn : Cat → Type`. The
definitions that follow it one line per constructor (`Ctor`, `Ctor.all`,
`Syn.ctor`, `Syn.children`, `Syn.placeholders`, `Syn.nodes` in
`Solidity/Source/Ctor.lean`; `Syn.paths` in `Solidity/Source/Decls.lean`) are
generated from the constructors' signatures, so every `Syn`-typed field is
consumed and every constructor has its `Ctor`. They live between
`-- BEGIN generated by scripts/source-ctors.py (NAME)` and `-- END …` lines.

Usage: python3 -I scripts/source-ctors.py [--check | --write]
`--check` (the default) fails when a generated block differs from the
generator's output; `--write` rewrites the blocks. Standard library only.
"""
import argparse, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYNTAX = ROOT / "Solidity/Source/Syntax.lean"

def split_top(t, sep):
    out, d, b, i = [], 0, "", 0
    while i < len(t):
        c = t[i]
        if c in "([{⟨": d += 1
        if c in ")]}⟩": d -= 1
        if d == 0 and t.startswith(sep, i):
            out.append(b); b = ""; i += len(sep); continue
        b += c; i += 1
    out.append(b)
    return out

def constructors():
    s = SYNTAX.read_text()
    body = s[s.index("inductive Syn : Cat → Type where"):s.index("end Solidity.Source")]
    ctors, cur = [], None
    for l in body.split("\n")[1:]:
        if l.startswith("  | "):
            if cur: ctors.append(cur)
            cur = l[4:]
        elif l.startswith("      ") and cur is not None:
            cur += " " + l.strip()
        else:
            if cur: ctors.append(cur)
            cur = None
    if cur: ctors.append(cur)
    res = []
    for c in ctors:
        name = c.split()[0]
        rest = c[len(name):].strip()
        parts = split_top(rest, " : ")
        pre = parts[0] if len(parts) > 1 else ""
        typ = " : ".join(parts[1:]) if len(parts) > 1 else parts[0].lstrip(": ")
        if pre.startswith(":"): typ, pre = rest[1:], ""
        args = []
        for m in re.finditer(r"([({])([^(){}]*?) : ([^(){}]*(?:\([^()]*\))?[^(){}]*)([)}])", pre):
            if m.group(1) == "(":
                for n in m.group(2).split(): args.append((n, m.group(3).strip()))
        for x in [x.strip() for x in split_top(typ, "→")][:-1]:
            m = re.match(r"^\((\w+) : (.*)\)$", x)
            args.append((m.group(1), m.group(2)) if m else (None, x))
        res.append((name, args))
    return res

def pat(n, a, names):
    ps = [names[j] if t.startswith("Syn") or names[j] != "_" else "_" for j, (x, t) in enumerate(a)]
    return "." + n + (" " + " ".join(ps) if ps else "")

def gen(r):
    names = [n for n, _ in r]
    out = {}
    L = ["/-- The constructors of `Syn`, one per constructor. -/", "inductive Ctor where"]
    for i in range(0, len(names), 6): L.append("  | " + " | ".join(names[i:i + 6]))
    L += ["  deriving DecidableEq, Repr", "", "/-- Every constructor, in declaration order. -/", "def Ctor.all : List Ctor :="]
    L.append("  [" + ",\n    ".join(", ".join("." + n for n in names[i:i + 6]) for i in range(0, len(names), 6)) + "]")
    L += ["", "/-- The constructor at the root. -/", "def Syn.ctor : {c : Cat} → Syn c → Ctor"]
    for n, a in r: L.append("  | _, %s => .%s" % (pat(n, a, ["_"] * len(a)), n))
    L += ["", "/-- The immediate subterms, with their categories. -/",
          "def Syn.children : {c : Cat} → Syn c → List (Σ c, Syn c)"]
    for n, a in r:
        cn = ["s%d" % j if t.startswith("Syn") else "_" for j, (x, t) in enumerate(a)]
        kids = [cn[j] for j, (x, t) in enumerate(a) if t.startswith("Syn")]
        L.append("  | _, %s => [%s]" % (pat(n, a, cn), ", ".join("⟨_, %s⟩" % k for k in kids)))
    L += ["", "/-- The modifier placeholders `_;` in a tree. -/", "def Syn.placeholders : {c : Cat} → Syn c → Nat",
          "  | _, .exprStmt (.ident \"_\") => 1"]
    for n, a in r:
        cn = ["s%d" % j if t.startswith("Syn") else "_" for j, (x, t) in enumerate(a)]
        kids = [cn[j] for j, (x, t) in enumerate(a) if t.startswith("Syn")]
        L.append("  | _, %s => %s" % (pat(n, a, cn), " + ".join("%s.placeholders" % k for k in kids) or "0"))
    out["ctor"] = "\n".join(L)
    L = ["/-- Every node, root first, with its constructor and the exclusion it", "triggers (`Syn.node`). -/",
         "def Syn.nodes : {c : Cat} → Syn c → List Node"]
    for n, a in r:
        cn = ["s%d" % j if t.startswith("Syn") else "_" for j, (x, t) in enumerate(a)]
        kids = [cn[j] for j, (x, t) in enumerate(a) if t.startswith("Syn")]
        rest = " ++ ".join("%s.nodes" % k for k in kids) if kids else "[]"
        L.append("  | _, s@(%s) => s.node :: %s" % (pat(n, a, cn), "(" + rest + ")" if len(kids) > 1 else rest))
    out["nodes"] = "\n".join(L)
    L = ["/-- The names a tree mentions, root first: paths in types, inheritance,",
         "modifiers, `using` and overrides, and identifiers. -/", "def Syn.paths : {c : Cat} → Syn c → List IdPath"]
    for n, a in r:
        ps, own, kids = [], [], []
        for j, (x, t) in enumerate(a):
            v = "a%d" % j
            if t.startswith("Syn"): ps.append(v); kids.append(v + ".paths")
            elif t == "IdPath": ps.append(v); own.append("[%s]" % v)
            elif t == "Option (List IdPath)": ps.append(v); own.append("%s.getD []" % v)
            elif t == "MapKey": ps.append(v); own.append("%s.paths" % v)
            elif n == "ident" and x == "name": ps.append(v); own.append("[⟨%s, []⟩]" % v)
            else: ps.append("_")
        L.append("  | _, %s => %s" % ("." + n + (" " + " ".join(ps) if ps else ""), " ++ ".join(own + kids) or "[]"))
    out["paths"] = "\n".join(L)
    return out

FILES = {"ctor": "Solidity/Source/Ctor.lean", "nodes": "Solidity/Source/Ctor.lean", "paths": "Solidity/Source/Decls.lean"}

def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    out = gen(constructors())
    bad = 0
    for key, rel in FILES.items():
        path = ROOT / rel
        s = path.read_text()
        b = "-- BEGIN generated by scripts/source-ctors.py (%s)\n" % key
        e = "-- END generated by scripts/source-ctors.py (%s)\n" % key
        if b not in s or e not in s:
            print("%s: no generated block %s" % (rel, key)); bad += 1; continue
        i, j = s.index(b) + len(b), s.index(e)
        if s[i:j] != out[key] + "\n":
            if args.write: path.write_text(s[:i] + out[key] + "\n" + s[j:])
            else: print("%s: generated block %s is stale" % (rel, key)); bad += 1
    n = len(constructors())
    print("source-ctors: %d constructors, %d stale block(s)" % (n, bad))
    sys.exit(1 if bad else 0)

if __name__ == "__main__":
    main()
