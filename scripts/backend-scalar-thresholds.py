#!/usr/bin/env python3
"""Generate compiler threshold constants; Lean kernel checks every boundary.

--check compares the generated owned module without writing it. No floating
point, native proof plugin or external package is used.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def floor_root(bound, exponent):
    low, high = 0, 1 << ((bound.bit_length() + exponent - 1) // exponent + 1)
    while low + 1 < high:
        middle = (low + high) // 2
        if middle ** exponent < bound:
            low = middle
        else:
            high = middle
    return low

def generate():
    lines = ["import Solidity.Backend.Scalar.Widths", "", "/-!", "# Checked-power threshold constants", "", "Generated by scripts/backend-scalar-thresholds.py. The generator is not", "trusted: threshold_bounds is checked by the Lean kernel over every entry.", "The constants are numeric compiler data, not a source or opcode language.", "-/", "namespace Solidity.Backend.Scalar", ""]
    for width in range(8, 257, 8):
        entries = [str(floor_root(1 << width, exponent)) for exponent in range(1, 256)]
        lines.append(f"private def naturalThresholdRow{width // 8 - 1} : Vector Nat 255 := ( #v[")
        for start in range(0, 255, 17):
            row = entries[start:start + 17]
            lines.append("    #v[" + ", ".join(row) + "]" + ("," if start + 17 < 255 else ""))
        lines += [" ] : Vector (Vector Nat 17) 15).flatten", ""]
    for w in range(32):
        lines += [f"private theorem rowBounds{w} : ∀ (i : Fin 255),", f"    naturalThresholdRow{w}[i] < 2 ^ {8*(w+1)} ∧", f"    naturalThresholdRow{w}[i] ^ (i.val + 1) < 2 ^ {8*(w+1)} ∧", f"    2 ^ {8*(w+1)} ≤ (naturalThresholdRow{w}[i] + 1) ^ (i.val + 1) := by", "  decide +kernel", ""]
    lines += ["def naturalThresholds : Vector (Vector Nat 255) 32 := #v["]
    lines += ["  naturalThresholdRow" + str(i) + ("," if i != 31 else "") for i in range(32)]
    lines += ["]", "", "theorem threshold_bounds : ∀ (w : Fin 32) (i : Fin 255),", "    naturalThresholds[w][i] < 2 ^ widthBits w ∧", "    naturalThresholds[w][i] ^ (i.val + 1) < 2 ^ widthBits w ∧", "    2 ^ widthBits w ≤ (naturalThresholds[w][i] + 1) ^ (i.val + 1) := by", "  intro w i", "  have hw : " + " ∨ ".join(f"w = {j}" for j in range(32)) + " := by omega", "  rcases hw with " + " | ".join(f"h{j}" for j in range(32))] + [line for j in range(32) for line in [f"  · subst w; exact rowBounds{j} i"]] + ["", "def thresholdWord (w : Fin 32) (i : Fin 255) : Word :=", "  BitVec.ofNat 256 naturalThresholds[w][i]", "", "def exponentWord (i : Fin 255) : Word := BitVec.ofNat 256 (i.val + 1)", "", "theorem thresholdWord_nat (w : Fin 32) (i : Fin 255) :", "    (thresholdWord w i).toNat = naturalThresholds[w][i] := by", "  have hb : naturalThresholds[w][i] < 2 ^ 256 :=", "    Nat.lt_of_lt_of_le (threshold_bounds w i).1", "      (Nat.pow_le_pow_right (by decide) (widthBits_bounds w).2)", "  simp only [thresholdWord, BitVec.toNat_ofNat, Nat.mod_eq_of_lt hb]", "", "theorem exponentWord_nat (i : Fin 255) :", "    (exponentWord i).toNat = i.val + 1 := by", "  have hi : i.val + 1 < 2 ^ 256 := by have := i.isLt; omega", "  simp only [exponentWord, BitVec.toNat_ofNat, Nat.mod_eq_of_lt hi]", "", "#print axioms threshold_bounds", "", "end Solidity.Backend.Scalar", ""]
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "Solidity/Backend/Scalar/PowerBounds.lean"
    generated = generate()
    if args.check:
        if target.read_text() != generated:
            raise SystemExit("power threshold generation differs")
        print("32 widths × 255 power thresholds: generated constants agree")
    else:
        target.write_text(generated)

if __name__ == "__main__":
    main()
