#!/usr/bin/env python3
"""Generate compiler threshold constants; Lean kernel checks every boundary.

--check compares the generated owned modules without writing them. No floating
point, native proof plugin or external package is used.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def floor_root(bound, exponent):
    low, high = 0, 1 << ((bound.bit_length() + exponent - 1) // exponent + 1)
    while low + 1 < high:
        middle = (low + high) // 2
        if middle ** exponent < bound:
            low = middle
        else:
            high = middle
    return low

PARTS = 8
ROWS_PER_PART = 32 // PARTS


def part_module(part):
    return f"Solidity.Backend.Scalar.PowerBounds.Part{part + 1:02d}"


def part_path(part):
    return f"Solidity/Backend/Scalar/PowerBounds/Part{part + 1:02d}.lean"


def generate_part(part):
    # Four widths per module: the kernel checks of all 32 rows in one module
    # peaked at 7.9 GiB at LEAN_NUM_THREADS=1, over the host pre-gate's bound.
    first = part * ROWS_PER_PART
    lines = ["import Solidity.Backend.Scalar.Widths", "", "/-!", f"# Checked-power threshold constants, widths {8 * (first + 1)}–{8 * (first + ROWS_PER_PART)}", "", "Generated by scripts/backend-scalar-thresholds.py. The generator is not", "trusted: every row's bounds are checked by the Lean kernel here, and", "`Solidity.Backend.Scalar.PowerBounds` assembles `threshold_bounds`.", "-/", "namespace Solidity.Backend.Scalar", ""]
    for w in range(first, first + ROWS_PER_PART):
        width = 8 * (w + 1)
        entries = [str(floor_root(1 << width, exponent)) for exponent in range(1, 256)]
        lines.append(f"def naturalThresholdRow{w} : Vector Nat 255 := ( #v[")
        for start in range(0, 255, 17):
            row = entries[start:start + 17]
            lines.append("    #v[" + ", ".join(row) + "]" + ("," if start + 17 < 255 else ""))
        lines += [" ] : Vector (Vector Nat 17) 15).flatten", ""]
    for w in range(first, first + ROWS_PER_PART):
        lines += [f"theorem rowBounds{w} : ∀ (i : Fin 255),", f"    naturalThresholdRow{w}[i] < 2 ^ {8*(w+1)} ∧", f"    naturalThresholdRow{w}[i] ^ (i.val + 1) < 2 ^ {8*(w+1)} ∧", f"    2 ^ {8*(w+1)} ≤ (naturalThresholdRow{w}[i] + 1) ^ (i.val + 1) := by", "  decide +kernel", ""]
    lines += ["end Solidity.Backend.Scalar", ""]
    return "\n".join(lines)


def generate():
    lines = [f"import {part_module(part)}" for part in range(PARTS)] + ["", "/-!", "# Checked-power threshold constants", "", "Generated by scripts/backend-scalar-thresholds.py. The generator is not", "trusted: threshold_bounds is checked by the Lean kernel over every entry,", "row by row in `PowerBounds/Part01`–`Part08`.", "The constants are numeric compiler data, not a source or opcode language.", "-/", "-- Keep the 32 kernel-checked rows from retaining concurrent proof tasks.", "set_option Elab.async false", "", "namespace Solidity.Backend.Scalar", ""]
    lines += ["def naturalThresholds : Vector (Vector Nat 255) 32 := #v["]
    lines += ["  naturalThresholdRow" + str(i) + ("," if i != 31 else "") for i in range(32)]
    lines += ["]", "", "theorem threshold_bounds : ∀ (w : Fin 32) (i : Fin 255),", "    naturalThresholds[w][i] < 2 ^ widthBits w ∧", "    naturalThresholds[w][i] ^ (i.val + 1) < 2 ^ widthBits w ∧", "    2 ^ widthBits w ≤ (naturalThresholds[w][i] + 1) ^ (i.val + 1) := by", "  intro w i", "  have hw : " + " ∨ ".join(f"w = {j}" for j in range(32)) + " := by omega", "  rcases hw with " + " | ".join(f"h{j}" for j in range(32))] + [line for j in range(32) for line in [f"  · subst w; exact rowBounds{j} i"]] + ["", "def thresholdWord (w : Fin 32) (i : Fin 255) : Word :=", "  BitVec.ofNat 256 naturalThresholds[w][i]", "", "def exponentWord (i : Fin 255) : Word := BitVec.ofNat 256 (i.val + 1)", "", "theorem thresholdWord_nat (w : Fin 32) (i : Fin 255) :", "    (thresholdWord w i).toNat = naturalThresholds[w][i] := by", "  have hb : naturalThresholds[w][i] < 2 ^ 256 :=", "    Nat.lt_of_lt_of_le (threshold_bounds w i).1", "      (Nat.pow_le_pow_right (by decide) (widthBits_bounds w).2)", "  simp only [thresholdWord, BitVec.toNat_ofNat, Nat.mod_eq_of_lt hb]", "", "theorem exponentWord_nat (i : Fin 255) :", "    (exponentWord i).toNat = i.val + 1 := by", "  have hi : i.val + 1 < 2 ^ 256 := by have : i.val < 255 := i.isLt; omega", "  simp only [exponentWord, BitVec.toNat_ofNat, Nat.mod_eq_of_lt hi]", "", "#print axioms threshold_bounds", "", "end Solidity.Backend.Scalar", ""]
    return "\n".join(lines)


def outputs():
    yield ROOT / "Solidity/Backend/Scalar/PowerBounds.lean", generate()
    for part in range(PARTS):
        yield ROOT / part_path(part), generate_part(part)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for target, generated in outputs():
        if args.check:
            if not target.is_file() or target.read_text() != generated:
                raise SystemExit(f"power threshold generation differs: {target.relative_to(ROOT)}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(generated)
    if args.check:
        print("32 widths × 255 power thresholds: generated constants agree")

if __name__ == "__main__":
    main()
