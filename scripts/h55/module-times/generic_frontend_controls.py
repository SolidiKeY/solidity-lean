#!/usr/bin/env python3
"""Guard regression: generic frontend controls imply generated parser validation."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
PREFIX = 'tests/h62/item4/generic-source-frontend/'
ROLES = {
    'Core': 'conditional generic control correspondence on existing intrinsic syntax, not actual parser-table validation',
    'CoreControls': 'typed generic acceptance, mismatch and refusal witnesses, not original parser fixture coverage',
    'FixtureTable': 'generated 45 finite certificates; historical source says producer migration and passing check pending',
}


def classify(root, rows):
    if not isinstance(rows, list):
        raise ValueError('invalid reference index')
    root = Path(root).resolve()
    out, seen = [], set()
    for entry in rows:
        if not isinstance(entry, dict) or not isinstance(entry.get('candidate'), dict):
            raise ValueError('invalid candidate')
        row = entry['candidate']
        path = row.get('path')
        if not isinstance(path, str) or not path.startswith(PREFIX) or entry.get('status') != 'no-supplied-current-reference':
            continue
        filename = path[len(PREFIX):]
        name = filename[:-5] if filename.endswith('.lean') else ''
        if name not in ROLES or path in seen:
            raise ValueError('unreviewed or duplicate candidate')
        seen.add(path)
        source = root / path
        if source.is_symlink() or not source.is_file() or source.resolve() != source:
            raise ValueError('invalid source')
        if hashlib.sha256(source.read_bytes()).hexdigest() != row.get('sha256'):
            raise ValueError('source differs from reference snapshot')
        driver = ('validate.py checks CoreControls closure including Core; current invocation unresolved'
                  if name != 'FixtureTable' else 'generated by generate.py; not included in validate.py CoreControls closure; current Lean driver unresolved')
        out.append({'candidate': row, 'role': ROLES[name], 'driver': driver,
                    'inputs': 'source/import closure, isolated toolchain and private artifacts; exact current inputs unverified',
                    'effects': 'generator can write fixture source; validation writes private logs and oleans',
                    'expected_outcome': 'current execution unresolved; historical unblocked packet is not full parser or timing acceptance',
                    'status': 'static-reference-not-execution-acceptance'})
    return out


def main():
    if len(sys.argv) != 2:
        print('usage: generic_frontend_controls.py REFERENCE_INDEX.json', file=sys.stderr)
        return 2
    try:
        raw = Path(sys.argv[1]).read_bytes()
        data = json.loads(raw)
        print(json.dumps({'status': 'partial-static-classification-not-acceptance',
                          'coverage': 'supplied-snapshot-subset-only-unverified',
                          'input_sha256': hashlib.sha256(raw).hexdigest(),
                          'rows': classify(ROOT, data['rows'])}, indent=2, sort_keys=True))
    except (OSError, UnicodeError, ValueError, KeyError, TypeError) as exc:
        print(f'generic frontend classification unavailable: {exc}', file=sys.stderr)
        return 1
    return 0

if __name__ == '__main__':
    sys.exit(main())
