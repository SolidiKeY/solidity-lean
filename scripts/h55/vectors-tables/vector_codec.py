#!/usr/bin/env python3
"""Lossless structured extraction/rendering of the frozen finite controls.

The data records the original outputs; it is not an independent arithmetic oracle.
Bulk JSON is intentionally external to Git. Never write into the source tree.
"""
import argparse
import json
import re
from pathlib import Path
import vector_census as census

NAT = r"(?:0|[1-9][0-9]*)"
LINE = re.compile(rf"theorem (v[0-9]{{4}}) : \(Pure\.eval .«([a-z]+)» \(fun (i|_) => (.*?)\)\)\.val = ({NAT}) := by decide \+kernel\n")
ARG = re.compile(rf"if i\.val = ({NAT}) then word ({NAT}) else ")
TAIL = re.compile(rf"word ({NAT})")
ARITY = {**dict.fromkeys(("not", "iszero", "clz"), 1),
         **dict.fromkeys(("addmod", "mulmod"), 3),
         **dict.fromkeys(("shl", "shr", "sar", "add", "sub", "mul", "div", "sdiv", "mod", "smod", "lt", "gt", "slt", "sgt", "eq", "and", "or", "xor", "byte", "signextend", "exp"), 2)}

def wrapper(path):
    ns = path.removesuffix(".lean").replace("/", ".")
    return ("import Solidity.Yul.Words\n\n/-! Kernel controls, generated by a script not in this repository.\n"
            "Integer-oracle vectors are finite tests, not universal opcode agreement proofs. -/\n"
            f"namespace {ns}\n\n", f"\nend {ns}\n")

def extract(path, data):
    census.audit(path, data)
    head, foot = wrapper(path)
    text = data.decode("utf-8")
    if not text.startswith(head) or not text.endswith(foot):
        raise ValueError(f"{path}: unsupported wrapper")
    rows = []
    for line in text[len(head):-len(foot)].splitlines(keepends=True):
        match = LINE.fullmatch(line)
        if not match: raise ValueError(f"{path}: unsupported row")
        name, op, binder, expr, result = match.groups()
        args = []
        while m := ARG.match(expr):
            if int(m.group(1)) != len(args): raise ValueError("argument index")
            args.append(m.group(2)); expr = expr[m.end():]
        tail = TAIL.fullmatch(expr)
        if not tail: raise ValueError("argument tail")
        args.append(tail.group(1))
        if op not in ARITY or len(args) != ARITY[op] or binder != ("_" if len(args) == 1 else "i"):
            raise ValueError("opcode arity or binder")
        rows.append({"name": name, "op": op, "args": args, "result": result})
    return rows

def render(path, rows):
    if not isinstance(rows, list) or not rows: raise ValueError("empty rows")
    head, foot = wrapper(path)
    result = []
    for row in rows:
        if not isinstance(row, dict) or set(row) != {"name", "op", "args", "result"}: raise ValueError("row fields")
        name, op, args, value = (row[k] for k in ("name", "op", "args", "result"))
        if not isinstance(name, str) or not re.fullmatch(r"v[0-9]{4}", name): raise ValueError("name")
        if not isinstance(op, str) or op not in ARITY or not isinstance(args, list) or len(args) != ARITY[op]: raise ValueError("opcode or arity")
        if any(not isinstance(x, str) or not re.fullmatch(NAT, x) for x in [*args, value]): raise ValueError("numeric field")
        expr = "".join(f"if i.val = {i} then word {arg} else " for i, arg in enumerate(args[:-1])) + f"word {args[-1]}"
        binder = "_" if len(args) == 1 else "i"
        result.append(f"theorem {name} : (Pure.eval .«{op}» (fun {binder} => {expr})).val = {value} := by decide +kernel\n")
    out = (head + "".join(result) + foot).encode()
    census.audit(path, out)
    return out

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=("extract", "check", "emit"))
    parser.add_argument("data", type=Path)
    parser.add_argument("--output", type=Path)
    a = parser.parse_args()
    if (a.mode == "emit") != (a.output is not None): parser.error("--output is required only for emit")
    expected = json.loads(census.MANIFEST.read_text())["files"]
    if census.census(census.ROOT) != expected: raise SystemExit("frozen inputs differ")
    if a.mode == "extract":
        if a.data.exists(): raise SystemExit("refusing to overwrite existing data")
        if a.data.resolve().is_relative_to(census.ROOT): raise SystemExit("bulk data must remain outside checkout")
        records = {p: extract(p, (census.ROOT / p).read_bytes()) for p in census.PATHS}
        a.data.write_text(json.dumps({"schema": 1, "files": records}, separators=(",", ":")) + "\n")
    else:
        data = json.loads(a.data.read_text())
        if set(data) != {"schema", "files"} or type(data["schema"]) is not int or data["schema"] != 1 or set(data["files"]) != set(census.PATHS): raise ValueError("inventory/schema")
        rendered = {}
        for p in census.PATHS:
            output = render(p, data["files"][p])
            if output != (census.ROOT / p).read_bytes(): raise ValueError(f"{p}: output differs")
            rendered[p] = output
        if a.mode == "emit":
            destination = a.output.resolve()
            if destination.is_relative_to(census.ROOT): raise ValueError("output must remain outside checkout")
            destination.mkdir(parents=True, exist_ok=False)
            for p, output in rendered.items():
                target = destination / p
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(output)
        print("PASS: all 6903 declarations and complete module bytes reproduced")

if __name__ == "__main__": main()
