    def test_git_replacement_cannot_redefine_pinned_baseline(self):
        lane = self.root / LANE
        fragment = sorted((lane / "body").glob("[0-9]*.txt"))[0]
        changed = fragment.read_text().replace("/-!", "/-! Replacement fixture.", 1)
        fragment.write_text(changed)
        inventory = lane / "baseline-inventory.json"
        values = json.loads(inventory.read_text())
        values["body"][fragment.name] = hashlib.sha256(changed.encode()).hexdigest()
        inventory.write_text(json.dumps(values))
        rendered = self.run_gen("--render")
        self.assertEqual(rendered.returncode, 0, rendered.stderr)
        (self.root / TARGET).write_text(rendered.stdout)
        self.safe_run(["git", "add", "--", str(TARGET)], cwd=self.root, check=True)
        self.safe_run(["git", "commit", "-qm", "replacement source"], cwd=self.root, check=True)
        replacement = self.safe_run(["git", "rev-parse", "HEAD"], cwd=self.root,
                                     text=True, capture_output=True, check=True).stdout.strip()
        self.safe_run(["git", "replace", self.fixture_base, replacement],
                      cwd=self.root, check=True)
        rewritten = self.safe_run(["git", "show", self.fixture_base + ":" + str(TARGET)],
                                  cwd=self.root, text=True, capture_output=True, check=True)
        self.assertEqual(rewritten.stdout, rendered.stdout)
        checked = self.safe_run([sys.executable, "-B", str(lane / "census.py"), "--baseline"],
                                cwd=self.root, text=True, capture_output=True)
        self.assertEqual(checked.returncode, 1, checked.stdout + checked.stderr)

