#!/usr/bin/env python3
"""Writes the parsed `Census` and `LinkedMath` IR trees as Lean modules from
fixtures/census-tree.txt (printed from the parser's output by IrCensusGen.lean)
and the quoted fixture texts. Nothing here is trusted: `census_certified` and
`linked_certified` re-check each tree against its text by kernel evaluation.
Usage: gen-census-modules.py [--check]
"""
import sys, pathlib, re
here = pathlib.Path(__file__).resolve().parent
root = here.parents[2]
target_dir = root / "Solidity/SolcValidation"

def lean_str(s):
    assert all(ord(c) < 128 for c in s)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'

HEAD = """import Solidity.SolcValidation.IrParse
import Solidity.SolcValidation.IrEval
"""

def parse_lines():
    files = {}
    cur = None
    stack = []
    for line in (here / "fixtures/census-tree.txt").read_text().splitlines():
        tag, _, rest = line.partition(" ")
        if tag == "FILE":
            cur = rest; files[cur] = []
        elif tag == "OBJ":
            obj = {"name": rest, "bodies": [], "children": []}
            if stack: stack[-1]["children"].append(obj)
            else: files[cur].append(obj)
            stack.append(obj)
        elif tag == "SIGS": stack[-1]["sigs"] = rest
        elif tag == "BODY": stack[-1]["bodies"].append(rest)
        elif tag == "ITEMS": stack[-1]["items"] = rest
        elif tag == "DATA":
            name, _, bytes_ = rest.partition(" ")
            stack[-1]["children"].append({"data": name, "bytes": bytes_})
        elif tag == "END": stack.pop()
        else: raise ValueError(line)
    return files

def sig_list(sigs):
    return re.findall(r'⟨("[^"]*"), (\[[^\]]*\]), (\[[^\]]*\])⟩', sigs)

def code_module(obj, p, doc, imports=HEAD):
    sigs = sig_list(obj["sigs"])
    assert len(sigs) == len(obj["bodies"])
    P = p.capitalize()
    out = imports + f"""
/-!
{doc}
-/
namespace Solidity.SolcValidation.IrSyntax
open Solidity.SolcValidation

/-- The function group of `{obj['name']}`'s code, in definition order. -/
def {p}Sigs : List FnSig :=
  {obj['sigs']}

abbrev {P}Body (params rets : List String) :=
  Block ({p}Sigs ++ []) ⟨true, false⟩ (params ++ rets)
"""
    for i, ((n, ps, rs), b) in enumerate(zip(sigs, obj["bodies"])):
        out += f"\n/-- `{n[1:-1]}` -/\ndef {p}F{i} : {P}Body {ps} {rs} :=\n  {b}\n"
    chain = ".nil"
    for i in reversed(range(len(sigs))):
        chain = f"(.cons {p}F{i} {chain})"
    out += f"""
def {p}Bodies : Bodies ({p}Sigs ++ []) {p}Sigs :=
  {chain}

def {p}Items : Items ({p}Sigs ++ []) ⟨false, false⟩ [] {p}Sigs.length :=
  {obj['items']}

/-- The code block of `{obj['name']}`. -/
def {p}Code : Code := .mk {p}Sigs {p}Bodies {p}Items

/-- The function environment the object's code installs (`evalBlock` on `.nil`). -/
def {p}Env : FunEnv ({p}Sigs ++ []) := .group {p}Sigs {p}Bodies .nil

end Solidity.SolcValidation.IrSyntax
"""
    return out

DOC_C = """# Parsed `Census` IR: the creation object's code

Generated by `tests/fullscope-20261104/vt1/gen-census-modules.py` from the parser's
output on `fixtures/Census.unoptimized.yul` (`IrCensusGen.lean`); one definition per
function body, in the group's order. `census_certified`
(`SolcValidation/IrCensusTree.lean`) is what ties this term to the text."""
DOC_D = DOC_C.replace("the creation object's code", "the deployed object's code")
DOC_L = """# Parsed `LinkedMath` IR: the creation and deployed objects' code

Generated by `tests/fullscope-20261104/vt1/gen-census-modules.py` from the parser's
output on `fixtures/LinkedMath.unoptimized.yul` (`IrCensusGen.lean`). `linked_certified`
(`SolcValidation/IrCensusTree.lean`) is what ties this term to the text."""

def tree_module(files):
    census = (here / "fixtures/Census.unoptimized.yul").read_text()
    linked = (here / "fixtures/LinkedMath.unoptimized.yul").read_text()
    (c,) = files["Census.unoptimized"]
    (l,) = files["LinkedMath.unoptimized"]
    def data(obj):
        (d,) = [x for x in obj["children"] if "data" in x]
        return f'.data {lean_str(d["data"])} {d["bytes"]}'
    (cd,) = [x for x in c["children"] if "name" in x]
    (ld,) = [x for x in l["children"] if "name" in x]
    assert [x.get("name", x.get("data")) for x in c["children"]] == [cd["name"]]
    assert [x.get("name", x.get("data")) for x in cd["children"]] == [".metadata"]
    assert [x.get("name", x.get("data")) for x in l["children"]] == [ld["name"]]
    assert [x.get("name", x.get("data")) for x in ld["children"]] == [".metadata"]
    return f"""import Solidity.SolcValidation.IrCensusCreation
import Solidity.SolcValidation.IrCensusDeployed
import Solidity.SolcValidation.IrLinkedCode

/-!
# The parsed `Census` and `LinkedMath` IR trees, certified

`censusText` and `linkedText` are the saved solc 0.8.38 `--ir` (unoptimized)
fixtures `tests/fullscope-20261104/vt1/fixtures/{{Census,LinkedMath}}.unoptimized.yul`,
quoted verbatim (`gen-census-modules.py --check` compares them). `censusRoot` and
`linkedRoot` are the trees the parser returned for them, printed as terms by
`IrCensusGen.lean` (not checked by the kernel); the certificates prove by kernel
evaluation that each prints to exactly the lexed text and passes `objectWf` (the
`Parsed.sound` statement), so `censusParsed` is a `Parsed censusText`. That the
tree is the parser's own result is proved for LinkedMath only
(`linked_is_the_parse`). Generated by `gen-census-modules.py`.
-/
namespace Solidity.SolcValidation.IrSyntax
open Solidity.SolcValidation

def censusText : String :=
  {lean_str(census)}

def linkedText : String :=
  {lean_str(linked)}

def censusDeployedObj : Object Code :=
  .object {lean_str(cd['name'])} cdCode [{data(cd)}]

def censusRoot : Object Code :=
  .object {lean_str(c['name'])} ccCode [censusDeployedObj]

def linkedDeployedObj : Object Code :=
  .object {lean_str(ld['name'])} ldCode [{data(ld)}]

def linkedRoot : Object Code :=
  .object {lean_str(l['name'])} lcCode [linkedDeployedObj]

/-- The Census tree carries the parser's certificate for the Census fixture. -/
theorem census_certified :
    lex censusText = some (objectToks censusRoot) ∧ objectWf censusRoot = true := by
  decide +kernel

/-- The LinkedMath tree carries the parser's certificate for its fixture. -/
theorem linked_certified :
    lex linkedText = some (objectToks linkedRoot) ∧ objectWf linkedRoot = true := by
  decide +kernel

/-- The Census tree as a parse result of the Census text. -/
def censusParsed : Parsed censusText :=
  ⟨⟨{lean_str(c['name'])}, ccCode, [censusDeployedObj]⟩, objectToks censusRoot,
    census_certified.1, rfl, census_certified.2⟩

/-- The LinkedMath tree as a parse result of the LinkedMath text. -/
def linkedParsed : Parsed linkedText :=
  ⟨⟨{lean_str(l['name'])}, lcCode, [linkedDeployedObj]⟩, objectToks linkedRoot,
    linked_certified.1, rfl, linked_certified.2⟩

end Solidity.SolcValidation.IrSyntax
"""

def linked_module(files):
    (l,) = files["Linked" + "Math.unoptimized"]
    (ld,) = [x for x in l["children"] if "name" in x]
    a = code_module(l, "lc", DOC_L)
    b = code_module(ld, "ld", DOC_L)
    # one module: drop the second header/doc, keep its declarations
    body_b = b[b.index("namespace Solidity.SolcValidation.IrSyntax"):]
    body_b = body_b.replace("namespace Solidity.SolcValidation.IrSyntax\nopen Solidity.SolcValidation\n", "", 1)
    return a.replace("end Solidity.SolcValidation.IrSyntax\n", "") + body_b


SIG_RE = re.compile(r'⟨"([^"]*)", (\[[^\]]*\]), (\[[^\]]*\])⟩')

def sigs_of(module, name):
    text = (target_dir / module).read_text()
    i = text.index(f"def {name} : List FnSig :=")
    line = text[i:].split("\n")[1]
    return SIG_RE.findall(line)

def mem(i):
    return "(.there " * i + ".here" + ")" * i

# (source sigs, source module, prefix) -> targets
GROUPS = [("helperSigs", "IrHelpers.lean", "helpers"), ("expSigs", "IrExpHelpers.lean", "exp"),
          ("abiSigs", "IrAbiHelpers.lean", "abi"), ("pushSigs", "IrPushHelpers.lean", "push")]
TARGETS = [("cdSigs", "IrCensusDeployed.lean", "Cd"), ("ccSigs", "IrCensusCreation.lean", "Cc"),
           ("ldSigs", "IrLinkedCode.lean", "Ld")]
PAIRS = [("helpers", "Cd"), ("helpers", "Ld"), ("exp", "Cd"), ("abi", "Cd"), ("abi", "Ld"),
         ("push", "Cd"), ("push", "Cc")]

def maps_module():
    out = """import Solidity.SolcValidation.IrRename
import Solidity.SolcValidation.IrHelpers
import Solidity.SolcValidation.IrExpHelpers
import Solidity.SolcValidation.IrAbiHelpers
import Solidity.SolcValidation.IrPushHelpers
import Solidity.SolcValidation.IrCensusCreation
import Solidity.SolcValidation.IrCensusDeployed
import Solidity.SolcValidation.IrLinkedCode

/-!
# Where each extracted helper sits in the parsed Census and LinkedMath groups

Generated by `tests/fullscope-20261104/vt1/gen-census-modules.py`. `ren<Group><Obj>`
maps each function of an extracted helper group to the function with the same
signature (name, parameters, returns) in the code group of a parsed object
(`Cd`: `Census_134_deployed`, `Cc`: `Census_134`, `Ld`: `LinkedMath_14_deployed`),
and to `none` when that object does not define it. The membership's type fixes
the signature, so a wrong position does not elaborate; what the bodies are is
proved in `SolcValidation/IrCensusTransfer.lean`.
-/
namespace Solidity.SolcValidation.IrSyntax
open Solidity.SolcValidation
"""
    srcs = {p: (n, m) for n, m, p in GROUPS}
    tgts = {p: (n, m) for n, m, p in TARGETS}
    for g, t in PAIRS:
        sn, sm = srcs[g]; tn, tm = tgts[t]
        ss = sigs_of(sm, sn); ts = sigs_of(tm, tn)
        out += f"\n/-- `{sn}` into `{tn}`. -/\ndef ren{g.capitalize()}{t} : Ren ({sn} ++ []) ({tn} ++ []) :=\n  fun m => (\n"
        for i, sig in enumerate(ss):
            j = ts.index(sig) if sig in ts else None
            rhs = f"(some {mem(j)})" if j is not None else "none"
            out += f"  -- {sig[0]}\n  Ren.cons {rhs} <|\n"
        out += "  Ren.nil) m\n"
    return out + "\nend Solidity.SolcValidation.IrSyntax\n"

files = parse_lines()
(c,) = files["Census.unoptimized"]
(cd,) = [x for x in c["children"] if "name" in x]
outputs = {
    "IrCensusCreation.lean": code_module(c, "cc", DOC_C),
    "IrCensusDeployed.lean": code_module(cd, "cd", DOC_D),
    "IrLinkedCode.lean": linked_module(files),
    "IrCensusTree.lean": tree_module(files),
}
outputs["IrCensusMaps.lean"] = maps_module()
failed = False
for name, out in outputs.items():
    t = target_dir / name
    if "--check" in sys.argv:
        if not t.exists() or t.read_text() != out:
            print(f"{name} differs"); failed = True
    else:
        t.write_text(out); print(t, len(out), "bytes")
if "--check" in sys.argv:
    if failed: sys.exit(1)
    print("CENSUS_MODULES_CHECK_PASS")
