#!/usr/bin/env python3
"""H44: the lane's bulk run data stays off Git, recorded by a sha256 manifest.

`runs/BULK.json` lists every bulk file (repository-relative path, bytes,
sha256) and where its exact bytes come from: the frozen final manifest is
regenerated by `tools/freeze_final.py` (byte-identical), and every run
record, compact log and full-record archive is read from the Git object of
the commit that last held it (`source_commit`; removed from the branch, not
from history).  Nothing is trusted unverified: each file is checked against
its size and sha256 after it is restored.

  bulk.py freeze    write runs/BULK.json from the files present now
  bulk.py verify    check every bulk file present; list the absent ones
  bulk.py restore   restore every bulk file, verify it, and unpack the final
                    run's full records into runs/<run>/checks/ (ignored),
                    so that accept.py and seal.py --verify run in full

With the bulk files absent, `seal.py --verify` checks every sealed file that
is in Git and reports the bulk ones as absent with their manifest digest.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tarfile

LANE = "tests/h28-sol/mutation-testing"
REPO = Path(__file__).resolve().parents[4]
MANIFEST = REPO / LANE / "runs/BULK.json"
FINAL = "final-8fad7b13"
REGENERATED = {LANE + "/manifests/h28-final.json": "python3 tests/h28-sol/mutation-testing/tools/freeze_final.py"}


def sha(data):
    return hashlib.sha256(data).hexdigest()


def bulk_paths():
    """The bulk: every run record but the final run's summary, acceptance
    and seal, and the frozen final manifest."""
    runs = REPO / LANE / "runs"
    keep = {f"{LANE}/runs/{FINAL}/{n}" for n in ("summary.json", "acceptance.json", "seal.json")}
    keep.add(f"{LANE}/runs/BULK.json")
    out = sorted(str(p.relative_to(REPO)) for p in runs.rglob("*")
                 if p.is_file() and "/checks/" not in str(p) and str(p.relative_to(REPO)) not in keep)
    return [LANE + "/manifests/h28-final.json"] + out


def freeze():
    head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO, text=True).strip()
    files = {}
    for p in bulk_paths():
        data = (REPO / p).read_bytes()
        files[p] = {"bytes": len(data), "sha256": sha(data)}
        if p in REGENERATED:
            files[p]["regenerate"] = REGENERATED[p]
    MANIFEST.write_text(json.dumps({"schema": 1, "authorization": "H44",
                                    "final_run": FINAL, "source_commit": head,
                                    "files": files}, indent=1) + "\n")
    print(len(files), "bulk files;", sum(f["bytes"] for f in files.values()), "bytes; source", head)


def load():
    return json.loads(MANIFEST.read_text())


def verify():
    m = load()
    bad, absent = [], []
    for p, f in m["files"].items():
        q = REPO / p
        if not q.exists():
            absent.append(p)
            continue
        data = q.read_bytes()
        if len(data) != f["bytes"] or sha(data) != f["sha256"]:
            bad.append(p)
    print(json.dumps({"verified": not bad, "files": len(m["files"]), "present": len(m["files"]) - len(absent),
                      "absent": absent, "mismatch": bad}, indent=1))
    return not bad


def restore():
    m = load()
    for p, f in m["files"].items():
        q = REPO / p
        if p in REGENERATED:
            subprocess.run(REGENERATED[p].split(), cwd=REPO, check=True, stdout=subprocess.DEVNULL)
        else:
            q.parent.mkdir(parents=True, exist_ok=True)
            q.write_bytes(subprocess.check_output(["git", "show", f"{m['source_commit']}:{p}"], cwd=REPO))
        data = q.read_bytes()
        if len(data) != f["bytes"] or sha(data) != f["sha256"]:
            raise SystemExit("restored bulk file differs from its manifest digest: " + p)
    run = REPO / LANE / "runs" / m["final_run"]
    with tarfile.open(run.parent / (m["final_run"] + "-checks-full.tar.gz")) as t:
        for member in t:
            inside = member.name == m["final_run"] + "/checks" or member.name.startswith(m["final_run"] + "/checks/")
            if not (member.isfile() or member.isdir()) or member.name.startswith("/") or \
                    ".." in Path(member.name).parts or not inside:
                raise SystemExit("unexpected archive member: " + member.name)
        t.extractall(run.parent, filter="data")
    print("restored and verified", len(m["files"]), "bulk files; records unpacked into", run.relative_to(REPO) / "checks")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "verify"
    if cmd == "freeze":
        freeze()
    elif cmd == "restore":
        restore()
    else:
        sys.exit(0 if verify() else 1)
