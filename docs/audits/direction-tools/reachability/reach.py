BASE = 'd4ad633a9624263a59b14fd2c520b9bc602f88f3'
TOKEN = re.compile(r"[^\W\d][\w'!?]*(?:\.[^\W\d][\w'!?]*)*", re.UNICODE)
DECL = re.compile(r"^[ \t]*(?:@\[[^\]]*\][ \t]*(?:\n[ \t]*)?)*(?:(?:private|protected|noncomputable|nonrec|partial|unsafe)\s+)*(theorem|lemma|def|abbrev|structure|inductive|class|instance|axiom|opaque)\b(?:[ \t]+([^\s(:{\[=]+))?", re.M)
