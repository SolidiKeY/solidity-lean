#!/usr/bin/env python3
"""Committed-tree lexical census. Run: python3 docs/audits/direction-tools/census/metrics.py
No Lean elaboration. Python 3 standard library only. See census.json methodology.
"""
import argparse, bisect, collections, csv, io, json, pathlib, re, subprocess
BASE = "d4ad633a9624263a59b14fd2c520b9bc602f88f3"
OUT = pathlib.Path(__file__).resolve().parent
KINDS = ("def", "theorem", "lemma", "instance", "structure", "inductive", "abbrev", "axiom", "opaque")
DECL = re.compile(r"^[ \t]*(?:@\[[^\n]*?\][ \t]*)*(?:(?:private|protected|noncomputable|unsafe|partial|nonrec)\s+)*(" + "|".join(KINDS) + r")\b", re.M)

def git(*args):
    return subprocess.check_output(["git", *args])

def tree(rev):
    entries = git("ls-tree", "-r", "-z", rev).split(b"\0")
    return {p.decode(): meta.split()[2].decode() for row in entries if row for meta,p in [row.split(b"\t",1)] if meta.startswith(b"100")}

def blobs(paths):
    # One cat-file process; no checkouts or per-file process overhead.
    proc = subprocess.run(["git", "cat-file", "--batch"], input=("\n".join(paths.values())+"\n").encode(), stdout=subprocess.PIPE, check=True)
    stream = io.BytesIO(proc.stdout); result = {}
    for path in paths:
        header = stream.readline().split(); size = int(header[2])
        result[path] = stream.read(size).decode("utf-8", errors="replace"); stream.read(1)
    return result

def clean(text):
    # Preserve newlines/offsets while removing nested comments and string literals.
    out=list(text); i=0; depth=0; string=False
    while i<len(text):
        if depth:
            if text.startswith("/-",i): out[i:i+2]=[" "," "]; depth+=1; i+=2; continue
            if text.startswith("-/",i): out[i:i+2]=[" "," "]; depth-=1; i+=2; continue
            if text[i]!="\n": out[i]=" "
            i+=1; continue
        if string:
            if text[i]=="\\" and i+1<len(text):
                out[i]=" "; out[i+1]="\n" if text[i+1]=="\n" else " "; i+=2; continue
            if text[i]=='"': string=False
            if text[i]!="\n": out[i]=" "
            i+=1; continue
        if text.startswith("--",i):
            j=text.find("\n",i); j=len(text) if j<0 else j
            out[i:j]=" "*(j-i); i=j; continue
        if text.startswith("/-",i): out[i:i+2]=[" "," "]; depth=1; i+=2; continue
        if text[i]=="'" and (i==0 or not (text[i-1].isalnum() or text[i-1] in "_'")):
            char=re.match(r"'(?:\\(?:u\{[0-9a-fA-F]+\}|x[0-9a-fA-F]{2}|.)|[^\\'\n])'",text[i:])
            if char:
                j=i+len(char.group()); out[i:j]=" "*(j-i); i=j; continue
        if text[i]=='"': out[i]=" "; string=True
        i+=1
    return "".join(out)

def category(path,text):
    if "AxiomPins" in path: return "axiom_pins"
    if path.startswith("Solidity/Corpus/") and path != "Solidity/Corpus/Basic.lean": return "corpus"
    code=clean(text)
    meaningful=[l.strip() for l in code.splitlines() if l.strip()]
    if meaningful and all(l.startswith("import ") for l in meaningful): return "generated_root" if path in {"Solidity.lean", "SolidityExamples.lean", "SoliditySlowExamples.lean", "SolidityCorpus.lean", "Bridge/SolidityBridge.lean"} or "Generated by `scripts/coord-tools/register.sh`" in text else "import_only_unknown"
    # Marker must say the SOURCE is generated, not merely mention generated values.
    if re.search(r"(?im)^\s*(?:--|/[-*!]+)?\s*(?:auto[- ]generated|generated (?:by|from)|.*kernel controls, generated by)", text[:2000]): return "marked_generated"
    return "unmarked"

def module(path,text):
    code=clean(text); matches=list(DECL.finditer(code)); counts=collections.Counter(m.group(1) for m in matches)
    spans=collections.Counter()
    # Lexical command spans, not kernel proof size: until next top-level command.
    boundaries=list(re.finditer(r"(?m)^(?:@\[|(?:private |protected |noncomputable |unsafe |partial )*(?:def|theorem|lemma|instance|structure|inductive|abbrev|axiom|opaque)\b|end\b|namespace\b|section\b|open\b|set_option\b|attribute\b|#)",code))
    positions=sorted({b.start() for b in boundaries} | {m.start() for m in matches})
    for m in matches:
        start=code.rfind("\n",0,m.end())+1
        idx=bisect.bisect_right(positions,max(m.start(),start))
        following=positions[idx] if idx<len(positions) else len(code)
        spans["proof_lines" if m.group(1) in ("theorem","lemma") else "definition_lines"]+=sum(bool(l.strip()) for l in code[m.start():following].splitlines())
    imports=re.findall(r"(?m)^\s*import\s+([^\n]+)",code)
    imports=[x for line in imports for x in line.split()]
    heading=re.search(r"/[-!]+[ \t]*\n(?:[ \t]*\n)*[ \t]*#?[ \t]*([^\n]+)",text)
    names=[code[m.end():].lstrip().split()[0] for m in matches[:3] if code[m.end():].strip()]
    description=(heading.group(1).strip()[:220] if heading else "Declarations: "+", ".join(names))
    d={"description":description,"path":path,"area":path.split("/")[1].removesuffix(".lean") if "/" in path else "_roots", "lines":len(text.splitlines()),"code_lines":sum(bool(l.strip()) for l in code.splitlines()),"category":category(path,text),"roadmap_commands":len(re.findall(r"(?m)^\s*#roadmap\b",code)),"declarations":dict(counts),**dict(spans),"imports":imports}
    for token in ("sorry","native_decide","implemented_by"):
        d[token]=len(re.findall(r"\b"+token+r"\b",code))
    d["definition_to_proof_line_ratio"]=d.get("definition_lines",0)/d["proof_lines"] if d.get("proof_lines") else None
    d["maxHeartbeats"] = re.findall(r"\bset_option\s+maxHeartbeats\s+([^\s]+)",code)
    return d

def aggregate(mods):
    d={k:sum(m.get(k,0) for m in mods) for k in ("lines","code_lines","definition_lines","proof_lines","sorry","native_decide","implemented_by")}
    d["files"]=len(mods); d["declarations"]={k:sum(m["declarations"].get(k,0) for m in mods) for k in KINDS}
    d["by_category"]={k:{"files":sum(m["category"]==k for m in mods),"lines":sum(m["lines"] for m in mods if m["category"]==k)} for k in sorted({m["category"] for m in mods})}
    d["generated_lines"]=sum(m["lines"] for m in mods if m["category"] not in ("unmarked","import_only_unknown"))
    d["presumed_handwritten_lines"]=sum(m["lines"] for m in mods if m["category"]=="unmarked")
    d["unknown_import_only_lines"]=sum(m["lines"] for m in mods if m["category"]=="import_only_unknown")
    d["generated_share"]=d["generated_lines"]/d["lines"] if d["lines"] else None
    d["definition_to_proof_line_ratio"]=d["definition_lines"]/d["proof_lines"] if d["proof_lines"] else None
    d["maxHeartbeats_options"]=sum(len(m["maxHeartbeats"]) for m in mods)
    d["imports_out"]=sum(len(m["imports"]) for m in mods); d["imports_in"]=sum(m.get("imports_in",0) for m in mods)
    return d

def dump(path,data): path.write_text(json.dumps(data,indent=2,sort_keys=True)+"\n")

def inventory(paths):
    candidates=["docs/audits/architecture-tools/","docs/audits/proof-coverage-tools/","docs/audits/build-speed", "scripts/build-measure", "scripts/differential/", "scripts/bench/"]
    return {prefix:sorted(p for p in paths if p.startswith(prefix)) for prefix in candidates}

def run(rev,out):
    paths=tree(rev); selected={p:b for p,b in paths.items() if p.endswith(".lean")}
    texts=blobs(selected); allmods=[module(p,t) for p,t in sorted(texts.items())]
    incoming=collections.Counter(i for m in allmods for i in m["imports"])
    for m in allmods: m["imports_in"]=incoming[m["path"][:-5].replace("/",".")]
    mods=[m for m in allmods if m["path"].startswith("Solidity/")]
    areas={a:aggregate([m for m in mods if m["area"]==a]) for a in sorted({m["area"] for m in mods})}
    timing_path="docs/audits/architecture-tools/timing-sample.tsv"
    timing=[]
    if timing_path in paths:
        raw=blobs({timing_path:paths[timing_path]})[timing_path]
        for line in raw.splitlines():
            if line == "done" or not line.strip(): continue
            group,p,full,imports,status=line.replace(r"\t", "\t").split("\t")
            if p not in texts: continue
            timing.append(dict(path=p,area=p.split("/")[1],group=group,full_seconds=float(full),import_seconds=float(imports),body_seconds=float(full)-float(imports),status=status,lines=len(texts[p].splitlines())))
    for area,d in areas.items():
        rows=[r for r in timing if r["area"]==area and r["status"]=="PASS"]
        n=sum(r["lines"] for r in rows)
        d["timing"]={"sample_files":len(rows),"sample_lines_at_census_revision":n,"full_seconds":sum(r["full_seconds"] for r in rows),"body_seconds":sum(r["body_seconds"] for r in rows),"body_seconds_per_1k_lines":1000*sum(r["body_seconds"] for r in rows)/n if n else None,"coverage":"historical_sample" if rows else "no_data"}
    out.mkdir(parents=True,exist_ok=True)
    chunks=[]
    for i in range(0,len(mods),300):
        name=f"modules-{i//300:02d}.json"; dump(out/name,mods[i:i+300]); chunks.append(name)
    data={"revision":rev,"scope":"Solidity/**/*.lean (tracked committed blobs); repository totals include all tracked .lean", "repository_totals":aggregate(allmods),"solidity_totals":aggregate(mods),"outside_solidity_totals":aggregate([m for m in allmods if not m["path"].startswith("Solidity/")]),"areas":areas,"module_chunks":chunks,"inventory":inventory(paths),"timing_source":timing_path,"timing_rows":timing,"methodology":{"counts":"Lexical, nested comments and strings removed; anchored declaration commands; no kernel/semantic claims. Physical lines include comments/blanks.","line_ratio":"Nonblank lexical command spans for theorem/lemma versus other declaration kinds; instance proofs counted under definition. Approximation, not proof-term size.","generated":"Corpus except handwritten Basic.lean, AxiomPins, proven generated registry roots, explicit source-generation header; other import-only modules are unknown; unmarked is presumed handwritten, may contain unmarked generated code. Chain/agreement name alone is not a generation marker.","imports":"Direct syntactic edges, multiplicity preserved; incoming includes all tracked Lean modules. Not transitive closure.","timing":"Historical CPU sample: column 3 full, column 4 import-only, difference body. Denominator uses census revision lines, not proven identical timed source. No area-wide estimate or current benchmark.","references":"docs/audits/architecture.md section 3; reused committed timing, no Lean executed."}}
    dump(out/"census.json",data)
    fields=["area","files","lines","generated_lines","generated_share","definition_lines","proof_lines","definition_to_proof_line_ratio","sorry","native_decide","implemented_by","imports_in","imports_out","maxHeartbeats_options",*KINDS,"timed_files","sample_body_seconds_per_1k_lines"]
    with (out/"areas.csv").open("w",newline="") as f:
        w=csv.DictWriter(f,fieldnames=fields); w.writeheader()
        for a,d in areas.items(): w.writerow({"area":a,**{k:d[k] for k in fields if k in d},**d["declarations"],"timed_files":d["timing"]["sample_files"],"sample_body_seconds_per_1k_lines":d["timing"]["body_seconds_per_1k_lines"]})
    print(json.dumps({"revision":rev,"totals":data["solidity_totals"],"module_chunks":len(chunks)}))
    return data,mods

if __name__=="__main__":
    ap=argparse.ArgumentParser(description=__doc__); ap.add_argument("--rev",default=BASE); ap.add_argument("--out",type=pathlib.Path,default=OUT); args=ap.parse_args()
    run(git("rev-parse",args.rev).decode().strip(),args.out)
