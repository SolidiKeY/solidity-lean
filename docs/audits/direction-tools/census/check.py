#!/usr/bin/env python3
"""Parser controls and accounting invariants, no Lean or external dependencies."""
import sys
sys.dont_write_bytecode=True
import json, pathlib
from metrics import OUT, aggregate, category, clean, module

def main():
    sample = 'import A\n/- theorem fake : True := by trivial /- nested -/ -/\n-- sorry\ndef text := "native_decide sorry"\n@[simp] theorem real : True := by\n  trivial\naxiom trusted : True\nset_option maxHeartbeats 900\n'
    m=module("Solidity/Test.lean",sample)
    assert m["declarations"]=={"def":1,"theorem":1,"axiom":1},m
    assert m["sorry"]==0 and m["native_decide"]==0
    assert m["maxHeartbeats"]==["900"]
    quoted=module("Solidity/Test.lean", "def quote := '\"'\ndef real := 1\ndef nextQuote := '\"'\ntheorem stillReal : True := by trivial\n")
    assert quoted["declarations"]=={"def":3,"theorem":1},quoted
    assert clean("def foo'a' := 1").strip()=="def foo'a' := 1"
    assert clean('a /- nested /- x -/ y -/ b').strip()=='a                        b'.strip() or clean('a /- nested /- x -/ y -/ b').split()==['a','b']
    assert category("Solidity/Corpus/Basic.lean","def a := 1")=="unmarked"
    assert category("Solidity/Corpus/TestSuite.lean","")=="corpus"
    assert category("Solidity/AxiomPins.lean","")=="axiom_pins"
    assert category("Solidity/Area.lean","import A\nimport B")=="import_only_unknown"
    assert category("Solidity/Agreement.lean","-- Generated by script\ndef a := 1")=="marked_generated"
    assert category("Solidity/Chain.lean","-- The generated value is observed.\ndef a := 1")=="unmarked"
    data=json.loads((OUT/"census.json").read_text())
    mods=[m for name in data["module_chunks"] for m in json.loads((OUT/name).read_text())]
    assert len({m["path"] for m in mods})==len(mods)
    assert aggregate(mods)==data["solidity_totals"]
    assert all(m.get("definition_lines",0)+m.get("proof_lines",0)<=m["code_lines"] for m in mods)
    assert sum(a["lines"] for a in data["areas"].values())==sum(m["lines"] for m in mods)
    assert len(data["timing_rows"])==60
    for a in data["areas"].values():
        assert a["lines"]==a["generated_lines"]+a["presumed_handwritten_lines"]+a["unknown_import_only_lines"]
    for p in OUT.iterdir():
        if p.suffix in (".json",".csv"): assert p.stat().st_size<1_000_000,(p,p.stat().st_size)
    history=json.loads((OUT/"history.json").read_text())
    assert history[-1]["revision"]==data["revision"]
    assert history[-1]["lines"]==data["solidity_totals"]["lines"]
    assert history[-1]["imports_in"]==data["solidity_totals"]["imports_in"]
    assert all(r["lines_added_per_goal_closed"] is None for r in history)
    print("PASS parser controls, unique modules, all area/category accounting, 60 historical timing rows, monthly endpoint, data size caps")

if __name__=="__main__": main()
