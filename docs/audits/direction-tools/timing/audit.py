#!/usr/bin/env python3
"""Pinned inventory: python3 docs/audits/direction-tools/timing/audit.py --out DIR.
Reads committed base blobs, never the cache. Physical lines include comments.
Historical times are NOT fresh measurements or matched reference timings.
"""
import argparse, collections, hashlib, json, pathlib, re, subprocess
BASE='d6fd95f0886775d7c286813fa9b993a40ba7a777'
ROOT=pathlib.Path(__file__).resolve().parents[4]
def git(*args):
    return subprocess.check_output(['git','-C',str(ROOT),*args])
def snapshot():
    rows=git('ls-tree','-r',BASE).decode().splitlines()
    mapping={r.split('\t',1)[1]:r.split()[2] for r in rows if r.split()[1]=='blob'}
    selected={p:s for p,s in mapping.items() if p.endswith('.lean')}
    objects=list(dict.fromkeys(selected.values()))
    raw=subprocess.run(['git','-C',str(ROOT),'cat-file','--batch'],input=('\n'.join(objects)+'\n').encode(),stdout=subprocess.PIPE,check=True).stdout
    pos=0; texts={}
    for sha in objects:
        end=raw.index(b'\n',pos); size=int(raw[pos:end].split()[-1]); pos=end+1
        texts[sha]=raw[pos:pos+size].decode(errors='replace'); pos+=size+1
    return mapping,{p:texts[s] for p,s in selected.items()}
def strip_comments(text):
    # Nested Lean comments and quoted strings, preserving newlines for imports.
    out=[]; i=0; depth=0; string=False
    while i<len(text):
        pair=text[i:i+2]; c=text[i]
        if depth:
            if pair=='/-': depth+=1; i+=2; continue
            if pair=='-/': depth-=1; i+=2; continue
            out.append('\n' if c=='\n' else ' '); i+=1; continue
        if string:
            if c=='\\': out.extend('  '); i+=2; continue
            if c=='"': string=False
            out.append('\n' if c=='\n' else ' '); i+=1; continue
        if pair=='/-': depth=1; i+=2; continue
        if pair=='--':
            j=text.find('\n',i); i=len(text) if j<0 else j; continue
        if c=='"': string=True; out.append(' '); i+=1; continue
        out.append(c); i+=1
    return ''.join(out)
def area(p):
    if p.startswith('Bridge/SolidityBridge/'): return 'Bridge'
    if p.startswith('Solidity/'): return p.split('/')[1] if '/' in p[9:] else 'Core'
    return 'Other'
def generated(p,t):
    if re.search(r'(?:^|/)(?:Corpus|Generated)(?:/|$)|AxiomPins|(?:^|/)(?:Solidity|SolidityExamples|SolidityBridge)\.lean$',p): return 'detected_generated'
    if re.search(r'(?im)^-- BEGIN generated',t): return 'mixed_generated_regions'
    if re.search(r'auto.?generated|generated by|do not edit',t[:1500],re.I): return 'marker_associated_unresolved'
    if re.search(r'chain|agreement',p,re.I): return 'unresolved_chain_agreement'
    return 'unmarked_not_proven_handwritten'
def generation_counts(p,t):
    category=generated(p,t); lines=t.splitlines()
    if category!='mixed_generated_regions': return {category+'_lines':len(lines)}
    inside=False; generated_lines=0
    for line in lines:
        if re.match(r'-- BEGIN generated',line): inside=True
        if inside: generated_lines+=1
        if re.match(r'-- END generated',line): inside=False
    return {'detected_generated_lines':generated_lines,'unmarked_not_proven_handwritten_lines':len(lines)-generated_lines}
def module_name(p):
    p=p.removeprefix('Bridge/').removesuffix('.lean')
    if p.startswith('vendor/'): p=p.removeprefix('vendor/')
    if p.startswith('vendor/LeanTeX/'): p=p.removeprefix('vendor/LeanTeX/')
    # LeanTeX library srcDir is vendor/LeanTeX, unlike Bridge vendor libraries.
    if p.startswith('LeanTeX/LeanTeX'): p=p.removeprefix('LeanTeX/')
    return p.replace('/','.')
def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--out',type=pathlib.Path,required=True); args=ap.parse_args()
    mapping,texts=snapshot(); modules={}
    counts=collections.defaultdict(collections.Counter)
    for p,t in texts.items():
        a=area(p); n=len(t.splitlines()); g=generated(p,t)
        counts[a]['modules']+=1; counts[a]['lines']+=n; counts[a].update(generation_counts(p,t))
        m=module_name(p)
        if m in modules: raise ValueError('duplicate module mapping: '+m)
        clean=strip_comments(t); imports=[]
        for line in clean.splitlines():
            s=line.strip()
            if not s or s in ('module','prelude'): continue
            match=re.match(r'(?:(?:public|meta)\s+)*import\s+(?:all\s+)?(.+)',s)
            if not match: break
            imports.extend(match.group(1).split())
        modules[m]={'path':p,'area':a,'lines':n,'classification':g,'imports':imports}
    largest=sorted((a for a in counts if a not in ('Other','Core')),key=lambda a:(-counts[a]['lines'],a))[:10]
    reverse=collections.defaultdict(set)
    for m,row in modules.items():
        for dep in row['imports']:
            if dep in modules: reverse[dep].add(m)
    def dependents(m):
        seen=set(); todo=list(reverse[m])
        while todo:
            x=todo.pop()
            if x in seen: continue
            seen.add(x); todo.extend(reverse[x]-seen)
        return seen
    core=['Solidity.Keccak','Solidity.KeySort','Solidity.AST','Solidity.Syntax.Raw','Solidity.Semantics.Value','Solidity.Source.Types']
    def closure(roots):
        seen=set(); todo=list(roots)
        while todo:
            x=todo.pop()
            if x in seen or x not in modules: continue
            seen.add(x); todo.extend(modules[x]['imports'])
        return seen
    workloads={'checkpoint':['Solidity'],'full':['Solidity','SolidityExamples','SoliditySlowExamples','SolkeyTestSuite','SolidityLean'],'Bridge':['SolidityBridge']}
    reachable={name:closure(roots) for name,roots in workloads.items()}
    incremental=[]
    for m in core:
        if m not in modules: continue
        deps=dependents(m)
        incremental.append({'module':m,'all_tracked_potential_dependents':len(deps),'workload_rebuilds':{name:len((deps|{m})&reached) for name,reached in reachable.items()},'rebuilds_including_changed_module':len(deps|{m}),'dependent_lines':sum(modules[x]['lines'] for x in deps)})
    source='docs/audits/architecture-tools/timing-sample.tsv'; samples=[]
    for line in git('show',BASE+':'+source).decode().splitlines():
        cols=line.replace('\\t','\t').split('\t')
        if len(cols)!=5: continue
        stratum,p,wall,rss,status=cols
        if p not in texts: continue
        samples.append({'path':p,'area':area(p),'historical_wall_seconds':float(wall),'historical_peak_gib':float(rss),'status':status,'base_lines':len(texts[p].splitlines()),'classification':generated(p,texts[p]),'stratum':stratum})
    inputs={}
    for prefix in ['docs/audits/architecture-tools','docs/audits/proof-coverage-tools','docs/audits/build-speed','scripts/build-measure','scripts/differential','scripts/bench']:
        paths=sorted(p for p in mapping if p.startswith(prefix))
        inputs[prefix]={'files':paths,'present':bool(paths)}
    # Four deterministic size quartiles per area, selecting the lower middle.
    selected=[]
    for a in largest:
        candidates=sorted((r for r in modules.values() if r['area']==a),key=lambda r:(r['lines'],r['path']))
        for q in range(4):
            r=candidates[min(len(candidates)-1,((2*q+1)*len(candidates))//8)]
            selected.append({**r,'quartile':q+1})
    out={'base':BASE,'method':'all tracked Lean physical lines; nested-comment/string-stripped header imports; transitive reverse closure includes roots and Bridge, excludes external packages; generated path markers plus bounded BEGIN/END regions; ambiguous file headers and chain/agreement names unresolved; remaining lines not proven handwritten','areas':dict(sorted(counts.items())),'largest_areas':largest,'inputs':inputs,'incremental':incremental,'build_workloads':{name:{'roots':workloads[name],'reachable_modules':len(reached)} for name,reached in reachable.items()},'historical':{'source':source,'source_base':'d4ad633a9624263a59b14fd2c520b9bc602f88f3','warning':'60 nonrandom historical observations; base_lines are current pinned base, NOT measured-source denominator; no fresh seconds/kloc inferred','samples':samples},'sample_plan':selected}
    args.out.mkdir(parents=True,exist_ok=True)
    (args.out/'inventory.json').write_text(json.dumps(out,indent=2,sort_keys=True)+'\n')
    print(json.dumps({'tracked_lean':len(texts),'largest_areas':largest,'planned_samples':len(selected),'historical_observations':len(samples),'incremental':incremental},indent=2))
if __name__=='__main__': main()
