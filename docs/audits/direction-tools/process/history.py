#!/usr/bin/env python3
"""Read-only process census. Python stdlib; no checkouts, builds or dependencies.

Run at repository root:
 python3 docs/audits/direction-tools/process/history.py --out /tmp/process-results
Optional reference reproduction:
 git clone --depth 1 https://github.com/AbsInt/CompCert.git /tmp/process-compcert
 git -C /tmp/process-compcert fetch --depth 1 origin 2685140bf72c959446981fb99b5e44a8975021bc
 python3 docs/audits/direction-tools/process/history.py --out /tmp/process-results --compcert /tmp/process-compcert

All source counts are physical lines (blank/comments included), not proof terms,
semantic work, or person-hours. Snapshot trust tokens are lexical indicators.
History uses all reachable NON-MERGE commits, no rename detection (moves become
creation/deletion), committer UTC month; first-parent sensitivity is also emitted.
A rewrite means a non-creation edit, NOT a complete rewrite of a file.
"""
import argparse
import collections as C
import hashlib
import io
import json
import pathlib
import re
import subprocess as S
import tarfile

BASE = 'd4ad633a9624263a59b14fd2c520b9bc602f88f3'
REF = '2685140bf72c959446981fb99b5e44a8975021bc'
ROOTS = {'Solidity.lean', 'SolidityExamples.lean', 'Bridge/SolidityBridge.lean', 'SolidityCorpus.lean', 'SoliditySlowExamples.lean'}
GEN = re.compile(r'(?im)^\s*(?:--\s*|/[-!]\s*)?(?:auto[- ]generated|generated by|generated file|do not edit)\b')
PIN = re.compile(r'^\s*#(?:guard_msgs(?:\s*\([^)]*\))?\s+in\s+#)?print\s+axioms\b')
INFRA = ('coordination', 'scripts_other', 'generated_registry', 'ci', 'docs', 'generated_docs', 'generated_roots')


def git(*args, repo='.'):
    return S.check_output(['git', '-C', str(repo), *args])


def sources(rev, repo='.'):
    proc = S.Popen(['git', '-C', str(repo), 'archive', rev], stdout=S.PIPE)
    with tarfile.open(fileobj=proc.stdout, mode='r|') as archive:
        for m in archive:
            if m.isfile():
                data = archive.extractfile(m).read()
                if b'\0' not in data:
                    yield m.name, data.decode('utf-8', 'replace')
    if proc.wait():
        raise RuntimeError('git archive failed')


def lines(text):
    return len(text.splitlines())


def generated(path, text=''):
    if path in ROOTS:
        return 'generated_roots'
    if path.startswith('Solidity/Corpus/'):
        return 'generated_corpus'
    if path.endswith('.lean') and ('AxiomPins' in path or (path.endswith('Pins.lean') and GEN.search(text[:2500]))):
        return 'axiom_pins_files'
    if path.startswith('docs/') and (re.search(r'(?i)<!-- Generated from', text[:500]) or GEN.search(text[:2500])):
        return 'generated_docs'
    if path == 'scripts/g07-axiom-pins.json':
        return 'generated_registry'
    if path.endswith('.lean') and GEN.search(text[:2500]):
        return 'generated_other'
    return None


def category(path, gen):
    if path in gen:
        return gen[path]
    if path.startswith('scripts/coord-tools/'):
        return 'coordination'
    if path.startswith('scripts/'):
        return 'scripts_other'
    if path.startswith('.github/'):
        return 'ci'
    if path.startswith('docs/') or path.endswith('.md'):
        return 'docs'
    if path.startswith('Solidity/') and path.endswith('.lean'):
        return 'solidity_header_unmarked_proofs_and_definitions'
    if path.endswith('.lean'):
        return 'other_lean'
    return 'other'


def blank_lean(text):
    """Blank nested Lean comments and ordinary/raw strings, keeping newlines.

    This is a source metric, not Lean parsing; macro quotations and escaped
    identifiers can still contain apparent tokens. No kernel claim follows.
    """
    out = list(text); i = 0
    while i < len(text):
        start = i
        if text.startswith('/-', i):
            depth = 1; i += 2
            while i < len(text) and depth:
                if text.startswith('/-', i): depth += 1; i += 2
                elif text.startswith('-/', i): depth -= 1; i += 2
                else: i += 1
        elif text.startswith('--', i):
            i = text.find('\n', i)
            if i < 0: i = len(text)
        else:
            raw = re.match(r'r(#+)?"', text[i:i+20]) if text[i] == 'r' else None
            if raw:
                delim = '"' + (raw[1] or '')
                end = text.find(delim, i + len(raw[0]))
                i = len(text) if end < 0 else end + len(delim)
            elif text[i] == '"':
                i += 1
                while i < len(text):
                    if text[i] == '\\': i += 2
                    elif text[i] == '"': i += 1; break
                    else: i += 1
            else:
                i += 1; continue
        for j in range(start, min(i, len(text))):
            if out[j] != '\n': out[j] = ' '
    return ''.join(out)


def snapshot(rev):
    counts = C.Counter(); trust = C.Counter(); trust_bridge = C.Counter(); gen = {}; details = {}; inventory = None; policy = ''
    for path, text in sources(rev):
        g = generated(path, text)
        if g: gen[path] = g
        c = category(path, gen); counts[c] += lines(text)
        if path == 'tests/trust-inventory.json': inventory = json.loads(text)
        if path == 'scripts/check-trust.mjs': policy = text
        if path.endswith('.lean') and (path.startswith(('Solidity/', 'Bridge/')) or path in ROOTS or path == 'SolkeyTestSuite.lean'):
            clean = blank_lean(text)
            metrics = {
                'lines': lines(text), 'category': c,
                'pin_command_lines': sum(bool(PIN.match(x)) for x in clean.splitlines()),
                'pin_expected_output_lines': sum(bool(re.search(r'depends on axioms:|does not depend on any axioms', x)) for x in text.splitlines()),
                'implemented_by': len(re.findall(r'\bimplemented_by\b', clean)),
                'native_decide': len(re.findall(r'\bnative_decide\b|\bdecide\s*\+\s*native\b', clean)),
                'sorry_admit_tokens': len(re.findall(r'(?<![\w.])(?:sorry|sorryAx|admit)\b', clean)),
                'recovery_dot_admit_tokens': len(re.findall(r'\.admit\b', clean)),
                'axiom_declarations': len(re.findall(r'^\s*(?:private\s+)?axiom\s', clean, re.M)),
                'chain_agreement_generator_commands': len(re.findall(r'(?m)^\s*#(?:chain(?:_rest)?|agreement)\b', clean)),
                'theorem_lemma_declarations': len(re.findall(r'^\s*(?:(?:private|protected|noncomputable)\s+)*(?:theorem|lemma)\s', clean, re.M)),
            }
            metrics['axiom_pin_lines_lower_bound'] = metrics['pin_command_lines'] + metrics['pin_expected_output_lines']
            details[path] = metrics
            target = trust_bridge if path.startswith('Bridge/') else trust
            for k, v in metrics.items():
                if isinstance(v, int): target[k] += v
            target['lean_files'] += 1
            block = None
            for line in clean.splitlines():
                command = re.match(r'^\s*(?:(?:private|protected|noncomputable|unsafe)\s+)*(theorem|lemma|example|def|abbrev|instance|opaque|structure|inductive|namespace|end|open|section|variable|attribute|macro|syntax|elab|initialize|set_option|#\w+)\b', line)
                if command: block = 'proof' if command[1] in ('theorem','lemma','example') else 'definition' if command[1] in ('def','abbrev','instance','opaque','structure','inductive') else None
                if block and line.strip(): target[block+'_block_nonblank_code_lines_heuristic'] += 1
            # Explicit generated regions in otherwise handwritten files.
            active = False
            for line in text.splitlines():
                if re.search(r'BEGIN generated by', line): active = True
                if active:
                    target['embedded_generated_region_lines'] += 1
                    if c == 'solidity_header_unmarked_proofs_and_definitions':
                        counts[c] -= 1; counts['generated_embedded_regions'] += 1
                if re.search(r'END generated by', line): active = False
    # Absence of an inventory/policy is unknown, never silently zero.
    if policy and inventory is not None and 'native_decide' in policy and "['forbidden'" in policy:
        native_allow = sum(1 for row in inventory if row.get('kind') == 'forbidden' and 'native_decide' in row.get('code', ''))
        trust['native_decide_allowlist_entries'] = native_allow
        allow_status = 'measured explicit forbidden policy plus trust inventory; no native exception in audit()'
    else:
        trust['native_decide_allowlist_entries'] = None
        allow_status = 'unknown: no current-style explicit trust policy/inventory at snapshot'
    proof = counts['solidity_header_unmarked_proofs_and_definitions']
    infrastructure = sum(counts[k] for k in INFRA)
    return {'revision': rev, 'line_categories': dict(sorted(counts.items())), 'trust_source_metrics': dict(trust), 'bridge_trust_source_metrics': dict(trust_bridge),
            'native_allowlist_status': allow_status, 'overhead': {'infrastructure_lines': infrastructure,
            'header_unmarked_solidity_source_lines': proof, 'ratio': infrastructure/proof if proof else None,
            'proof_block_heuristic_ratio': infrastructure/trust['proof_block_nonblank_code_lines_heuristic'] if trust['proof_block_nonblank_code_lines_heuristic'] else None,
            'denominator': 'header-unmarked Solidity Lean sources: definitions, proofs, comments, tactics and controls; NOT proof-only lines'}}, gen, details


def history(gen, first_parent=False):
    # --root includes the initial creation; no merge double counting in default mode.
    mode = ['--first-parent', '--diff-merges=first-parent'] if first_parent else ['--no-merges']
    raw = git('log', BASE, '--root', '--no-renames', '--numstat', '--format=@@%H\t%ct\t%s', *mode).decode('utf-8', 'replace')
    monthly = {}; touches = C.Counter(); creates = C.Counter(); deletes = C.Counter(); last = {}; reverts = []
    import datetime
    for row in raw.splitlines():
        if row.startswith('@@'):
            sha, stamp, subject = row[2:].split('\t', 2)
            month = datetime.datetime.fromtimestamp(int(stamp), datetime.timezone.utc).strftime('%Y-%m')
            d = monthly.setdefault(month, {'commits': 0, 'revert_subjects': 0, 'categories': {}})
            d['commits'] += 1
            if re.match(r'(?i)^revert\b', subject):
                d['revert_subjects'] += 1; reverts.append({'sha': sha, 'subject': subject, 'month': month})
        elif '\t' in row:
            a, b, path = row.split('\t', 2)
            c = category(path, gen)
            v = d['categories'].setdefault(c, {'added': 0, 'deleted': 0, 'file_changes': 0, 'binary_changes': 0})
            v['file_changes'] += 1
            if a == '-': v['binary_changes'] += 1; continue
            a, b = int(a), int(b); v['added'] += a; v['deleted'] += b
            touches[path] += 1
            if path not in last: last[path] = sha
    # Exact presence changes, rather than infer creation from a zero deletion count.
    statuses = git('log', BASE, '--root', '--no-renames', '--name-status', '--format=', *mode).decode().splitlines()
    for row in statuses:
        if '\t' in row:
            state, path = row.split('\t', 1)
            if state == 'A': creates[path] += 1
            if state == 'D': deletes[path] += 1
    edits = {p: max(0, n-creates[p]-deletes[p]) for p, n in touches.items()}
    return {'monthly': dict(sorted(monthly.items())), 'revert_subjects': reverts,
            'files_edited_more_than_5_times': sum(n > 5 for n in edits.values()),
            'files_created_and_deleted': sum(bool(creates[p] and deletes[p]) for p in set(creates)|set(deletes)),
            'path_lifecycle_note': 'reachable DAG, path-based; moves and branch deletion/recreation count, not necessarily abandoned work'}, edits, touches, last, creates, deletes


def reference(repo):
    counts = C.Counter(); generated_lines = 0
    for path, text in sources(REF, repo):
        n = lines(text)
        if path.endswith('.v'):
            counts['coq_source_lines'] += n
            if path.startswith(('flocq/', 'MenhirLib/')): counts['vendored_coq_lines'] += n
            if GEN.search(text[:2500]): generated_lines += n
        if path.startswith(('scripts/', 'tools/', '.github/', 'doc/')) or path.endswith('.md') or path.split('/')[-1].startswith('Makefile') or path == 'configure':
            counts['infrastructure_lines'] += n
        if path.endswith(('.ml', '.mli', '.mll', '.mly', '.c', '.h', '.S')): counts['other_implementation_lines'] += n
    counts['header_marked_generated_coq_lines'] = generated_lines
    return {'repository': 'https://github.com/AbsInt/CompCert', 'revision': REF,
            'citation': 'https://github.com/AbsInt/CompCert/tree/'+REF,
            'status': 'measured', 'counts': dict(counts),
            'ratio': counts['infrastructure_lines']/counts['coq_source_lines'],
            'ratio_excluding_vendored_coq': counts['infrastructure_lines']/(counts['coq_source_lines']-counts['vendored_coq_lines']),
            'ratio_including_noncoq_implementation': counts['infrastructure_lines']/(counts['coq_source_lines']+counts['other_implementation_lines']),
            'boundary': 'tools/doc/Markdown/Makefiles/configure over all .v; Coq sources include definitions and proofs; non-Coq compiler implementation shown separately; .github CI counted at this revision; not a labor ratio'}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', type=pathlib.Path, required=True)
    ap.add_argument('--compcert', type=pathlib.Path)
    args = ap.parse_args()
    if git('rev-parse', '--is-shallow-repository').strip() != b'false': raise SystemExit('full local history required')
    git('cat-file', '-e', BASE+'^{commit}')
    args.out.mkdir(parents=True, exist_ok=True)
    fp = git('log', BASE, '--first-parent', '--format=%H\t%ct').decode().splitlines()
    latest = {}
    for row in fp:
        sha, stamp = row.split('\t')
        import datetime
        month = datetime.datetime.fromtimestamp(int(stamp), datetime.timezone.utc).strftime('%Y-%m')
        latest.setdefault(month, sha)
    snapshots = {}; gen = {}; details = {}
    for month, sha in sorted(latest.items()):
        snap, g, dd = snapshot(sha)
        snapshots[month] = snap; gen.update(g)
        if sha == BASE: details = dd
    hist, edits, touches, last, creates, deletes = history(gen)
    fp_hist, *_ = history(gen, True)
    current = snapshots[max(snapshots)]
    if current['revision'] != BASE: raise SystemExit('base snapshot missing')
    top = []
    for path, n in sorted(edits.items(), key=lambda x: (-x[1], x[0]))[:30]:
        metric = details.get(path)
        closure = ('not_applicable: registry/docs/checker or syntax module has no theorem goal'
                   if not metric or not metric['theorem_lemma_declarations'] else
                   'source_complete_kernel_unverified: theorem declarations present, no sorry/admit/axiom tokens'
                   if not metric['sorry_admit_tokens'] and not metric['axiom_declarations'] else
                   'unverified: inspect source markers')
        subject = git('show', '-s', '--format=%s', last[path]).decode().strip()
        top.append({'path': path, 'edit_count': n, 'touch_count': touches[path], 'creations': creates[path], 'deletions': deletes[path],
                    'category': category(path, gen), 'last_nonmerge_change': last[path], 'base_metrics': metric,
                    'closed_goal': closure, 'kernel_closure_confirmed': None, 'last_change_subject': subject,
                    'closure_evidence': {'base_path': BASE+':'+path, 'source_metrics': metric, 'historical_timing_matches': []},
                    'interpretation': 'no verdict from churn alone; deletion, formatting and productive fixes all count'})
    files = git('ls-tree', '-r', '--name-only', BASE).decode().splitlines()
    wanted = ['docs/audits/architecture-tools/', 'docs/audits/proof-coverage-tools/', 'docs/audits/build-speed-tools/',
              'docs/audits/build-speed.md', 'scripts/build-measure', 'scripts/differential/', 'scripts/bench/', 'docs/audits/direction-tools/references/']
    inventory = {p: [x for x in files if x.startswith(p)] for p in wanted}
    timing_path = 'docs/audits/architecture-tools/timing-sample.tsv'
    timing = git('show', BASE+':'+timing_path).decode()
    timing_rows = [x.split('\t') for x in timing.splitlines() if x]
    timing_summary = {'path': timing_path, 'sha256': hashlib.sha256(timing.encode()).hexdigest(),
                      'rows': len(timing_rows), 'passing_rows': sum(x[-1]=='PASS' for x in timing_rows),
                      'interpretation': 'reuse only; source audit timing sample is not a whole-project or matched-reference check time'}
    for row in top:
        row['closure_evidence']['historical_timing_matches'] = [x for x in timing_rows if row['path'] in x]
    ref = reference(args.compcert) if args.compcert else None
    waits = [
        {'item': 'da-references', 'status': 'absent on pinned base; own shallow CompCert measurement used when supplied'},
        {'item': 'va3/vu1', 'status': 'scripts/differential/** and scripts/bench/** absent on pinned base; no output invented'},
        {'item': 'CI logs', 'status': 'gh run list --repo SolidiKeY/solidity-lean --commit '+BASE+' --limit 10 --json databaseId,conclusion,workflowName,headSha,status: Forbidden from api.github.com; no access request per assignment'},
        {'item': 'closed goal evidence', 'status': 'Each hotspot classified N/A or source-complete/kernel-unverified with last-change and timing evidence; no current per-file kernel receipts available in census'}]
    findings = []
    months = list(snapshots)
    first, final = snapshots[months[0]], current
    findings.append({'signal': 'infrastructure/source stock ratio', 'first_month': months[0], 'first': first['overhead'],
                     'last_month': months[-1], 'last': final['overhead'],
                     'verdict': None, 'reason': 'stock is not time spent; see reference calibration and generated exclusions'})
    if ref:
        ratio = final['overhead']['ratio']/ref['ratio']
        findings.append({'signal': 'CompCert infrastructure/source calibration', 'ratio_of_ratios': ratio,
                         'outlier': ratio > 3 or ratio < 1/3,
                         'verdict': None, 'assessment': 'inconclusive: unmatched inventory boundaries; no justified/redundant/wrong-direction claim',
                         'ratio_of_ratios_excluding_reference_vendor': final['overhead']['ratio']/ref['ratio_excluding_vendored_coq'],
                         'reason': 'Outlier requires product-level investigation; this ratio does not justify the overhead. Approximate source-stock comparison only: Lean has extensive checked fixtures, Coq compiler also has non-Coq implementation; no labor or proof-efficiency inference.'})
    for month, row in hist['monthly'].items():
        cats = row['categories']
        infra = sum(cats.get(k, {}).get('added', 0)+cats.get(k, {}).get('deleted', 0) for k in INFRA)
        product = cats.get('solidity_header_unmarked_proofs_and_definitions', {})
        lean_churn = product.get('added', 0)+product.get('deleted', 0)
        findings.append({'signal': 'monthly infrastructure/header-unmarked Solidity churn', 'month': month,
                         'infrastructure_added_plus_deleted': infra, 'solidity_added_plus_deleted': lean_churn,
                         'ratio': infra/lean_churn if lean_churn else None,
                         'verdict': None, 'reason': 'No matched historical reference churn denominator; cannot infer wasted work from deletions.'})
    findings.append({'signal': 'top30 churn composition',
                     'files_by_category': dict(C.Counter(x['category'] for x in top)),
                     'edits_by_category': dict(C.Counter({k:sum(x['edit_count'] for x in top if x['category']==k) for k in {x['category'] for x in top}})),
                     'kernel_closure_confirmed': sum(x['kernel_closure_confirmed'] is True for x in top),
                     'source_complete_kernel_unverified_files': [x['path'] for x in top if x['closed_goal'].startswith('source_complete')],
                     'verdict': None, 'reason': 'Generated registries and documentation dominate the hottest paths; frequent integration regeneration is not repeated proof failure.'})
    findings.append({'signal': 'repeated edits and disappearing paths', 'files_edited_more_than_5_times': hist['files_edited_more_than_5_times'],
                     'files_created_and_deleted': hist['files_created_and_deleted'], 'revert_subject_count': len(hist['revert_subjects']),
                     'verdict': None, 'reason': 'Potential review targets; generated registry regeneration and file moves are not closed-goal failures.'})
    findings.append({'signal': 'trust/pin growth', 'monthly': {m:{'solidity_and_roots':s['trust_source_metrics'], 'bridge':s['bridge_trust_source_metrics']} for m,s in snapshots.items()},
                     'verdict': None, 'reason': 'Pins measure checking machinery, implemented_by measures executable override sites; neither count alone proves a larger logical axiom set.'})
    summary = {'schema': 'direction-process-v1', 'base': BASE,
       'reproduce': 'python3 docs/audits/direction-tools/process/history.py --out /tmp/process-results --compcert /tmp/process-compcert',
       'methods': {'history': history.__doc__ or __doc__, 'generated': 'Named roots, Corpus/, AxiomPins files, and explicit generated headers in first 2500 chars; explicit BEGIN/END regions subtracted from header-unmarked source stock and emitted separately. Historical churn uses file categories and does not separate mixed-file regions. Union of monthly snapshots classifies history; unknown deleted generated files may remain handwritten.',
                   'proof_lines': 'Heuristic nonblank code lines in theorem/lemma/example command blocks versus definition blocks; statements/bodies inseparable here; macro quotations/local defs may confuse boundaries. Primary ratio uses physical file source, not this heuristic. Never compared as proof efficiency.',
                   'trust': 'Solidity+roots and Bridge shown separately. Comment/string-stripped lexical tokens, not elaborated declarations; pins include command and expected-output line counts separately plus their sum as a lower bound (continuation guard lines not counted). .admit recovery APIs separated from unfinished-proof tokens. Native allowlist unknown before explicit current-style policy, not assumed zero.',
                   'closure': 'Each top30 investigated using declaration counts, source escapes, last change and committed timing sample. Non-goal files N/A; theorem files source-complete/kernel-unverified. Absence of sorry is not closure.',
                   'months': 'Final first-parent revision per committer month; November partial through pinned base; history month uses UTC committer timestamp, snapshot month also uses UTC committer timestamp.'},
       'inventory': inventory, 'timing_reuse': timing_summary, 'reference': ref, 'trends': findings, 'waits': waits,
       'conclusion': 'The measured reference outlier calls for investigation, not automatic justification. Source volume alone cannot establish wasted effort. Top30 is dominated by generated registries and documentation; the single theorem-bearing hotspot has source-complete but kernel-unverified goals.',
       'limits': ['No Lean builds, no proof timings measured, no proof closure claimed.', 'Physical source lines include comments/blanks; Solidity denominator is not all product code (Bridge/ and other Lean reported separately).',
                  'Generator implementation is infrastructure; output is separate. Chain/agreement elaborator command sites are counted, not their in-memory generated declarations. Headers cannot identify all generated or hand-expanded chain/agreement code.', 'Git path churn is not person-hours; merges excluded by default, first-parent sensitivity supplied.',
                  'CompCert is one approximate source reference, not a matched theorem or labor reference. No numeric claim copied from prose.']}
    outputs = {'history.json': hist, 'first-parent.json': fp_hist, 'snapshots.json': snapshots,
               'hotspots.json': top, 'summary.json': summary, 'generated-paths.json': dict(sorted(gen.items()))}
    for name, obj in outputs.items():
        data = json.dumps(obj, indent=2, sort_keys=True)+'\n'
        if len(data.encode()) >= 1_000_000: raise SystemExit('result too large: '+name)
        (args.out/name).write_text(data)
    print(json.dumps({'base': BASE, 'months': months, 'commits': sum(x['commits'] for x in hist['monthly'].values()),
                      'overhead': current['overhead'], 'hotspots': len(top), 'reference': ref}, indent=2))

if __name__ == '__main__': main()
