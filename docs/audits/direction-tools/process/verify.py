#!/usr/bin/env python3
"""Independent accounting checks and regression probes for the process census.
Run: python3 docs/audits/direction-tools/process/verify.py [RESULT_DIRECTORY]
Uses only stdlib and Git. Writes nothing; does not invoke Lean.
"""
import collections
import importlib.util
import json
import pathlib
import re
import subprocess
import sys
sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('process_history', HERE/'history.py')
h = importlib.util.module_from_spec(spec); spec.loader.exec_module(h)
result = pathlib.Path(sys.argv[1]) if len(sys.argv)>1 else HERE
load = lambda p: json.loads((result/p).read_text())
history = load('history.json'); snapshots = load('snapshots.json'); top = load('hotspots.json'); summary = load('summary.json')
assert summary['base'] == h.BASE
assert len(top) == 30
assert not h.generated('scripts/generator.py', 'DATA = """\n-- Generated by generator.py\n"""')
assert not h.generated('SolkeyTestSuite.lean', '-- handwritten library root')
assert h.generated('SoliditySlowExamples.lean') == 'generated_roots'
assert h.generated('docs/module-map.md', '<!-- Generated from fragments -->') == 'generated_docs'
assert h.generated('docs/inventory.md', 'Generated by a committed generator') == 'generated_docs'
assert not h.generated('scripts/pins/AxiomPins.json', '{}')
assert h.generated('Solidity/X/AxiomPins.lean') == 'axiom_pins_files'
assert h.generated('Solidity/Corpus/X.lean') == 'generated_corpus'
assert h.PIN.match('#guard_msgs (whitespace := lax) in #print axioms x')
clean = h.blank_lean('/- native_decide /- sorry -/ axiom -/\n-- implemented_by\nr###"native_decide"###\n"sorry"\n@[implemented_by fast] def f := 0\ng.admit\n')
assert not re.search(r'\b(?:native_decide|sorry|axiom)\b', clean)
assert len(re.findall(r'\bimplemented_by\b', clean)) == 1
assert not re.search(r'(?<![\w.])(?:sorry|sorryAx|admit)\b', clean)
# Aggregate --shortstat is independent of the --numstat/category parser.
for filename, mode in [('history.json', ['--no-merges']), ('first-parent.json', ['--first-parent','--diff-merges=first-parent'])]:
    data = load(filename)
    stat = subprocess.check_output(['git','log',h.BASE,'--root','--no-renames','--format=','--shortstat',*mode], text=True)
    added = sum(map(int, re.findall(r'(\d+) insertions?\(\+\)', stat)))
    deleted = sum(map(int, re.findall(r'(\d+) deletions?\(-\)', stat)))
    cats = [c for month in data['monthly'].values() for c in month['categories'].values()]
    assert sum(c['added'] for c in cats) == added, filename
    assert sum(c['deleted'] for c in cats) == deleted, filename
    count = int(subprocess.check_output(['git','rev-list',h.BASE,'--count',*(['--first-parent'] if 'first-parent' in filename else ['--no-merges'])]))
    assert sum(m['commits'] for m in data['monthly'].values()) == count
    print(filename, 'accounting PASS', added, 'added', deleted, 'deleted', count, 'commits')
for row in top:
    status = subprocess.check_output(['git','log',h.BASE,'--no-merges','--full-history','--root','--no-renames','--format=','--name-status','--',row['path']],text=True)
    assert sum(x.startswith('M\t') for x in status.splitlines()) == row['edit_count'], row['path']
    if row['closed_goal'].startswith('source_complete'):
        assert row['base_metrics']['theorem_lemma_declarations'] > 0
        assert row['kernel_closure_confirmed'] is None
    if row['closed_goal'].startswith('closed_by_reused'):
        assert row['kernel_closure_confirmed'] is True
        receipt=row['closure_evidence']['archived_validation']
        assert receipt['local_import_source_blobs_identical'] and receipt['toolchain_blob_identical']
        assert receipt['audited_revision']==h.BASE
for month, snap in snapshots.items():
    counts = snap['line_categories']; overhead = snap['overhead']
    assert overhead['infrastructure_lines'] == sum(counts.get(k,0) for k in h.INFRA)
    assert overhead['header_unmarked_solidity_source_lines'] == counts['solidity_header_unmarked_proofs_and_definitions']
    assert abs(overhead['ratio']-overhead['infrastructure_lines']/overhead['header_unmarked_solidity_source_lines']) < 1e-12
for path in result.glob('*.json'):
    assert path.stat().st_size < 1_000_000, path
    json.loads(path.read_text())
print('classification, lexer, pin options, top30 independent modifications, monthly ratios, JSON size/schema basics: PASS')
