#!/usr/bin/env python3
"""Lexical census, not kernel declarations. Usage: measure.py EXTERNAL-CACHE.
Counts physical lines including comments; declaration/proof markers are lexical
proxies. Generated provenance is detected conservatively by path/header; unknown
material stays unclassified rather than asserted handwritten. No builds.
"""
import csv,json,pathlib,re,subprocess,sys
HERE=pathlib.Path(__file__).resolve().parent
ROOT=HERE.parents[3]
BASE='d4ad633a9624263a59b14fd2c520b9bc602f88f3'
EXT={'.lean','.v','.sml','.thy','.k','.md','.cpp','.h','.hs','.ml','.x','.y','.java','.g4','.key','.ML','.c','.cxx','.hpp'}
DECL=re.compile(r'^\s*(?:(?:private|protected|noncomputable|unsafe|partial)\s+)*(def|abbrev|inductive|structure|class|instance|theorem|lemma|Definition|Fixpoint|Inductive|Record|Theorem|Lemma|Corollary|Datatype|Definition|Theorem|definition|fun|function|datatype|record|lemma|theorem|rule|syntax)\b',re.M)
THM=re.compile(r'^\s*(?:(?:private|protected)\s+)*(?:theorem|lemma|Theorem|Lemma|Corollary)\b',re.M)
BASE_FILES={}
BASE_TEXT={}
def base_snapshot():
 global BASE_FILES,BASE_TEXT
 if BASE_FILES: return
 rows=subprocess.check_output(['git','-C',str(ROOT),'ls-tree','-r',BASE],text=True).splitlines()
 for row in rows:
  metadata,name=row.split('\t',1)
  kind,typ,sha=metadata.split()
  if typ=='blob': BASE_FILES[name]=sha
 selected={name:sha for name,sha in BASE_FILES.items() if name.endswith('.lean')}
 objects=list(dict.fromkeys(selected.values()))
 raw=subprocess.run(['git','-C',str(ROOT),'cat-file','--batch'],input=('\n'.join(objects)+'\n').encode(),stdout=subprocess.PIPE,check=True).stdout
 pos=0; texts={}
 for sha in objects:
  end=raw.index(b'\n',pos); header=raw[pos:end].split(); size=int(header[-1]); pos=end+1
  texts[sha]=raw[pos:pos+size].decode(errors='replace'); pos+=size+1
 BASE_TEXT={name:texts[sha] for name,sha in selected.items()}
def source_text(root,name):
 if root==ROOT:
  base_snapshot()
  if name in BASE_TEXT: return BASE_TEXT[name]
  return subprocess.check_output(['git','-C',str(ROOT),'show',BASE+':'+name],text=True)
 return (root/name).read_text(errors='replace')
def tracked(root):
 if root==ROOT:
  base_snapshot(); return list(BASE_FILES)
 return subprocess.check_output(['git','-C',str(root),'ls-files'],text=True).splitlines()
def count(root,paths):
 result=dict(unsupported_native_files=0,proof_region_lines_estimate=0,definition_region_lines_estimate=0,other_lines_estimate=0,handwritten_candidate_lines=0,files=0,lines=0,declarations=0,theorems=0,generated_lines=0,unclassified_lines=0,proof_marker_lines=0)
 for name in paths:
  f=root/name
  if f.suffix not in EXT or (root!=ROOT and not f.is_file()): continue
  text=source_text(root,name)
  if f.suffix=='.md':
   # K uses literate Markdown. Count fenced K only; exclude English and examples in other languages.
   text='\n'.join(re.findall(r'^```k[^\n]*\n(.*?)^```',text,re.M|re.S))
   if not text: continue
  n=len(text.splitlines())
  generated=bool(re.search(r'(?:^|/)(?:Corpus|Generated)(?:/|$)|AxiomPins|(?:^|/)(?:Solidity|SolidityExamples|SolidityBridge)\.lean$|_gen\.|generated',name,re.I) or re.search(r'auto.?generated|generated by|do not edit',text[:1500],re.I))
  if name.endswith('_user.lean'): generated=False # Clear user obligations are manually supplied
  # Region estimates follow language declaration/proof delimiters; they include
  # comments/blank lines within regions and are not AST or kernel measurements.
  region='other'; regions={'proof':0,'definition':0,'other':0}
  for line in text.splitlines():
   if THM.match(line) or re.match(r'\s*(?:Proof|proof)\b',line): region='proof'
   elif DECL.match(line) or (f.suffix in {'.cpp','.h','.java','.g4','.key','.k','.md'} and line.strip()): region='definition'
   regions[region]+=1
   if re.match(r'\s*(?:Qed|Defined|qed|QED|End)\b',line): region='other'
  for key in regions: result[key+'_region_lines_estimate' if key!='other' else 'other_lines_estimate']+=regions[key]
  if not generated: result['handwritten_candidate_lines']+=n
  if f.suffix in {'.cpp','.h','.java','.g4','.key','.c','.cxx','.hpp','.x','.y','.hs','.ml','.ML'}: result['unsupported_native_files']+=1
  result['files']+=1; result['lines']+=n; result['declarations']+=len(DECL.findall(text)); result['theorems']+=len(THM.findall(text))
  result['generated_lines' if generated else 'unclassified_lines']+=n
  result['proof_marker_lines']+=sum(bool(re.search(r'\b(?:by|Proof|Qed|proof|qed|prove|store_thm)\b',line)) for line in text.splitlines())
 result['declarations_status']='lexical markers only; not native declarations' if result['unsupported_native_files'] else 'lexical declaration headers, not kernel declarations'
 result['native_declarations']=None if result['unsupported_native_files'] else result['declarations']
 return result
if __name__=='__main__':
 cache=pathlib.Path(sys.argv[1]); inventory=[]
 pins=json.loads((HERE/'pins.json').read_text())
 def git(root,*args): return subprocess.check_output(['git','-C',str(root),*args],text=True).strip()
 subprocess.run(['git','-C',str(ROOT),'merge-base','--is-ancestor',BASE,'HEAD'],check=True)
 # Read immutable base blobs, so subsequent coordinator merges cannot relabel source.
 base_snapshot()
 for name,pin in pins.items():
  assert git(cache/name,'rev-parse','HEAD')==pin, name+' pin mismatch'
  assert not git(cache/name,'status','--porcelain'), name+' dirty reference'
 inputs={}
 for path in ['docs/audits/architecture-tools','docs/audits/proof-coverage-tools','docs/audits/build-speed-tools','docs/audits/build-speed.md','scripts/build-measure.py','scripts/build-measure-report.py','scripts/differential','scripts/bench']:
  matches=sorted(x for x in BASE_FILES if x==path or x.startswith(path+'/'))
  inputs[path]=dict(present=bool(matches),files=matches)
 (HERE/'reused-inputs.json').write_text(json.dumps(dict(base=BASE,inputs=inputs,policy='reuse historical timing sample; no project build or Lean elaboration'),indent=2)+'\n')
 timings={} 
 timing_source=ROOT/'docs/audits/architecture-tools/timing-sample.tsv'
 for line in source_text(ROOT,str(timing_source.relative_to(ROOT))).splitlines():
  cols=line.replace('\\t','\t').split('\t')
  if len(cols)==5 and cols[-1]=='PASS': timings[cols[1]]=float(cols[2])
 (HERE/'timing-input.json').write_text(json.dumps(dict(source=str(timing_source.relative_to(ROOT)),source_base=BASE,meaning='historical single-file wall seconds; not matched reference hardware or clean builds',samples=timings),indent=2)+'\n')
 published=[]
 for project,repo in json.loads((HERE/'sources.json').read_text()).items():
  root=cache/project
  if not (root/'.git').exists(): inventory.append(dict(project=project,status='unavailable')); continue
  readme=root/'README.md'
  if not readme.exists(): readme=root/'README'
  excerpts=[]
  if readme.exists():
   for i,line in enumerate(readme.read_text(errors='replace').splitlines(),1):
    if re.search(r'build time|check time|minutes|hours|seconds',line,re.I): excerpts.append(dict(line=i,text=line))
  published.append(dict(project=project,url='https://github.com/'+repo+'/blob/'+pins[project]+'/'+readme.name,searched=readme.name,excerpts=excerpts,check_seconds=None,note='qualitative test duration is not proof check time; no comparable numeric check time established'))
  inventory.append(dict(project=project,commit=subprocess.check_output(['git','-C',str(root),'rev-parse','HEAD'],text=True).strip(),source_url='https://github.com/'+repo+'/tree/'+pins[project],metrics=count(root,[x for x in tracked(root) if project!='Isabelle-Solidity' or x.startswith('thys/Isabelle-Solidity/')]),check_seconds=None,timing_status='not measured; published timing not yet located'))
 (HERE/'published-times.json').write_text(json.dumps(published,indent=2)+'\n')
 solkey=cache/'SolKey'
 inventory.append(dict(project='SolKey-Solidity-component',commit=pins['SolKey'],metrics=count(solkey,[x for x in tracked(solkey) if x.startswith('keyext.solidity.core/')]),scope='Solidity extension only; parent SolKey inventory includes shared KeY platform'))
 inventory.append(dict(project='this',commit=BASE,metrics=count(ROOT,[x for x in tracked(ROOT) if x.endswith('.lean') and not x.startswith('Bridge/vendor/')])))
 (HERE/'inventory.json').write_text(json.dumps(inventory,indent=2)+'\n')
 rows=[]
 for pair in json.loads((HERE/'pair-specs.json').read_text()):
  for path in pair['this_paths']: assert path in BASE_FILES,path
  for path in pair['reference_paths']: assert (cache/pair['reference']/path).is_file(),path
  a=count(ROOT,pair['this_paths']); b=count(cache/pair['reference'],pair['reference_paths']); ratio=a['lines']/b['lines'] if b['lines'] else None
  rows.append(dict(**pair,this_lines=a['lines'],this_decls=a['native_declarations'],this_generated=a['generated_lines'],this_check_s=(timings.get(pair['this_paths'][0]) if len(pair['this_paths'])==1 else None),this_metrics=a,reference_metrics=b,reference_lines=b['lines'],reference_decls=b['native_declarations'],reference_generated=b['generated_lines'],reference_check_s=None,ratio=ratio))
 with (HERE/'pairs.csv').open('w') as f:
  w=csv.DictWriter(f,fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
 out=[dict(**r,verdict='unclear',reason=r['outlier_reason']) for r in rows if r['ratio'] is not None and (r['ratio']>3 or r['ratio']<1/3)]
 (HERE/'summary.json').write_text(json.dumps(dict(status='partial',method='physical source lines, lexical declaration markers and proof/definition region estimates, not kernel declarations; generated detected by path/header, remaining handwritten candidates retain uncertainty',outliers=out,waits=['Numeric reference check times not established; published-times.json records bounded source search','Native declaration metrics and exact proof/definition separation remain unsupported for mixed implementation languages; lexical estimates only'],missing_counterparts=json.loads((HERE/'boundaries.json').read_text())['missing_counterparts'],rejected_pairs=json.loads((HERE/'boundaries.json').read_text())['rejected_pairs']),indent=2)+'\n')
