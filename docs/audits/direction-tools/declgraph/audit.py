#!/usr/bin/env python3
"""Pinned source inventory and fail-closed elaborated-cache census (stdlib only).
Run from repository root: python3 -I docs/audits/direction-tools/declgraph/audit.py inventory
Results are source facts, not declaration liveness. Cache files are untrusted until
Export.lean hashes every source and Lake verifies matching dependency inputs.
"""
import argparse, collections, hashlib, json, pathlib, re, subprocess, tarfile
BASE="d6fd95f0886775d7c286813fa9b993a40ba7a777"
HERE=pathlib.Path(__file__).resolve().parent
ROOT=HERE.parents[3]
FAMILIES=["Solidity/Yul/Views/","Solidity/Backend/InternalFlow/","Solidity/SolcValidation/","Solidity/Frontend/SolcJson/"]
CANDIDATES=dict(zip(FAMILIES,[10146,6100,4878,4440]))
def git(*a): return subprocess.check_output(["git",*a],cwd=ROOT,text=True).strip()
def sources():
    proc=subprocess.Popen(["git","archive",BASE,"--","*.lean"],cwd=ROOT,stdout=subprocess.PIPE)
    out={}
    with tarfile.open(fileobj=proc.stdout,mode="r|") as archive:
        for f in archive:
            if f.isfile(): out[f.name]=archive.extractfile(f).read().decode()
    assert proc.wait()==0
    return out
def assert_sources():
    pinned=sources(); scope="docs/audits/direction-tools/declgraph/"
    actual=set(git("ls-files","--cached","--others","--exclude-standard","--","*.lean").splitlines())
    assert {p for p in actual if not p.startswith(scope)}=={p for p in pinned if not p.startswith(scope)}, "Lean source path set differs from pinned BASE"
    assert all((ROOT/p).read_bytes()==t.encode() for p,t in pinned.items()), "Lean source bytes differ from pinned BASE"
    return pinned
def provenance(p,t):
    if p in ("Solidity.lean","SolidityExamples.lean","SoliditySlowExamples.lean","Bridge/SolidityBridge.lean"): return "generated_root"
    if "AxiomPins" in p: return "axiom_pins"
    if p in ("Solidity/Corpus/Basic.lean","Solidity/Corpus/Imported.lean"): return "explicit_handwritten_corpus_exception"
    if "/Corpus/" in p or p=="SolidityCorpus.lean": return "generated_corpus"
    if re.search(r"generated by|auto[- ]generated|do not edit|automatically generated",t,re.I): return "marked_generated"
    if re.search("chain|agreement",p,re.I): return "unresolved_chain_agreement"
    return "untraced"
def inventory():
    src=sources(); totals=collections.defaultdict(collections.Counter)
    families={}
    for p,t in src.items():
        c=provenance(p,t)
        totals[c]["files"]+=1; totals[c]["physical_lines"]+=len(t.splitlines())
    for pre in FAMILIES:
        ps=[p for p in src if p.startswith(pre)]
        groups=collections.defaultdict(collections.Counter)
        for p in ps:
            groups[provenance(p,src[p])]["files"]+=1
            groups[provenance(p,src[p])]["physical_lines"]+=len(src[p].splitlines())
        families[pre]=dict(files=len(ps),physical_lines=sum(len(src[p].splitlines()) for p in ps),
            previous_candidate_span_lines=CANDIDATES[pre],provenance=dict(sorted(groups.items())))
    reused=["docs/audits/direction.md","docs/audits/architecture-tools/unreferenced.py",
        "docs/audits/architecture-tools/imports.py","docs/audits/proof-coverage-tools/theorem_census.py",
        "docs/audits/build-speed.md","docs/audits/build-speed-tools/import_graph.py",
        "docs/audits/direction-tools/reachability/reach.py","docs/audits/direction-tools/statements/provenance.py"]
    return dict(base=BASE,tracked_lean_files=len(src),physical_lines=sum(len(t.splitlines()) for t in src.values()),
        provenance=dict(sorted(totals.items())),families=families,
        reused=[dict(path=p,sha256=hashlib.sha256(subprocess.check_output(["git","show",BASE+":"+p],cwd=ROOT)).hexdigest()) for p in reused],
        unavailable_at_base=[p for p in ["scripts/differential/","scripts/bench/"] if not git("ls-tree","-r","--name-only",BASE,"--",p)],
        boundaries=["Physical lines include blanks and comments; candidate spans are older lexical results, not current deletion totals.",
        "Generated roots, Corpus and AxiomPins are separated. Marker classification is not historical authorship proof.",
        "Chain/agreement filenames without producer evidence remain unresolved, never presumed handwritten.",
        "Prior architecture/reachability counters are lexical/import inventories and cannot settle declaration liveness."])
def cache_census():
    src=sources(); cache=ROOT/".lake/build/lib/lean"
    rows=[]
    for p in src:
        stem=cache/pathlib.Path(p).with_suffix("")
        rows.append(dict(path=p,ilean=stem.with_suffix(".ilean").is_file(),olean=stem.with_suffix(".olean").is_file(),trace=stem.with_suffix(".trace").is_file()))
    return dict(base=BASE,tracked_files=len(rows),present={k:sum(r[k] for r in rows) for k in ("ilean","olean","trace")},families={pre:{k:sum(r[k] for r in rows if r["path"].startswith(pre)) for k in ("ilean","olean","trace")} for pre in FAMILIES},boundary="Presence is not source/dependency validity; no zero-use or deletion verdict follows.")
def main():
    a=argparse.ArgumentParser();a.add_argument("mode",choices=["inventory","cache"]);a.add_argument("--check",action="store_true");a.add_argument("--out",type=pathlib.Path);v=a.parse_args()
    result=inventory() if v.mode=="inventory" else cache_census()
    out=v.out or HERE/("inventory.json" if v.mode=="inventory" else "cache.json")
    body=json.dumps(result,indent=2,sort_keys=True)+"\n"
    if v.check: assert out.read_text()==body,"STALE "+str(out)
    else: out.write_text(body)
    print(v.mode.upper()+"_PASS",out)
if __name__=="__main__":main()
