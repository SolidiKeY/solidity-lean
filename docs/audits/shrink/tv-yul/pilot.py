#!/usr/bin/env python3
"""Reproduce the frozen, signature-preserving NormalControl word pilot inventory.
Prototype Git objects must be available locally; they are deliberately not ancestors
of the audit branch. No Lean runs or benchmark evidence is generated by this script.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path
from inventory import BASE, strip_comments
from family import body_separator

HERE = Path(__file__).resolve().parent
PROTOTYPE = "2aa3a2a21a1e081be5a2a760f91c0d11a084c3e2"
PREFIX = "Solidity/Yul/Compilation/"
NAMES = ["NormalControl", "NormalControlControls", "NormalWordTransport",
         "NormalWordTransportControls", "NormalFramedTransport", "NormalFramedTransportControls"]
DECL = r"^ *(?:(?:private|protected|noncomputable|unsafe) +)*(?:def|abbrev|theorem|lemma|structure|inductive|class|instance|opaque|axiom)\s+([^\s{(:]+)"


def source(commit, path):
    return subprocess.check_output(["git", "show", commit + ":" + path], text=True)


def module(commit, path):
    raw = source(commit, path)
    clean = strip_comments(raw)
    statements = []
    for match in re.finditer(r"^ *(?:private +)?(?:theorem|lemma)\s+([^\s{(:]+)", clean, re.M):
        end = body_separator(clean, match.end())
        scopes = []
        for event in re.finditer(r"^(namespace) +(\S+)|^(end)(?: +\S+)?$", clean[:match.start()], re.M):
            if event.group(1):
                scopes.append(event.group(2))
            else:
                scopes.pop()
        statements.append({"name": ".".join([*scopes, match.group(1)]),
                           "signature": " ".join(raw[match.start():end].split())})
    return {"commit": commit, "path": path, "sha256": hashlib.sha256(raw.encode()).hexdigest(),
            "physical_lines": len(raw.splitlines()),
            "lexical_declarations": len(re.findall(DECL, clean, re.M)),
            "theorems": statements}


def measure():
    before = [module(BASE, PREFIX + name + ".lean") for name in NAMES]
    retained = [m for m in before if not m["path"].endswith("/NormalWordTransport.lean")]
    added = [module(PROTOTYPE, p) for p in ["prototypes/TvYulBlock.lean",
             "prototypes/shadow/" + PREFIX + "NormalWordTransport.lean"]]
    old = {s["name"]: s["signature"] for m in before for s in m["theorems"]}
    facade = added[1]
    for statement in facade["theorems"]:
        assert old[statement["name"]] == statement["signature"], statement["name"]
    def totals(modules):
        return {key: sum(m[key] for m in modules) for key in ["physical_lines", "lexical_declarations"]}
    alternatives = {}
    for name, extra in [("word", ["NormalWordTransport", "NormalWordTransportControls", "NormalFramedTransport", "NormalFramedTransportControls"]),
                        ("numeric", ["NormalNumericTransport", "NormalNumericTransportControls"]),
                        ("stack", ["NormalStackTransport"])]:
        alternatives[name] = totals([module(BASE, PREFIX + n + ".lean")
                                     for n in ["NormalControl", "NormalControlControls", *extra]])
    return {"base": BASE, "prototype_commit": PROTOTYPE,
            "family": "NormalControl word-selector transports and unchanged controls",
            "method": "Physical source lines and lexical declaration headers, not elaborated constants or proof-only lines. Five original modules retained; only NormalWordTransport is shadowed. All prototype tests and facade lines included.",
            "before": {**totals(before), "modules": before},
            "after": {**totals(retained + added), "retained_paths": [m["path"] for m in retained],
                      "prototype": totals(added), "modules_added": added},
            "normal_control_comparison_groups": alternatives,
            "preservation": [{"name": s["name"], "method": "exact-header facade and kernel proof-type equality" if m["path"].endswith("/NormalWordTransport.lean") else "unchanged source recompiled against private facade"}
                             for m in before for s in m["theorems"]],
            "coverage_boundary": "WordControl-selected loop-free Backend.Block, uniform source horizon. Largest of the listed NormalControl selector groups by source lines; no repository-wide maximum or numeric/stack selector-inclusion theorem claimed. Larger ScopedControl has LoopControl leaves outside this domain."}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    actual = measure()
    path = HERE / "pilot.json"
    if args.check:
        assert json.loads(path.read_text()) == actual, "pilot inventory differs"
        print("pilot: PASS; original signatures preserved; before", actual["before"]["physical_lines"],
              "after", actual["after"]["physical_lines"])
    else:
        path.write_text(json.dumps(actual, indent=2) + "\n")


if __name__ == "__main__":
    main()
